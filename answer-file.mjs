// 상황판 — 답 파일 한 벌의 셈. 사용자가 규칙안·설계안에 찍은 답과 코멘트를 누를 때마다 작은 답 파일 하나로 남기고, //
//   같은 자리의 답 파일이 여럿이면 가장 늦은 것을 최종으로 고른다. //
//
// 따르는 설계(관리부 bp-답찍기): //
//   답 파일의 이름 형식 · 칸 · 내놓는 최종 답과 코멘트, 그리고 자리 · 더늦음 · 최종답 · 최종코멘트를 여기서 셈한다. 안 파일에 이미 적혀 있는 답 줄과 코멘트 줄은 //
//     그 자리에 답 파일이 없을 때만 쓴다(doc-mark.mjs 찍힌표시() · 코멘트달린줄들()로 읽는다). //
// ★파일을 읽지도 쓰지도 않는다 — 브라우저(상황판)와 node(AI의 규칙안목록 체크 · 설계실 체크 도구)가 같은 식을 쓰게, 둘 다에 있는 것만 쓴다. //
import { 찍힌표시, 코멘트달린줄들 } from './doc-mark.mjs';

