export const 작업계획목록문서 = 'docs/work.md';
// 규칙 지도(docs/규칙지도.md)도 답 찍기 대상의 파일이다 — 규칙 이름을 안으로 삼아 규칙답을 찍는다(bp-규칙지도) //
export const 규칙문서 = 'docs/규칙지도.md';
