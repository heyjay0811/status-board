// [관리부 작업 545] 규칙안 · 설계안에 찍는 답은 확인 하나다(bp-답찍기). 옛 답 파일의 승인은 확인으로, 취소는 답 없음으로 읽는다 //
export const 답값들 = ['확인', '거둠'];
const 옛답값들 = ['승인', '취소'];
export const 옛표시답값들 = ['체크', '물음', '엑스', '거둠'];   // 옛 작업계획 표시 — 남은 답 파일만 읽는다 //
// 옛 결정할 사항 답(정할것답) — 상황판은 더 짓지 않고, 남은 답 파일을 읽어 전달만 한다(관리부 [작업 548]) //
export const 정할것답값들 = ['Y', 'N', 'A', 'B', '코멘트', '취소', '거둠'];
const 옛정할것답값들 = ['기본', '세컨'];
// [관리부 작업 497] 작업계획 단추 줄에 찍는 답(작업계획답) — ▶️ 진행 · 💬 코멘트 · ❌ 취소 · 거둠(bp-답찍기) //
export const 작업계획단추값들 = ['진행', '코멘트', '취소', '거둠'];
const 칸들 = ['문서', '안', '무엇', '줄', '답', '글', '누른시각'];
// 턴 안 = 「[작업계획 N · M턴]」 · 작업계획 안 = 「[작업계획 N]」 — 보고 머리와 글자까지 같은 형식(bp-답찍기) //
const 턴안형식 = /^\[작업계획 (\d+) · (\d+)턴\]$/;
const 작업계획안형식 = /^\[작업계획 (\d+)\]$/;
export const 턴안 = (작업계획번호, 턴번호) => `[작업계획 ${작업계획번호} · ${턴번호}턴]`;
export const 작업계획안 = (작업계획번호) => `[작업계획 ${작업계획번호}]`;
export function 작업계획안읽기(안) {
  const t = 턴안형식.exec(String(안 ?? ''));
  if (t) return { 작업계획: Number(t[1]), 턴: Number(t[2]) };
  const w = 작업계획안형식.exec(String(안 ?? ''));
  return w ? { 작업계획: Number(w[1]), 턴: null } : null;
}

// 이름 = <누른 시각>-<기기 표지>-<누른 번호>.json — 누른 시각은 세계 표준시 열아홉 글자(20261014T031522123Z), //
//   기기 표지는 영문 소문자와 숫자 여덟 글자, 누른 번호는 여섯 자리다. //
// 한계: 누른 번호는 한 기기에서 999999번까지 · 바꿀 때: 넘으면 기기 표지를 새로 지어 번호를 1부터 다시 센다. //
const 이름꼴 = /^(\d{8}T\d{9}Z)-([a-z0-9]{8})-(\d{6})\.json$/;
const 표지꼴 = /^[a-z0-9]{8}$/;
export const 이름꼴맞음 = (이름) => 이름꼴.test(String(이름 ?? ''));
// 2026-10-14T03:15:22.123Z ↔ 20261014T031522123Z //
const 이름시각 = (iso) => iso.replace(/[-:.]/g, '');
const 시각풀기 = (s) => `${s.slice(0, 4)}-${s.slice(4, 6)}-${s.slice(6, 8)}T${s.slice(9, 11)}:${s.slice(11, 13)}:${s.slice(13, 15)}.${s.slice(15, 18)}Z`;

// 기기 표지 — 상황판이 그 기기에서 처음 켜질 때 한 번 짓는다. AI가 쓰는 표지 ai000000은 짓지 않는다(bp-답찍기) //
export const AI표지 = 'ai000000';
export function 기기표지짓기() {
  const 글자 = 'abcdefghijklmnopqrstuvwxyz0123456789', 수 = new Uint8Array(8);
  let 표지;
  do {
    globalThis.crypto.getRandomValues(수);
    표지 = [...수].map((n) => 글자[n % 글자.length]).join('');
  } while (표지 === AI표지);
  return 표지;
}

// 누른 때(Date 또는 밀리초) · 기기 표지 · 누른 번호 → 답 파일 이름. 틀린 값이면 던진다 //
export function 이름짓기(때, 기기표지, 번호) {
  const d = new Date(때);
  if (Number.isNaN(d.getTime())) throw new Error(`누른 때가 시각이 아니다: ${때}`);
  if (!표지꼴.test(String(기기표지))) throw new Error(`기기 표지가 영문 소문자와 숫자 여덟 글자가 아니다: ${기기표지}`);
  if (!Number.isInteger(번호) || 번호 < 0 || 번호 > 999999) throw new Error(`누른 번호가 0~999999가 아니다: ${번호}`);
  const 이름 = `${이름시각(d.toISOString())}-${기기표지}-${String(번호).padStart(6, '0')}.json`;
  if (!이름꼴맞음(이름)) throw new Error(`답 파일 이름이 꼴에 안 맞는다: ${이름}`);
  return 이름;
}

// 안 제목 — 제목 줄에서 「## 」 뒤부터 첫 「 | 」 앞까지 //
export const 안이름 = (제목줄) => String(제목줄 ?? '').replace(/\r$/, '').replace(/^## /, '').split(' | ')[0];

// 답 파일의 글을 읽어 칸을 잰다 — 맞으면 { 값 }, 칸이 모자라거나 값이 틀리면 { 까닭 }(그 파일은 버린다) //
export function 글읽기(이름, 글) {
  const 틀림 = (까닭) => ({ 까닭: `${이름}: ${까닭}` });
  const m = 이름꼴.exec(String(이름 ?? ''));
  if (!m) return 틀림('이름이 <누른 시각>-<기기 표지>-<누른 번호>.json 형식이 아니다');
  let v;
  try { v = JSON.parse(글); } catch (e) { console.log(`[답 파일] ERROR ${이름}: JSON으로 못 읽었다 — ${e.message}`); return 틀림(`JSON이 아니다 — ${e.message}`); }
  if (!v || typeof v !== 'object' || Array.isArray(v)) return 틀림('JSON 덩어리가 아니다');
  const 빠짐 = 칸들.filter((k) => typeof v[k] !== 'string');
  if (빠짐.length) return 틀림(`칸이 없거나 글이 아니다 — ${빠짐.join(' · ')}`);
  if (!안파일들.includes(v.문서)) return 틀림(`문서 칸이 ${안파일들.join(' · ')} 가운데 하나가 아니다(${v.문서})`);
  if (!v.안 || v.안.includes(' | ') || /[\r\n]/.test(v.안)) return 틀림(`안 칸이 제목 하나가 아니다(${v.안})`);
  const 작업계획목록 = v.문서 === 작업계획목록문서;
  const 가리킴 = 작업계획목록 ? 작업계획안읽기(v.안) : null;
  if (작업계획목록 && !가리킴) return 틀림(`작업계획 목록의 안 칸이 [작업계획 N] · [작업계획 N · M턴] 형식이 아니다(${v.안})`);
  if ((v.문서 === 규칙문서) !== (v.무엇 === '규칙답')) return 틀림(`규칙답은 ${규칙문서}에만 찍고, 그 문서에는 규칙답만 찍는다`);
  if (v.무엇 === '규칙답') {
    if (v.줄 !== '') return 틀림('규칙답의 줄 칸은 빈 값이어야 한다');
    if (!규칙답값들.includes(v.답)) return 틀림(`규칙답의 답 칸이 ${규칙답값들.join(' · ')} 가운데 하나가 아니다(${v.답})`);
  } else if (v.무엇 === '턴답') {
    if (!작업계획목록 || 가리킴.턴 == null) return 틀림('턴답은 docs/work.md의 [작업계획 N · M턴]에만 찍는다');
    if (v.줄 !== '' || v.답 !== '') return 틀림('턴답의 줄 · 답 칸은 빈 값이어야 한다');
    if (!Array.isArray(v.고른것) || !v.고른것.length) return 틀림('턴답의 고른것 칸이 비었거나 목록이 아니다');
    for (const g of v.고른것) {
      if (!g || typeof g.이름표 !== 'string' || !g.이름표 || typeof g.옵션 !== 'string' || typeof g.글 !== 'string') return 틀림('고른것의 한 칸이 { 이름표, 옵션, 글 } 형식이 아니다');
      if (!g.옵션 && !g.글) return 틀림(`고른것 「${g.이름표}」에 옵션도 글도 없다`);
    }
  } else if (v.무엇 === '정할것답') {
    if (!작업계획목록 || 가리킴.턴 != null) return 틀림('정할것답은 docs/work.md의 [작업계획 N]에만 찍는다');
    if (!v.줄) return 틀림('정할것답의 줄 칸(결정할 사항의 이름표)이 비었다');
    if (!정할것답값들.includes(v.답) && !옛정할것답값들.includes(v.답)) return 틀림(`정할것답의 답 칸이 ${정할것답값들.join(' · ')} 가운데 하나가 아니다(${v.답})`);
  } else if (v.무엇 === '작업계획답') {
    if (!작업계획목록 || 가리킴.턴 != null) return 틀림('작업계획답은 docs/work.md의 [작업계획 N]에만 찍는다');
    if (v.줄 !== '') return 틀림('작업계획답의 줄 칸은 빈 값이어야 한다');
    if (!작업계획단추값들.includes(v.답)) return 틀림(`작업계획답의 답 칸이 ${작업계획단추값들.join(' · ')} 가운데 하나가 아니다(${v.답})`);
  } else if (v.무엇 === '답') {
    if (작업계획목록 && 가리킴.턴 != null) return 틀림('턴에는 답이 아니라 턴답을 찍는다');
    const 값들 = 작업계획목록 ? 옛표시답값들 : [...답값들, ...옛답값들];
    if (!값들.includes(v.답)) return 틀림(`답 칸이 ${값들.join(' · ')} 가운데 하나가 아니다(${v.답})`);
    if (v.줄 !== '') return 틀림('답의 줄 칸은 빈 값이어야 한다');
  } else if (v.무엇 === '코멘트') {
    if (!v.줄) return 틀림('코멘트의 줄 칸이 비었다');
    if (작업계획목록) return 틀림('작업계획 목록에는 코멘트를 따로 남기지 않는다 — 작업계획 단추의 💬 코멘트(작업계획답)로 보낸다(bp-답찍기)');
    if (v.답 !== '') return 틀림('코멘트의 답 칸은 빈 값이어야 한다');
  } else return 틀림(`무엇 칸이 답 · 코멘트 · 정할것답 · 작업계획답 · 턴답이 아니다(${v.무엇})`);
  if (v.누른시각 !== 시각풀기(m[1])) return 틀림(`누른시각 칸(${v.누른시각})이 이름의 누른 시각과 다르다`);
  const 값 = {};
  for (const k of 칸들) 값[k] = v[k];
  if (v.무엇 === '턴답') 값.고른것 = v.고른것.map((g) => ({ 이름표: g.이름표, 옵션: g.옵션, 글: g.글 }));
  return { 값 };
}

// 답 파일의 글을 짓는다 — 누른시각은 이름에서 받는다. 지은 글이 글읽기()를 못 지나면 던진다(틀린 파일을 보내지 않는다) //
// [관리부 작업 487] 작업의 답(표시)은 그 표시와 함께 보낸 글을, 턴답은 고른것과 그 턴의 코멘트 글을 담는다(bp-답찍기) //
export function 글짓기(이름, { 문서, 안, 무엇, 줄 = '', 답 = '', 글 = '', 고른것 = undefined }) {
  const m = 이름꼴.exec(String(이름 ?? ''));
  if (!m) throw new Error(`답 파일 이름이 꼴에 안 맞는다: ${이름}`);
  const 글담음 = 무엇 === '코멘트' || 무엇 === '턴답' || 무엇 === '정할것답' || 무엇 === '작업계획답' || 무엇 === '규칙답' || (무엇 === '답' && 문서 === 작업계획목록문서);
  const 값 = { 문서, 안, 무엇, 줄: 무엇 === '코멘트' || 무엇 === '정할것답' ? 줄 : '', 답: 무엇 === '답' || 무엇 === '정할것답' || 무엇 === '작업계획답' || 무엇 === '규칙답' ? 답 : '', 글: 글담음 ? 글 : '', 누른시각: 시각풀기(m[1]) };
  if (무엇 === '턴답') 값.고른것 = 고른것;
  const 지은 = JSON.stringify(값, null, 2) + '\n';
  const r = 글읽기(이름, 지은);
  if (!r.값) throw new Error(`답 파일을 못 지었다 — ${r.까닭}`);
  return 지은;
}

// 자리 = 문서 · 안 · 무엇 · (무엇이 코멘트면 줄) — 같은 자리의 답 파일 가운데 가장 늦은 것이 최종이다 //
export const 자리 = (값) => [값.문서, 값.안, 값.무엇, 값.무엇 === '코멘트' || 값.무엇 === '정할것답' ? 값.줄 : ''].join('\n');
// 더늦음(가, 나) = 가의 파일 이름 > 나의 파일 이름(글자 차례) //
export const 더늦음 = (가, 나) => String(가) > String(나);
// 그 자리의 가장 늦은 답 파일 — 답파일들 = [{ 이름, 값 }]. 없으면 null //
function 가장늦은(답파일들, 자리값) {
  let 늦은 = null;
  for (const f of 답파일들 || []) if (자리(f.값) === 자리값 && (!늦은 || 더늦음(f.이름, 늦은.이름))) 늦은 = f;
  return 늦은;
}

// 안 파일에서 그 안의 제목 줄 — 「## 」로 시작하고 제목이 안과 글자까지 같은 줄. 없으면 null //
export function 안줄찾기(안파일글, 안) {
  for (const l of String(안파일글 ?? '').split('\n')) {
    const 줄 = l.replace(/\r$/, '');
    if (줄.startsWith('## ') && 안이름(줄) === 안) return 줄;
  }
  return null;
}

// 최종답(안) = 그 안의 답 자리에 답 파일이 있으면 가장 늦은 답 파일의 답(거둠이면 답 없음), 없으면 안 파일에서 그 안 제목 줄 아래의 답 줄 //
//   (없으면 답 없음). 돌려주는 것: '확인' · '없음' — 옛 승인은 확인, 옛 취소는 없음. 제목 줄(안줄)을 넘기면 안 파일에서 다시 찾지 않는다 //
const 확인으로 = (답) => (답 === '확인' || 답 === '승인' ? '확인' : '없음');
export function 최종답(안파일글, 문서, 안, 답파일들, 안줄 = undefined) {
  const 늦은 = 가장늦은(답파일들, 자리({ 문서, 안, 무엇: '답' }));
  if (늦은) return 확인으로(늦은.값.답);
  const 줄 = 안줄 === undefined ? 안줄찾기(안파일글, 안) : 안줄;
  if (!줄) return '없음';
  return 확인으로(찍힌표시(안파일글, 줄));
}

// [관리부 작업 545] 승인됨(묶음) = 묶음의 모든 안의 최종답이 확인이고, 어느 안의 어느 줄에도 최종코멘트가 없음(bp-답찍기). //
//   받는 것: [{ 표시(최종답 · 없으면 ''), 코멘트({ 줄: 글 }) }]. 빈 묶음은 승인이 아니다 //
export const 승인됨 = (안들) => !!(안들 || []).length && 안들.every((it) => it.표시 === '확인' && !Object.keys(it.코멘트 || {}).length);

// [관리부 작업 497] 최종작업계획답([작업계획 N]) = 그 작업계획의 작업계획답 자리에 답 파일이 있으면 가장 늦은 답 파일의 답과 글(거둠이면 답 없음), //
//   없으면 답 없음(bp-답찍기). 돌려주는 것: { 답: 진행 · 코멘트 · 취소 · 없음, 글 } //
export function 최종작업계획답(답파일들, 안, 문서 = 작업계획목록문서) {
  const 늦은 = 가장늦은(답파일들, 자리({ 문서, 안, 무엇: '작업계획답' }));
  if (!늦은 || 늦은.값.답 === '거둠') return { 답: '없음', 글: '' };
  return { 답: 늦은.값.답, 글: 늦은.값.글 || '' };
}

// 최종규칙답(규칙 이름) = 그 규칙의 규칙답 자리에 답 파일이 있으면 가장 늦은 답 파일의 답과 글(거둠이면 답 없음), 없으면 답 없음(bp-규칙지도) //
export function 최종규칙답(답파일들, 안) {
  const 늦은 = 가장늦은(답파일들, 자리({ 문서: 규칙문서, 안, 무엇: '규칙답' }));
  if (!늦은 || 늦은.값.답 === '거둠') return { 답: '없음', 글: '' };
  return { 답: 늦은.값.답, 글: 늦은.값.글 || '' };
}

// 최종코멘트(안, 줄) = 그 줄의 코멘트 자리에 답 파일이 있으면 가장 늦은 답 파일의 글(빈 글이면 코멘트 없음), //
//   없으면 안 파일에서 그 줄에 단 코멘트 줄. 그 안의 모든 줄을 한 번에 돌려준다 — { 줄: 글 }(코멘트 없는 줄은 들지 않는다) //
export function 최종코멘트(안파일글, 문서, 안, 답파일들, 안줄 = undefined) {
  const 결과 = {};
  const 줄 = 안줄 === undefined ? 안줄찾기(안파일글, 안) : 안줄;
  if (줄) {
    // 코멘트 줄 모양: 「> 💬 **줄** | 날짜 | 글」 — 옛 「 · 」도 읽는다(bill-parse.mjs 규칙안읽기()와 같은 자) //
    for (const l of 코멘트달린줄들(안파일글, 줄)) {
      const 조각 = l.slice(4).trim().split(/ [·|] /);
      const 키 = String(조각[0] || '').split('**').join('').trim();
      if (키) 결과[키] = 조각.slice(2).join(' | ').trim();
    }
  }
  const 줄들 = new Set((답파일들 || []).filter((f) => f.값.무엇 === '코멘트' && f.값.문서 === 문서 && f.값.안 === 안).map((f) => f.값.줄));
  for (const 키 of 줄들) {
    const 늦은 = 가장늦은(답파일들, 자리({ 문서, 안, 무엇: '코멘트', 줄: 키 }));
    if (늦은.값.글) 결과[키] = 늦은.값.글; else delete 결과[키];
  }
  return 결과;
}
