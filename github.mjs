//                   못 적으면 다시 읽거나 다시 적지 않고 까닭을 담아 던지고(끝내 못 닿음이면 끝내 표지를 붙인다 — //
//                   [관리부 작업 464] bp-결재 제3조 ⑧), 문서의 마지막 커밋 시각을 알려 준다. //
