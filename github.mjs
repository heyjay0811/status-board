export const 끝내오류 = (말) => Object.assign(new Error(말), { 끝내: true });
export const 끝내못닿음 = (e) => !!(e && e.끝내);
// 바꾸기를 부르고, 던지면 끝내 표지를 붙여 다시 던진다 //
export function 끝내로바꾸기(바꾸기, 글) {
  try { return 바꾸기(글); }
  catch (e) { if (e && typeof e === 'object') { e.끝내 = true; throw e; } throw 끝내오류(String(e)); }
}

// 기기에 남기는 답 하나(전달 기록) — { 번, 저장소, 경로, 문서, 표식(그 안의 제목 줄), 무엇('답'|'코멘트'), 답, 키(코멘트 줄), 글, 날짜, //
//   메시지, 이름(안 이름), 곳(어느 곳 — 「의회」·「설계실 · 곳 이름」), 처음(처음 누를 때 화면이 읽은 원본의 그 자리), 거친([이 자리에 먼저 //
//   닿은 이 기기의 누름이 원본에 남긴 자리 값]) }. 번은 누를 때마다 새로 받는 번호다(보내는 사이 갈아 끼워졌는지 가린다). //
// 같은 조 ⑫ — 자리 = 저장소 · 경로 · 그 안의 제목 줄 · (답이면 답 줄, 코멘트면 코멘트를 단 줄)마다 하나만 둔다. //
export const 전달자리 = (a) => `${a.저장소}/${a.경로}\n${a.표식}\n${a.무엇 === '답' ? '답' : '코멘트:' + a.키}`;
export const 전달파일 = (a) => `${a.저장소}/${a.경로}`;
// 그 자리의 지금 값 — 답이면 찍힌 답(승인·취소·빈 값), 코멘트면 그 줄에 달린 코멘트 글(없으면 빈 값). 제목 줄이 없으면 던진다 //
export function 자리값(글, a) {
  if (a.무엇 === '답') return 찍힌표시(글, a.표식);
  const 머리 = `${코멘트앞머리} **${a.키}** | `;
  const 줄 = 코멘트달린줄들(글, a.표식).find((l) => l.startsWith(머리));
  if (!줄) return '';
  const 뒤 = 줄.slice(머리.length), i = 뒤.indexOf(' | ');   // 「날짜 | 글」 //
  return i < 0 ? '' : 뒤.slice(i + 3);
}
// 기록 하나를 글에 얹는다 — 맞대지 않고 그 답이나 코멘트만 붙인다(화면이 원본 위에 기기에 남은 답을 얹어 그릴 때 · 보낼 때) //
export const 전달얹기 = (글, a) => (a.무엇 === '답' ? 표시붙인글(글, a.표식, a.답, a.날짜, a.문서) : 코멘트붙인글(글, a.표식, a.키, a.글, a.날짜));
// 보낼 때의 바꾸기 — 원본을 새로 읽은 글(지금) 위에: //
//   원본의 그 자리가 이미 그 답대로면 지금 글 그대로(「바뀐 것 없음」 — 닿은 것으로 친다) · //
//   그 자리가 처음 누를 때 읽은 값과도, 이 기기가 먼저 닿게 한 값(거친)과도 다르면 끝내 못 닿음으로 던진다 · 아니면 얹은 글. //
// ★거친 — 같은 자리를 승인하고 그 승인이 닿기 전에 거두면, 승인이 먼저 원본에 닿은 뒤 거둠을 보낼 때 원본의 그 자리(승인)가 처음 값(빈 값)과 //
//   다르다. 그 승인은 이 기기가 적은 것이지 「그사이 다른 답」이 아니라서, 먼저 닿은 누름의 값을 거친에 두고 다른 답으로 치지 않는다. //
export const 전달바꾸기만들기 = (a) => (지금) => {
  const 지금값 = 자리값(지금, a);
  const 새글 = 전달얹기(지금, a);
  if (자리값(새글, a) === 지금값) return 지금;
  const 알던 = [a.처음, ...(a.거친 || [])];
  if (a.처음 !== null && a.처음 !== undefined && !알던.includes(지금값)) {
    const 무엇 = a.무엇 === '답' ? '답' : `${a.키} 코멘트`;
    throw 끝내오류(`그사이 원본의 그 안에 다른 ${무엇}이 찍혀 있다(${지금값 || '없음'}) — 옛 누름으로 덮지 않았다`);
  }
  return 새글;
};
// 누름 하나를 기록 목록에 넣는다 — 같은 자리의 기록이 있으면 마지막 누름으로 갈아 끼우되 처음 값과 거친 값은 그대로 두고, //
//   없으면 원문(처음 누를 때 화면이 읽은 원본)에서 그 자리 값을 재어 처음으로 두고 끝에 붙인다. 새 목록을 돌려준다. //
export function 전달넣기(목록, a, 원문) {
  const 자리 = 전달자리(a), i = 목록.findIndex((x) => 전달자리(x) === 자리);
  if (i >= 0) { const 새 = 목록.slice(); 새[i] = { ...a, 처음: 목록[i].처음, 거친: 목록[i].거친 || [] }; return 새; }
  let 처음 = null;
  if (원문 !== undefined && 원문 !== null) { try { 처음 = 자리값(원문, a); } catch (e) { console.error(`[전달] 처음 값을 못 쟀다 — 빈 값으로 둔다: ${e.message}`); 처음 = null; } }
  return [...목록, { ...a, 처음, 거친: [] }];
}
// 보낸 기록이 닿았을 때 — 그 자리 기록이 보낸 그대로(번이 같음)면 지우고, 그사이 갈아 끼워졌으면 지우지 않고 //
//   닿은 값을 거친에 더한다(다음 보냄이 그 값을 다른 답으로 치지 않게). 새 목록을 돌려준다. //
export function 전달닿음(목록, 보낸, 닿은값) {
  const 자리 = 전달자리(보낸);
  return 목록.flatMap((x) => {
    if (전달자리(x) !== 자리) return [x];
    if (x.번 === 보낸.번) return [];
    return [{ ...x, 거친: [...new Set([...(x.거친 || []), 닿은값])] }];
  });
}
// 끝내 못 닿은 기록을 지운다 — 보낸 그대로일 때만(그사이 갈아 끼워진 새 누름은 남겨 이어 보낸다) //
export const 전달버림 = (목록, 보낸) => 목록.filter((x) => !(전달자리(x) === 전달자리(보낸) && x.번 === 보낸.번));
// 파일마다 다음에 보낼 기록 — 목록 차례에서 그 파일의 첫 기록 //
export const 다음보낼것 = (목록, 파일) => 목록.find((x) => 전달파일(x) === 파일) || null;

// 통로 하나를 만든다. 열쇠가 없으면 공개 저장소만 읽힌다. //
// API는 시험 때만 바꾼다 — 시험 서버(`dev-server.mjs`)가 GitHub과 같은 모양으로 임시 사본을 읽고 쓴다. //
export function 통로만들기({ 열쇠 = '', 주인 = 'heyjay0811', API = 진짜API, fetch: 부르기 = globalThis.fetch?.bind(globalThis), 기록 = console } = {}) {
  if (typeof 부르기 !== 'function') throw new Error('fetch가 없는 곳이다 — 이 통로를 쓸 수 없다');

  async function 요청(방법, 주소, 몸, 덧머리) {
    const 머리 = { Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28', ...(덧머리 || {}) };
    if (열쇠) 머리.Authorization = `Bearer ${열쇠}`;
    if (몸) 머리['Content-Type'] = 'application/json';
    const r = await 부르기(API + 주소, { method: 방법, headers: 머리, body: 몸 ? JSON.stringify(몸) : undefined, cache: 'no-store' });
    const 글 = await r.text();
    let 값 = null;
    // GitHub은 보통 JSON을 주지만 오류 쪽은 글 그대로 올 때가 있다 — 그때는 글을 값으로 두고 남긴다 //
    try { 값 = 글 ? JSON.parse(글) : null; } catch (e) { 기록.log(`[GitHub 통로] 응답이 JSON이 아니다(${r.status}) — 글 그대로 쓴다: ${e.message}`); 값 = 글; }
    return { 상태: r.status, 값, 지문: r.headers && r.headers.get ? r.headers.get('etag') : null };
  }
  const 실패 = (무엇, r) => new Error(`${무엇} — GitHub 응답 ${r.상태}${r.값 && r.값.message ? ': ' + r.값.message : ''}`);

  // 파일 하나를 읽는다. 없으면 null, 못 읽으면 던진다. //
  // [관리부 작업 422] 제1조 ⑦([확정 19]) — 지난번 받은 지문(ETag)을 넘기면 「이 지문과 같으면 보내지 마라」(If-None-Match)로 //
  //   묻는다. 안 바뀌었으면 GitHub이 304만 보내고 { 안바뀜: true }를, 바뀌었으면 새 글과 새 지문을 돌려준다. //
  async function 파일읽기(저장소, 경로, 지문 = null) {
    기록.log(`[GitHub 통로] START 파일읽기 — ${저장소}/${경로}${지문 ? ' (지문으로 묻기)' : ''}`);
    const r = await 요청('GET', `/repos/${주인}/${저장소}/contents/${경로감싸기(경로)}`, null, 지문 ? { 'If-None-Match': 지문 } : null);
    if (r.상태 === 304) { 기록.log(`[GitHub 통로] SUCCESS 안 바뀜 — ${저장소}/${경로}`); return { 안바뀜: true, 지문 }; }
    if (r.상태 === 404) { 기록.log(`[GitHub 통로] SUCCESS 파일 없음 — ${저장소}/${경로}`); return null; }
    if (r.상태 !== 200 || !r.값 || r.값.type !== 'file') throw 실패(`파일을 못 읽었다: ${저장소}/${경로}`, r);
    const 글 = b64를글(r.값.content);
    기록.log(`[GitHub 통로] SUCCESS 파일읽기 — ${저장소}/${경로} ${글.length}자`);
    return { 글, sha: r.값.sha, 지문: r.지문 };
  }

  // 저장소의 파일 경로 전부 — 설계실·의회·작업 문서를 이름을 코드에 적지 않고 이 목록에서 찾는다(제1조 ④). //
  // [관리부 작업 457] 커밋을 넘기면 그 커밋의 파일 목록을 받는다 — 곳목록확인()이 물은 마지막 커밋과 받은 목록이 늘 짝이 맞게. //
  async function 파일목록(저장소, 커밋 = 'HEAD') {
    기록.log(`[GitHub 통로] START 파일목록 — ${저장소} @ ${String(커밋).slice(0, 7)}`);
    const r = await 요청('GET', `/repos/${주인}/${저장소}/git/trees/${encodeURIComponent(커밋)}?recursive=1`);
    if (r.상태 !== 200 || !r.값 || !Array.isArray(r.값.tree)) throw 실패(`파일 목록을 못 읽었다: ${저장소}`, r);
    if (r.값.truncated) 기록.log(`[GitHub 통로] ERROR 파일 목록이 잘렸다 — ${저장소}: GitHub이 한 번에 주는 수를 넘었다`);
    return r.값.tree.filter((t) => t.type === 'blob').map((t) => t.path);
  }

  // 열쇠 주인의 저장소 이름 전부 — 한 번 묻는다. 못 읽으면 던진다(제7조 ②). //
  // 한계: 저장소 100개까지 한 번에 받는다 · 바꿀 때: 저장소가 100개를 넘으면 한 쪽씩 받아 이어 붙인다. //
  async function 저장소목록() {
    기록.log('[GitHub 통로] START 저장소목록');
    const r = await 요청('GET', '/user/repos?per_page=100&affiliation=owner');
    if (r.상태 !== 200 || !Array.isArray(r.값)) throw 실패('저장소 목록을 못 읽었다(열쇠가 맞는지 확인한다)', r);
    return r.값.map((x) => x.name);
  }

  // 저장소의 마지막 커밋 번호(sha) 하나 — GitHub의 파일은 커밋으로만 바뀌어, 이 번호가 같으면 파일 목록도 같다. //
  async function 저장소커밋(저장소) {
    기록.log(`[GitHub 통로] START 저장소커밋 — ${저장소}`);
    const r = await 요청('GET', `/repos/${주인}/${저장소}/commits?per_page=1`);
    // 커밋이 하나도 없는 빈 저장소는 GitHub이 409로 답한다 — 파일이 없어 부서·프로젝트가 아니니 「없음」(null)으로 돌려준다 //
    if (r.상태 === 409) { 기록.log(`[GitHub 통로] SUCCESS 빈 저장소(커밋 없음) — ${저장소}`); return null; }
    if (r.상태 !== 200 || !Array.isArray(r.값) || !r.값[0] || !r.값[0].sha) throw 실패(`마지막 커밋을 못 읽었다: ${저장소}`, r);
    return r.값[0].sha;
  }

  // [관리부 작업 457] bp-백엔드 「상황판은 원본에서 그때그때 읽은 문서로 화면을 그린다」 조 ⑤ — 모바일 앱이 열 때마다 부른다. //
  //   저장소 목록을 한 번 묻고, 곳마다 마지막 커밋을 물어 //
  //   목록다시받기(곳) = (기기에 저장한 그 곳의 파일 목록 없음) OR (지금 마지막 커밋 ≠ 그 곳 파일 목록을 받을 때 저장한 마지막 커밋)이 //
  //   참인 곳만 그 커밋의 파일 목록을 다시 받는다. 저장소 목록에 새로 생긴 저장소는 파일 목록을 받아 `.claude` 폴더가 있으면 //
  //   부서·프로젝트로 센다(제1조 ⑤). 이미 부서·프로젝트가 아니라고 가른 저장소는 다시 묻지 않는다. //
  // 받는 것: 알던 = { 저장소 이름: { 커밋, 곳 } } — 부르는 쪽이 기기에 저장한 것(곳이면 그 곳의 파일 목록이 기기에 있을 때만 넣는다) · //
  //   모두다시 — 참이면(「↻ 다시 읽기」) 커밋이 같아도 모든 저장소의 파일 목록을 받는다. //
  // 돌려주는 것: 저장소마다 { 이름, 곳, 커밋, 목록(새로 받았을 때) | 그대로: true | 오류(까닭) }. //
  // ★한 곳을 못 읽어도 던지지 않고 그 곳에 까닭을 단다 — 부르는 쪽이 그 곳만 「못 맞춘 곳」으로 알리고 저장해 둔 목록으로 그린다(조 ⑧). //
  //   저장소 목록 자체를 못 읽으면 던진다. //
  // ★저장소마다 동시에 묻는다([작업 395]) — 한 곳씩 차례로 받으면 17곳에 5.7초, 한꺼번에 0.6초였다(2026-09-30 실제 GitHub). //
  // 한계: 저장소 100개까지 요청을 한꺼번에 보낸다 · 바꿀 때: 저장소가 100개를 넘으면 몇십 개씩 끊어 보낸다. //
  async function 곳목록확인(알던 = {}, { 모두다시 = false } = {}) {
    const 이름들 = await 저장소목록();
    const 결과 = await Promise.all(이름들.map(async (이름) => {
      const 옛 = 알던[이름];
      if (옛 && 옛.곳 === false && !모두다시) return { 이름, 곳: false, 커밋: 옛.커밋, 그대로: true };
      try {
        const 커밋 = await 저장소커밋(이름);
        if (커밋 === null) return { 이름, 곳: false, 커밋: null, 목록: [] };
        if (옛 && 옛.곳 && !모두다시 && 옛.커밋 === 커밋) return { 이름, 곳: true, 커밋, 그대로: true };
        const 목록 = await 파일목록(이름, 커밋);
        return { 이름, 곳: 목록.some((p) => p.startsWith('.claude/')), 커밋, 목록 };
      } catch (e) {
        기록.log(`[GitHub 통로] ERROR 곳목록확인 — ${이름}: ${e.message}`);
        return { 이름, 곳: 옛 ? 옛.곳 : null, 오류: e.message };
      }
    }));
    const 셈 = (f) => 결과.filter(f).length;
    기록.log(`[GitHub 통로] SUCCESS 곳목록확인 — 저장소 ${결과.length}곳 · 부서·프로젝트 ${셈((x) => x.곳)}곳 · 목록 새로 받음 ${셈((x) => x.목록)} · 그대로 ${셈((x) => x.그대로)} · 못 읽음 ${셈((x) => x.오류)}`);
    return 결과;
  }

  // 그 파일의 마지막 커밋 시각(UTC 글자) — 화면 맨 위에 보인다(제10조 ⑤). 커밋이 없으면 null. //
  async function 마지막커밋(저장소, 경로) {
    const r = await 요청('GET', `/repos/${주인}/${저장소}/commits?per_page=1&path=${encodeURIComponent(경로)}`);
    if (r.상태 !== 200 || !Array.isArray(r.값)) throw 실패(`마지막 커밋을 못 읽었다: ${저장소}/${경로}`, r);
    return r.값[0] ? r.값[0].commit.committer.date : null;
  }

  // 파일을 한 번 읽어 바꾸기(옛 글 → 새 글)를 적용하고 커밋 하나로 한 번만 적는다(제10조 ③⑥). //
  // ★못 적으면 여기서 다시 읽거나 다시 적지 않고 까닭을 담아 던진다 — 다시 보낼지는 부르는 쪽(app.mjs 보내기 줄)이 //
  //   끝내 표지로 가른다([관리부 작업 464] bp-결재 「찍은 답을 원본까지 전달하기와 「전달 안 됨」 딱지」 조 ⑧). //
  //   끝내 표지 — 적어도됨 거짓 · 파일 없음 · 바꾸기가 던짐(제목 줄 없음 · 항 없음 · 찍을 수 없는 답 · 그사이 다른 답). //
  //   그사이 파일이 바뀌어 GitHub이 막아도(409·422 — 들고 간 sha가 옛것) 옛 글 위에 쓴 것은 올라가지 않아, //
  //   그사이 바뀐 글은 GitHub에 그대로 남는다 — 이것은 일시 실패라 다음에 새로 읽어 다시 보낸다. //
  //   곳들 — 부서·프로젝트 저장소 이름들(적어도됨()이 설계실 파일을 가린다) //
  async function 고쳐쓰기(저장소, 경로, 바꾸기, 메시지, 곳들 = []) {
    기록.log(`[GitHub 통로] START 고쳐쓰기 — ${저장소}/${경로}: ${메시지}`);
    if (!적어도됨(저장소, 경로, 곳들)) {
      기록.log(`[GitHub 통로] ERROR 적지 않는다 — 상황판이 적어도 되는 파일이 아니다: ${저장소}/${경로}`);
      throw 끝내오류(못적는까닭(저장소, 경로));
    }
    const 지금 = await 파일읽기(저장소, 경로);
    if (!지금) throw 끝내오류(`고쳐 쓸 파일이 GitHub에 없다: ${저장소}/${경로}`);
    const 새글 = 끝내로바꾸기(바꾸기, 지금.글);
    if (새글 === 지금.글) { 기록.log(`[GitHub 통로] SUCCESS 바뀐 것 없음 — 커밋하지 않았다`); return { 커밋: null, 바뀜: false }; }
    const r = await 요청('PUT', `/repos/${주인}/${저장소}/contents/${경로감싸기(경로)}`,
      { message: 메시지, content: 글을b64(새글), sha: 지금.sha });
    if (r.상태 === 200 || r.상태 === 201) {
      기록.log(`[GitHub 통로] SUCCESS 커밋 ${r.값.commit.sha.slice(0, 7)} — ${저장소}/${경로}`);
      // 커밋 응답에 적은 글의 새 지문과 커밋 시각이 들어 있다 — 부른 쪽이 파일을 다시 읽지 않아도 된다 //
      return { 커밋: r.값.commit.sha, 바뀜: true, 글: 새글, sha: r.값.content && r.값.content.sha, 시각: r.값.commit.committer && r.값.commit.committer.date };
    }
    if (r.상태 === 409 || r.상태 === 422) {
      기록.log(`[GitHub 통로] ERROR 그사이 파일이 바뀌어 GitHub이 막았다(${r.상태}) — 다시 적지 않는다: ${저장소}/${경로}`);
      throw 실패(`그사이 파일이 바뀌어 GitHub이 막았다: ${저장소}/${경로}`, r);
    }
    기록.log(`[GitHub 통로] ERROR 커밋하지 못했다(${r.상태}) — ${저장소}/${경로}`);
    throw 실패(`커밋하지 못했다: ${저장소}/${경로}`, r);
  }

  return { 파일읽기, 파일목록, 저장소목록, 저장소커밋, 곳목록확인, 마지막커밋, 고쳐쓰기 };
}
