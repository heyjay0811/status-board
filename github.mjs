// ★PC 앱과 모바일 앱이 이 한 벌을 쓴다 — 브라우저와 Node에 다 있는 fetch·TextEncoder·btoa만 쓴다. //
// ★열쇠는 부르는 쪽이 넘긴다 — 이 부품은 열쇠를 어디에도 적지 않는다(제10조 ②: 열쇠는 그 기기 안에만). //

import { 찍힌표시, 코멘트달린줄들, 코멘트앞머리, 표시붙인글, 코멘트붙인글 } from './doc-mark.mjs';

