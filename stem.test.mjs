// 열린 것의 줄기 셈 `stem.mjs`의 시험 — 누름·✕·곳 접힘·이전 버튼마다 줄기와 기록 수를 본다. //
// 따르는 설계: bp-프론트엔드 「열린 것의 줄기와 폰의 이전 버튼」 조 ①~⑥. //
import { 빈줄기, 줄기깊이, 바깥열기, 안열기, 접기, 바깥누름, 안누름, 끝접기, 깊이까지접기, 기록차이 } from './stem.mjs';

let 통과 = 0, 실패 = 0;
const 확인 = (이름, 조건, 실제) => {
  if (조건) { 통과++; console.log(`  ✅ ${이름}`); }
  else { 실패++; console.log(`  ❌ ${이름}\n     실제: ${JSON.stringify(실제)}`); }
};
const 같다 = (j, 바깥, 안) => j.바깥 === 바깥 && j.안 === 안;

console.log('① 줄기 깊이');
확인('빈 줄기는 0', 줄기깊이(빈줄기) === 0, 줄기깊이(빈줄기));
확인('바깥만 1', 줄기깊이({ 바깥: 'A', 안: null }) === 1);
확인('바깥과 안 2', 줄기깊이({ 바깥: 'A', 안: 'A#1' }) === 2);

console.log('② 같은 단계 바꾸기');
let j = 바깥누름(빈줄기, 'A');
j = 안누름(j, 'A', 'A#0');
j = 바깥누름(j, 'B');
확인('카드 A·조를 연 채 카드 B를 누르면 A와 그 조가 접히고 B만 열림', 같다(j, 'B', null), j);
j = 안누름(j, 'B', 'B#0');
j = 안누름(j, 'B', 'B#1');
확인('조 둘을 차례로 누르면 뒤의 것만 열림', 같다(j, 'B', 'B#1'), j);
확인('같은 단계 바꾸기는 기록을 더 쌓지 않음(2 → 2)', 기록차이(2, j) === 0, 기록차이(2, j));
확인('바깥 바꾸기로 안이 접히면 한 자리 걷음(2 → 1)', 기록차이(2, 바깥누름(j, 'C')) === -1);

console.log('③ 다시 누름 · ✕');
확인('열린 바깥을 다시 누르면 안과 함께 접힘', 같다(바깥누름({ 바깥: 'A', 안: 'A#0' }, 'A'), null, null));
확인('열린 안을 다시 누르면 안만 접힘', 같다(안누름({ 바깥: 'A', 안: 'A#0' }, 'A', 'A#0'), 'A', null));
확인('✕(바깥 접기)는 안과 함께 접고 두 자리 걷음', 기록차이(2, 접기({ 바깥: 'A', 안: 'A#0' }, 'A')) === -2);
확인('줄기에 없는 것을 접으면 그대로', 같다(접기({ 바깥: 'A', 안: null }, 'Z'), 'A', null));

console.log('여는 toggle이 다시 와도 그대로');
const k = { 바깥: 'A', 안: 'A#0' };
확인('열린 바깥을 다시 열면 안이 남음', 바깥열기(k, 'A') === k);
확인('열린 안을 다시 열면 그대로', 안열기(k, 'A', 'A#0') === k);

console.log('④ 이전 버튼');
확인('조 → 카드 차례: 첫 뒤로는 조만', 같다(끝접기(k), 'A', null));
확인('둘째 뒤로는 카드', 같다(끝접기(끝접기(k)), null, null));
확인('빈 줄기에서 뒤로는 빈 줄기', 같다(끝접기(빈줄기), null, null));
확인('기록이 0 단계로 줄면 줄기를 다 접음', 같다(깊이까지접기(k, 0), null, null));
확인('기록이 1 단계로 줄면 안만 접음', 같다(깊이까지접기(k, 1), 'A', null));

console.log('⑤ 기록 수');
확인('빈 줄기에서 박스를 열면 한 자리 쌓음', 기록차이(0, 바깥누름(빈줄기, '작업:x:0')) === 1);
확인('박스에서 지시를 열면 한 자리 쌓음', 기록차이(1, 안누름({ 바깥: '작업:x:0', 안: null }, '작업:x:0', 'x#1')) === 1);

console.log('⑥ 곳 접힘 · 보기 바뀜 — 바깥 접기');
확인('곳이 접혀 바깥을 접으면 두 자리 걷음', 기록차이(2, 접기(k, 'A')) === -2);

console.log(`\n통과 ${통과} · 실패 ${실패}`);
if (실패) process.exit(1);
