// [관리부 작업 443] 상황판 PC 앱의 문서 통로 — 앱 본체의 문서 통로(관리부 tools/docs-ipc.cjs)를 GitHub 통로(github.mjs 통로만들기())와 //
//   같은 모양(파일읽기·파일목록·마지막커밋·답파일만들기)으로 감싼다. 화면(app.mjs)은 PC 앱이면 이 통로를, 모바일 앱이면 GitHub 통로를 쓴다. //
// 따르는 설계: 관리부 설계 bp-백엔드 「백엔드 모듈은 PC 앱이면 PC 폴더와 그 PC의 GitHub 로그인으로, 모바일 앱이면 GitHub 열쇠로 문서를 읽고 쓴다」 조 · //
//   「문서 저장소는 비공개로 두고, 상황판은 답 파일 자리에 새 답 파일만 만든다」 조 ③④. //
// ★PC 앱은 열쇠를 쓰지 않는다 — 받아 오고 올리는 일은 PC의 `git`이 가진 로그인으로 앱 본체가 한다. //
import { 적어도됨, 못적는까닭 } from './github.mjs';
import { 답자리 } from './answer-file.mjs';

// 앱 본체가 문서 통로를 내주었나 — preload가 내주는 함수 이름으로 가린다 //
export const PC문서통로있음 = (창) => !!(창 && 창.상황판 && typeof 창.상황판.문서파일읽기 === 'function');

// 앱 본체가 알리는 결과 — github.mjs 답파일만들기()와 같은 다섯 가지 //
const 결과들 = ['만듦', '같은 이름 있음', '저장소 없음', '적어도됨 거짓', '못 보냄'];

export function PC통로만들기(본체, 기록 = console) {
  const 부르기 = async (이름, 요청) => {
    const r = await 본체[이름](요청);
    if (!r || !r.ok) throw new Error((r && r.이유) || `${이름} — 까닭을 못 받았다`);
    return r;
  };
  async function 파일읽기(저장소, 경로, 지문 = null) {
    const r = await 부르기('문서파일읽기', { 저장소, 경로, 지문 });
    if (r.없음) return null;
    if (r.안바뀜) return { 안바뀜: true, 지문: r.지문 };
    return { 글: r.글, 지문: r.지문 };
  }
  const 파일목록 = async (저장소) => (await 부르기('문서파일목록', { 저장소 })).목록;
  const 마지막커밋 = async (저장소, 경로) => (await 부르기('문서마지막커밋', { 저장소, 경로 })).시각;
  // 받아 오기 — { 못받음: [{ 저장소, 까닭 }], 바뀜: [새 커밋이 들어온 저장소] }를 돌려준다(통로 자체가 실패하면 던진다) //
  const 받아오기 = async (저장소들) => { const r = await 부르기('문서받아오기', { 저장소들 }); return { 못받음: r.못받음 || [], 바뀜: r.바뀜 || [] }; };
  // [관리부 작업 464] 답 파일 만들기 — 앱 본체가 PC 폴더 docs/답/에 그 파일을 만들어 그 파일 하나만 든 커밋을 GitHub에 올린다. //
  //   PC 폴더에 그 이름이 이미 있으면 새로 적지 않고 같은 이름 있음(글)을, 어느 실패든 PC 폴더에 만든 답 파일과 올리지 못한 커밋을 //
  //   남기지 않고 못 보냄(까닭)을 돌려준다. 결과는 던지지 않고 하나로 알린다(github.mjs 답파일만들기()와 같다). //
  //   붙잡기는 PC 앱에서 쓰지 않는다 — 앱 본체가 올리므로 화면이 닫혀도 본체가 살아 있는 동안 끝까지 간다. //
  async function 답파일만들기(저장소, 이름, 글, 메시지, { 곳들 = [] } = {}) {
    const 경로 = 답자리 + 이름;
    기록.log(`[PC 통로] START 답파일만들기 — ${저장소}/${경로}: ${메시지}`);
    if (!적어도됨(저장소, 경로, 글, 곳들)) return { 결과: '적어도됨 거짓', 까닭: 못적는까닭(저장소, 경로) };
    let r;
    try { r = await 본체.답파일적기({ 저장소, 이름, 글, 메시지 }); }
    catch (e) { 기록.log(`[PC 통로] ERROR 앱 본체가 답 파일을 못 받았다 — ${e.message}`); return { 결과: '못 보냄', 까닭: `앱 본체에 못 넘겼다 — ${e.message}` }; }
    if (!r || !r.ok) return { 결과: '못 보냄', 까닭: (r && r.이유) || '앱 본체가 까닭을 안 돌려줬다' };
    if (!결과들.includes(r.결과)) return { 결과: '못 보냄', 까닭: `앱 본체가 모르는 결과를 돌려줬다: ${r.결과}` };
    기록.log(`[PC 통로] ${r.결과 === '못 보냄' ? 'ERROR' : 'SUCCESS'} 답파일만들기 — ${저장소}/${경로}: ${r.결과}${r.커밋 ? ' 커밋 ' + String(r.커밋).slice(0, 7) : ''}${r.까닭 ? ' — ' + r.까닭 : ''}`);
    return { 결과: r.결과, 글: r.글, 까닭: r.까닭, 커밋: r.커밋 || null, 시각: r.시각 || null };
  }
  return { 파일읽기, 파일목록, 마지막커밋, 받아오기, 답파일만들기, PC: true };
}
