// 열린 것의 줄기 셈 — 화면을 만지지 않는 순수 함수(app.mjs가 부른다). //
// [관리부 작업 461] bp-프론트엔드 「열린 것의 줄기와 폰의 이전 버튼」 조 — //
//   ① 줄기 = { 바깥, 안 }. 바깥은 작업·법안·설계안 박스나 설계 모듈 카드 하나, 안은 그 바깥 것 안의 지시나 조 하나다(없으면 null). //
//      열쇠 글은 app.mjs가 정하고, 여기서는 같은지만 본다. //
//   ② 같은 단계의 다른 것을 열면 앞 것을 그 안의 것과 함께 접고 누른 것을 연다. //
//   ③ 열린 것을 다시 누르거나 ✕를 누르면 그것을 그 안의 것과 함께 접는다. //
//   ④ 이전 버튼은 줄기 끝(안이 있으면 안, 없으면 바깥)을 접는다. //
//   ⑤ 쌓은 기록 수 = 줄기 깊이 — 기록차이()가 더 쌓을 수(+)나 걷을 수(-)를 낸다. //
export const 빈줄기 = Object.freeze({ 바깥: null, 안: null });
export const 줄기깊이 = (j) => (j.바깥 ? (j.안 ? 2 : 1) : 0);

// 연다 — 이미 열려 있으면 그대로 둔다(<details>가 다시 그려지며 내는 toggle도 이 길로 온다) //
export const 바깥열기 = (j, 키) => (j.바깥 === 키 ? j : { 바깥: 키, 안: null });
export const 안열기 = (j, 바깥, 안) => (j.바깥 === 바깥 && j.안 === 안 ? j : { 바깥, 안 });

// 접는다 — 바깥 것을 접으면 그 안의 것도 함께 접힌다. 줄기에 없는 것이면 그대로 둔다 //
export function 접기(j, 키) {
  if (j.바깥 === 키) return 빈줄기;
  if (j.안 === 키) return { 바깥: j.바깥, 안: null };
  return j;
}

// 누른다 — 열린 것을 누르면 접고, 아니면 연다 //
export const 바깥누름 = (j, 키) => (j.바깥 === 키 ? 빈줄기 : 바깥열기(j, 키));
export const 안누름 = (j, 바깥, 안) => (j.바깥 === 바깥 && j.안 === 안 ? 접기(j, 안) : 안열기(j, 바깥, 안));

// 이전 버튼 — 줄기 끝 하나를 접는다 //
export const 끝접기 = (j) => (j.안 ? { 바깥: j.바깥, 안: null } : 빈줄기);
// 기록이 d 단계로 줄었을 때 — 줄기를 d 단계까지 끝부터 접는다 //
export function 깊이까지접기(j, d) {
  while (줄기깊이(j) > Math.max(0, d)) j = 끝접기(j);
  return j;
}

// 쌓은 기록 수를 줄기 깊이에 맞추려면 몇 자리를 더 쌓거나(+) 걷어야(-) 하나 //
export const 기록차이 = (쌓은, j) => 줄기깊이(j) - 쌓은;
