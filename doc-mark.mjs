// 상황판 — 의회 법안과 설계실 설계안에 「답 줄」과 「코멘트 줄」을 붙이고 걷어내는 공통 부품. //
//
// 무엇을 하나: 문서 글을 받아, 한 항목(법안·설계안) 제목 아래에 답을 찍거나 줄마다 코멘트를 단 새 글을 돌려준다. //
//   파일을 읽지도 쓰지도 않는다 — 읽고 쓰는 일은 부르는 쪽(PC 앱 통로 `doc-mark.cjs` · GitHub 통로 `github.mjs`)의 몫이다. //
//
// ★왜 여기 한 벌만 두나: PC 앱과 모바일 앱이 같은 문서에 같은 모양으로 적어야 한다(bp-프론트엔드의 「상황판은 PC 앱과 모바일 앱 둘이고, 의회·설계실·작업 목록은 두 앱이 코드 한 벌을 함께 쓴다」). //
//   두 벌을 두면 한쪽만 고쳐져 폰에서 찍은 답을 PC 화면이 못 읽는 일이 생긴다. //
//
// 따르는 설계(관리부 설계 bp-결재 「의회·설계실 화면은 법안과 설계안마다 `승인`·`취소` 두 답을 찍고, 제목 줄과 항마다 코멘트 칸을 둔다」 조): //
//   ②③ — 법안과 설계안의 답은 승인·취소 둘이다(의회 파일과 설계실 파일이 같다). 제거 안도 항마다가 아니라 안에 답 하나를 찍는다. //
//   ④ — 찍은 답은 제목 줄 아래 「> 📌 **승인** | 날짜」나 「> 📌 **취소** | 날짜」 한 줄로 남긴다. 전에 찍혀 남아 있는 //
//        신설·변경·제거·추가 답 줄은 승인으로 읽는다(찍힌표시()). //
//   ⑥ — 코멘트는 찍힌 답에 딸리고, 어느 답이 찍혀 있어도 달 수 있다. 답 없이 단 코멘트는 물음으로 남는다. //
//   잘못 찍은 답을 거두는 일은 답이 아니다 — 빈 답을 보내 걷어낸다(화면은 찍힌 단추를 다시 누르면 빈 답을 보낸다). //

// 줄바꿈 글자는 이름으로 만든다 — 이 파일을 거쳐 가는 도구가 역슬래시를 한 겹 먹어 //
// 실제 줄바꿈이 코드에 박힌 사고가 있었다(옛 `doc-mark.cjs`). 이름으로 두면 그럴 자리가 없다. //
const CR = String.fromCharCode(13), LF = String.fromCharCode(10);

// 답마다 문서에 적히는 글자 — 승인·취소와 작업 표시(체크·물음·엑스)만 새로 찍는다. //
//   옛 답(신설·추가·변경·제거·유지)은 읽기만 한다 — 찍힌표시()가 신설·추가·변경·제거를 승인으로 읽는다. //
// ★옛 「취소」 줄(「🚫 **취소**」)도 「**취소**」를 품어 그대로 취소로 읽힌다. //
export const 표시글 = {
  승인: '**승인**', 취소: '**취소**',
  체크: '✅ **체크(진행)**', 물음: '❓ **?(이게 뭐지)**', 엑스: '❌ **X(지워)**',
};
const 옛표시글 = { 신설: '🆕 **신설**', 추가: '🆕 **추가**', 변경: '✏️ **변경**', 제거: '🗑️ **제거**', 유지: '🔒 **유지**' };
const 승인으로읽을옛답 = ['신설', '추가', '변경', '제거'];
// 의회 파일과 설계실 파일의 답 — 둘이 같다 //
export const 안답들 = ['승인', '취소'];
// 작업 목록·구상 창고 같은 문서의 항목에 찍는 표시 — PC 앱 문서 목록의 ✅❓❌ 단추가 쓴다. //
export const 작업표시들 = ['체크', '물음', '엑스'];
// 문서 이름으로 고를 수 있는 답을 정한다 — 의회 파일·설계실 파일이면 승인·취소, 그 밖은 작업 표시. //
export const 답들 = (문서) => {
  const 이름 = String(문서 || '').split('/').pop();
  return 이름 === '설계실.md' || 이름 === 'assembly.md' ? 안답들 : 작업표시들;
};

export const 표시앞머리 = '> 📌';
// 표시(📌)와 코멘트(💬)의 앞머리를 가른 까닭 — 한 항목에 답은 하나지만 코멘트는 줄 수만큼 붙는다. //
export const 코멘트앞머리 = '> 💬';

// 항 기호(①②③…)로 시작하는 줄인가 — 코멘트를 달 «각 항»을 찾는 자다. //
const 항기호 = /^[①-⑳㉑-㉟]/;

// ★줄을 «줄끝까지 붙은 채로» 쪼갠다 — 줄끝을 버렸다 다시 이으면 한 파일 안에 CRLF와 LF가 섞인 //
//   문서가 한쪽으로 통일돼, 답 한 줄을 찍었는데 문서 전체가 바뀐 것으로 잡힌다. //
const 줄쪼개기 = new RegExp('[^' + CR + LF + ']*(?:' + CR + '?' + LF + '|$)', 'g');
const 줄조각들 = (글) => (String(글).match(줄쪼개기) || []).filter((t, i, a) => t !== '' || i === a.length - 1);
const 줄끝떼기 = (조각) => String(조각).replace(new RegExp('[' + CR + LF + ']+$'), '');

// 항목 제목 줄(## 로 시작하고 그 표식을 품은 줄)을 찾는다. 못 찾으면 던진다 — 조용히 넘어가면 //
// «찍었는데 안 붙은» 상태가 된다. //
function 제목줄찾기(글만, 표식) {
  const i = 글만.findIndex((l) => l.startsWith('## ') && l.includes(표식));
  if (i < 0) throw new Error(`그 항목을 문서에서 못 찾았다: ${표식}`);
  return i;
}

// 그 항목이 어디서 끝나나 — 다음 항목 제목 줄, 없으면 글 끝. 코멘트를 찾고 다는 범위가 이 안이다. //
function 항목끝찾기(글만, i) {
  let k = i + 1;
  while (k < 글만.length && !글만[k].startsWith('## ')) k++;
  return k;
}

// 어떤 줄 «바로 아래»에 붙은 딸림 줄(과 그 앞 빈 줄)을 걷고 새 줄을 끼운다. //
// ★답 줄과 코멘트 줄이 같은 모양(빈 줄 + `> 무엇` 한 줄)이라 자를 하나로 둔다. //
function 줄아래갈아끼우기(조각, 글만, 자리, 걷을앞머리들, 새글) {
  const 걷나 = (l) => 걷을앞머리들.some((p) => String(l).startsWith(p));
  let j = 자리 + 1;
  while (j < 글만.length && (걷나(글만[j]) ||
    (글만[j].trim() === '' && j + 1 < 글만.length && 걷나(글만[j + 1])))) j++;
  // 새로 넣는 줄의 줄끝은 그 자리 줄의 것을 따른다 — 이미 쓰이던 줄끝이라 섞이지 않는다. //
  const 줄끝 = 조각[자리].slice(글만[자리].length) || LF;
  const 새줄 = 새글 ? [줄끝, 새글 + 줄끝] : [];
  return [...조각.slice(0, 자리 + 1), ...새줄, ...조각.slice(j)].join('');
}

// 여러 줄로 온 글을 한 줄로 눕힌다 — 마크다운 `>` 인용은 한 줄이 한 덩어리다. //
const 한줄로 = (t) => 줄조각들(t).map(줄끝떼기).join(' ').trim();

// 그 항목에 지금 찍힌 답 — 답 글자 가운데 하나, 모르는 표시면 「기타」, 없으면 빈 값. //
//   옛 신설·추가·변경·제거 답 줄은 승인으로 읽는다(bp-결재 같은 조 ④). //
export function 찍힌표시(원문, 표식) {
  const 글만 = 줄조각들(원문).map(줄끝떼기);
  const i = 제목줄찾기(글만, 표식);
  const 줄 = 글만.slice(i, 항목끝찾기(글만, i)).find((l) => l.startsWith(표시앞머리)) || '';
  for (const [답, 글자] of Object.entries(표시글)) if (줄.includes(글자)) return 답;
  for (const [답, 글자] of Object.entries(옛표시글)) if (줄.includes(글자)) return 승인으로읽을옛답.includes(답) ? '승인' : 답;
  return 줄 ? '기타' : '';
}

// 그 항목에 달린 코멘트 줄들. //
export function 코멘트달린줄들(원문, 표식) {
  const 글만 = 줄조각들(원문).map(줄끝떼기);
  const i = 제목줄찾기(글만, 표식);
  return 글만.slice(i, 항목끝찾기(글만, i)).filter((l) => l.startsWith(코멘트앞머리));
}

// 그 항목 제목 아래의 답 줄을 갈아 끼운 새 글을 돌려준다. //
// 답이 빈 값이면 걷어내기만 한다 — 잘못 찍은 답을 거둘 길이다. //
// 그 문서에서 고를 수 없는 답이면 던진다(의회·설계실 파일에 옛 답 「신설」·「변경」, 작업 목록에 「승인」 같은 것). //
// 코멘트는 작업 표시(✅❓❌)를 찍으며 함께 적는 한마디다 — 답 줄 끝에 「 | 코멘트」로 붙는다. //
export function 표시붙인글(원문, 표식, 표시, 오늘, 문서 = 'assembly.md', 코멘트 = '') {
  if (!표식) throw new Error('어느 항목인지가 안 왔다');
  if (표시 && !답들(문서).includes(표시)) throw new Error(`이 문서에서 찍을 수 없는 답이다: ${표시} (${문서} — ${답들(문서).join('·')})`);
  const 조각 = 줄조각들(원문);
  const 글만 = 조각.map(줄끝떼기);
  const i = 제목줄찾기(글만, 표식);
  const 새글 = 표시 ? `${표시앞머리} ${표시글[표시]} | ${오늘}${코멘트 && 코멘트.trim() ? ' | ' + 한줄로(코멘트) : ''}` : '';
  return 줄아래갈아끼우기(조각, 글만, i, [표시앞머리], 새글);
}

// 제목 줄이나 한 항에 코멘트를 달거나(빈 코멘트면) 걷은 새 글을 돌려준다. 찍힌 답은 건드리지 않는다. //
// ★줄키는 제목 줄이면 '제목', 항이면 그 항 기호('①' 같은 것)다 — 화면에 보이는 글자와 문서의 글자가 같다. //
export function 코멘트붙인글(원문, 표식, 줄키, 코멘트, 오늘) {
  if (!표식) throw new Error('어느 항목인지가 안 왔다');
  if (!줄키) throw new Error('어느 줄에 다는 코멘트인지가 안 왔다');
  const 조각 = 줄조각들(원문);
  const 글만 = 조각.map(줄끝떼기);
  const i = 제목줄찾기(글만, 표식);
  let 자리 = i;
  if (줄키 !== '제목') {
    const 끝 = 항목끝찾기(글만, i);
    자리 = 글만.findIndex((l, k) => k > i && k < 끝 && 항기호.test(l) && l.startsWith(줄키));
    if (자리 < 0) throw new Error(`그 항을 항목에서 못 찾았다: ${줄키}`);
    // 한 항은 제 기호 줄에서 다음 항 기호 줄 앞까지다 — 항 아래 이어지는 줄(「→ 고칠 글:」·목록)이 있으면 //
    //   코멘트는 그 끝에 단다. 항 기호 줄 바로 밑에 달면 코멘트가 지금 글과 고칠 글 사이를 갈라놓는다. //
    for (let k = 자리 + 1; k < 끝 && !항기호.test(글만[k]) && 글만[k].trim() !== '---'; k++) {
      const t = 글만[k].trim();
      if (!t || t.startsWith(코멘트앞머리) || t.startsWith(표시앞머리)) continue;
      if (t.startsWith('**구현 계획')) break;   // 설계안의 구현 계획 묶음은 항이 아니다 //
      자리 = k;
    }
  }
  const 새글 = 코멘트.trim() ? `${코멘트앞머리} **${줄키}** | ${오늘} | ${한줄로(코멘트)}` : '';
  return 줄아래갈아끼우기(조각, 글만, 자리, [코멘트앞머리], 새글);
}
