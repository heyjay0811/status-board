// ── 2-2. 줄바꿈 방식 — CRLF 파일에서 한 줄도 못 읽던 자리 ──────────────────── //
// 프로젝트마다 줄바꿈이 다르다(LF·CRLF). 끝에 `\r`이 붙으면 정규식의 `(.*)$`가 `\r` 앞에서 //
// 멈추는데 `$`는 문자열 끝에만 맞아 매칭이 통째로 실패한다. 조용히 0개가 되는 종류라 //
// "문제 없음"과 구별되지 않는다. //
console.log('\n[줄바꿈 방식(CRLF/LF)]');
{
  확인('CRLF 줄도 읽는다', 항목머리('## [작업 6] 제목 — 진행중 · 2026-07-18\r') !== null,
    JSON.stringify(항목머리('## [작업 6] 제목 — 진행중 · 2026-07-18\r')));
  확인('CRLF 새 형식도 읽는다', 항목머리('## [작업계획 1] · 제목 · #core · 2026-07-19\r')?.번호 === 1,
    JSON.stringify(항목머리('## [작업계획 1] · 제목 · #core · 2026-07-19\r')));
  const crlf = ['## [작업계획 1] · 하나 · 2026-07-19', '## [검증 2] · 둘 · 2026-07-19'].join('\r\n');
  확인('CRLF 문서를 통째로 읽는다', 항목들(crlf).length === 2, `${항목들(crlf).length}개`);
}

