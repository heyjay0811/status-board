// 문서 항목 파서(doc-parse.mjs)의 회귀 테스트 — "안 걸리는 게 정상"과 "파서가 죽었다"를 구별하려는 장치. //
//
// 왜 필요한가: 이 파서가 통째로 고장 나 항목을 0개 읽어도, 그 결과를 받는 쪽에서는 대조할 것이 //
//   없으니 똑같이 "이상 없음"이 된다. //
//   그래서 "읽어야 할 것"과 "읽으면 안 되는 것"을 여기 못박는다. 규칙은 경로 규칙 `rule-문서` 제1조다. //
//
//   돌리기: 인자 없이 이 파일을 실행한다. //

import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { 항목들, 항목머리, 항목분해, 필드분해 } from './doc-parse.mjs';

const here = dirname(fileURLToPath(import.meta.url));

let 통과 = 0, 실패 = 0;
const 확인 = (이름, 조건, 실제) => {
  if (조건) { 통과++; console.log(`  ✅ ${이름}`); }
  else { 실패++; console.log(`  ❌ ${이름}\n     실제: ${실제}`); }
};

// ── 1. 읽어야 하는 것과, 옛 모양이라 건너뛰는 것 ───────────────────────────── //
// [작업 402] `rule-문서` 제1조 — # 둘 + `[종류 N]`인 줄만 항목이다. # 없는 평문 줄과 //
//   종류 없는 `[N]`은 항목이 아니다. //
console.log('\n[읽어야 하는 것 · 옛 모양은 건너뛴다]');
{
  const 원문 = [
    '## [검증 1] · 새 형식이다 · 가능 · 2026-07-19',
    '본문 한 줄.',
    '## [작업 2] · 종류가 작업이어도 읽는다 · 진행중 · [설계 1] · 2026-07-19',
    '[설계 3] · # 없는 평문 줄은 항목이 아니다 · #core · 2026-07-17',
    '## [4] · 종류 없는 번호는 항목이 아니다 · 2026-07-10',
    '## [구상 5] · 구상도 읽는다 · #문서 · 2026-07-20',
  ].join('\n');
  const 목록 = 항목들(원문);
  확인('# 둘 + 종류 있는 줄 셋만 항목으로 읽는다', 목록.length === 3, `${목록.length}개`);
  확인('번호를 정확히 뽑는다', 목록.map((i) => i.번호).join(',') === '1,2,5', 목록.map((i) => i.번호).join(','));
  확인('종류를 뽑는다(검증·작업·구상)', 목록.map((i) => i.종류).join(',') === '검증,작업,구상', 목록.map((i) => i.종류).join(','));
  const 작업만 = 항목들(원문, { 종류: '작업' });
  확인('종류로 걸러낸다', 작업만.map((i) => i.번호).join(',') === '2', 작업만.map((i) => i.번호).join(','));
}

// ── 2. 읽으면 안 되는 것 ───────────────────────────────────────────────────── //
console.log('\n[읽으면 안 되는 것]');
{
  const 사례 = [
    ['### 소제목이 항목처럼 생긴 경우', '### [작업 3] · 원래 계획 내용'],
    ['### 소제목(괄호로 시작)', '### ([작업 3]의 원래 계획 내용 — 착수 전에 세운 것)'],
    ['#### 더 깊은 소제목', '#### [설계 9] · 뭐든'],
    ['# 파일 제목 높이', '# [설계 9] · 뭐든'],
    ['본문 한가운데 인용', '이것은 [설계 26]이 정한 것이다.'],
    ['줄 맨 앞 인용(가운뎃점 없음)', '[설계 26]이 정한 것을 여기서 따른다.'],
    ['줄 맨 앞 인용 — 띄어쓰기까지 항목처럼 생긴 것', '[작업 3] 을 먼저 끝내야 한다.'],
    ['표 안의 예시', '| 설계 | `## [설계 36] · 제목 · #core · 2026-07-17` | blueprint.md |'],
    ['인용문 안', '> [설계 12] · 옛날에 이랬다'],
    ['# 없는 평문 줄(제12조 ②)', '[구상 7] · 평문으로 적은 구상 · #문서 · 2026-07-17'],
    ['종류 없는 번호(제12조 ④)', '## [7] · 종류 없는 항목 · 완료 · 2026-07-17'],
    ['번호 없는 `##` 줄(제12조 ②⑤)', '## 자원 점검 · 완료 · 2026-06-14'],
    ['조문에 없는 종류 `설계`', '## [설계 1] · 옛 설계 번호 · #core · 2026-07-19'],
  ];
  for (const [이름, 줄] of 사례) 확인(이름, 항목머리(줄) === null, JSON.stringify(항목머리(줄)));
}

// ── 2-1. 전환기 — 아직 안 고친 옛 작업 제목 ─────────────────────────────────── //
// 옛 작업 항목은 번호 뒤에 가운뎃점이 없다(`## [작업 1] 제목 — 진행중`). # 둘이 //
// "항목이다"라는 표시이므로 받는다 — 안 받으면 아직 안 고친 작업 파일을 통째로 못 읽는다. //
// 반대로 #이 없으면 본문 인용과 구별할 수 없으므로 받으면 안 된다. //
console.log('\n[전환기 — 옛 작업 형식]');
{
  const 옛작업 = '## [작업 1] 도면 그리는 방법을 옮긴다 — 진행중 · [설계 20] 배포 · 2026-07-15';
  const m = 항목머리(옛작업);
  확인('#이 있으면 가운뎃점이 없어도 항목으로 읽는다', m !== null && m.번호 === 1 && m.종류 === '작업', JSON.stringify(m));
  확인('그 경우 나머지를 통째로 준다', m?.나머지.startsWith('도면 그리는'), m?.나머지);
  확인('#도 가운뎃점도 없으면 안 읽는다(인용과 구별 불가)',
    항목머리('[작업 1] 도면 그리는 방법을 옮긴다 — 진행중') === null,
    JSON.stringify(항목머리('[작업 1] 도면 그리는 방법을 옮긴다 — 진행중')));
}

// ── 2-2. 줄바꿈 방식 — CRLF 파일에서 한 줄도 못 읽던 자리 ──────────────────── //
// 프로젝트마다 줄바꿈이 다르다(LF·CRLF). 끝에 `\r`이 붙으면 정규식의 `(.*)$`가 `\r` 앞에서 //
// 멈추는데 `$`는 문자열 끝에만 맞아 매칭이 통째로 실패한다. 조용히 0개가 되는 종류라 //
// "문제 없음"과 구별되지 않는다. //
console.log('\n[줄바꿈 방식(CRLF/LF)]');
{
  확인('CRLF 줄도 읽는다', 항목머리('## [작업 6] 제목 — 진행중 · 2026-07-18\r') !== null,
    JSON.stringify(항목머리('## [작업 6] 제목 — 진행중 · 2026-07-18\r')));
  확인('CRLF 새 형식도 읽는다', 항목머리('## [구상 1] · 제목 · #core · 2026-07-19\r')?.번호 === 1,
    JSON.stringify(항목머리('## [구상 1] · 제목 · #core · 2026-07-19\r')));
  const crlf = ['## [구상 1] · 하나 · 2026-07-19', '## [구상 2] · 둘 · 2026-07-19'].join('\r\n');
  확인('CRLF 문서를 통째로 읽는다', 항목들(crlf).length === 2, `${항목들(crlf).length}개`);
}

// ── 3. 코드블록 — 실제로 오탐이 났던 자리 ──────────────────────────────────── //
console.log('\n[코드블록 안은 건너뛴다]');
{
  const 원문 = [
    '## [구상 37] · 코드에 설계 태그를 단다 · #core · 2026-07-18',
    '다른 프로젝트 설계도엔 이런 항목을 만들면 된다:',
    '```',
    '[설계 41] · 이 앱의 로깅은 전역 규칙 #로깅을 따른다 · #로깅 · 2026-07-18',
    '## [작업 15] · 도면 그리는 방법을 옮긴다 · 진행중 · [설계 20] · 2026-07-15',
    '```',
    '그러면 된다.',
    '## [구상 38] · 그다음 항목 · #core · 2026-07-19',
  ].join('\n');
  const 목록 = 항목들(원문);
  확인('코드블록 밖의 둘만 읽는다', 목록.length === 2, `${목록.length}개 — ${목록.map((i) => i.번호).join(',')}`);
  확인('코드블록 안의 [41]을 안 읽는다', !목록.some((i) => i.번호 === 41), '읽어버렸다');
  확인('코드블록 안의 [15]를 안 읽는다', !목록.some((i) => i.번호 === 15), '읽어버렸다');
}
{
  // 여닫이가 안 맞는 코드블록(닫는 백틱 누락)은 그 뒤를 통째로 삼킨다. //
  // 막을 방법이 없으므로 "그렇게 동작한다"를 못박아 둔다 — 나중에 항목이 사라지면 여기부터 의심한다. //
  const 원문 = ['```', '## [설계 1] · 안 닫힌 블록 안 · 2026-07-19'].join('\n');
  확인('안 닫힌 코드블록은 뒤를 삼킨다(알려진 한계)', 항목들(원문).length === 0, `${항목들(원문).length}개`);
}

// ── 4. 필드 분해 — `rule-문서` 제1조 · 제5조 ──────────────────────────── //
console.log('\n[필드 분해]');
{
  const 줄표 = 필드분해('도면 — 옮긴다 · 작업 · 2026-07-15');
  확인('` — `에서 자르지 않는다(제목에 남는다)', 줄표.제목 === '도면 — 옮긴다' && 줄표.상태 === '작업', JSON.stringify(줄표));
  const 붙은점 = 필드분해('가·나를 잇는다 · 작업 · 2026-07-15');
  확인('빈칸 없이 붙은 `·`는 구분자가 아니다', 붙은점.제목 === '가·나를 잇는다', JSON.stringify(붙은점));
  const 검증 = 필드분해('상황판을 열어 본다 · 환경대기 · [작업 3] · 2026-09-14');
  확인('검증 상태 `환경대기`를 읽는다', 검증.상태 === '환경대기', JSON.stringify(검증));
  확인('검증의 `[작업 M]`은 제목이 아니라 작업 필드다', 검증.제목 === '상황판을 열어 본다' && 검증.작업.join() === '[작업 3]', JSON.stringify(검증));
  const 가능 = 필드분해('바로 해 본다 · 가능(실기기) · [작업 4] · 2026-09-14');
  확인('검증 상태 `가능`을 괄호 단서와 함께 읽는다', 가능.상태 === '가능(실기기)', JSON.stringify(가능));
  const 태그 = 필드분해('생각을 적는다 · #규칙 #작업 · 2026-09-12');
  확인('`#` 태그를 필드로 읽고 제목에서 뺀다', 태그.제목 === '생각을 적는다' && 태그.태그.join(' ') === '#규칙 #작업', JSON.stringify(태그));
  const 기호제목 = 필드분해('C# 문법을 본다 · #개발 · 2026-09-12');
  확인('제목 안의 `#`은 태그가 아니다', 기호제목.제목 === 'C# 문법을 본다' && 기호제목.태그.join() === '#개발', JSON.stringify(기호제목));
  const 인용제목 = 필드분해('[작업 9]를 이어 한다 · 작업 · 2026-09-12');
  확인('제목이 `[작업 N]를`로 시작해도 제목이 산다', 인용제목.제목 === '[작업 9]를 이어 한다' && 인용제목.작업.length === 0, JSON.stringify(인용제목));
}

// ── 5. 항목분해 — 번호 없는 `##` 줄 ─────────────────────────────────────────── //
console.log('\n[항목분해 — 번호 없는 줄]');
{
  const 원문 = [
    '## [작업 1] · 앞 항목 · 작업 · 2026-09-14',
    '본문.',
    '## 번호 없는 옛 항목 · 완료 · 2026-06-14',
    '## 작업 160 상태를 줄표 뒤에 적은 옛 줄 — 완료 · 2026-08-11',
    '## ★안내문 (상태 없음)',
  ].join('\n');
  const 목록 = 항목분해(원문, { 종류: '작업' });
  확인('번호 없는 `##` 줄은 상태가 있어도 항목이 아니다', 목록.length === 1, `${목록.length}개`);
  확인('그 줄은 앞 항목의 본문으로 흘러간다', 목록[0].본문.includes('번호 없는 옛 항목'), 목록[0].본문);
}

// ── 6. 실물 대조 — 이 프로젝트의 문서 ─────────────────────────────────────── //
// 옛 설계 파일(blueprint.md)을 걷어 낸 뒤 이 자리가 없는 파일을 열다 멈췄다 — 지금 문서로 대조한다. //
// 이 부품은 status-board 저장소에 살고, 대조할 문서는 옆 폴더 관리부(D:/1code/management/docs)에 있다. //
// 관리부가 없는 기계에서는 이 대목만 건너뛰고 건너뛴 것을 알린다. //
const 관리부문서 = join(here, '..', 'management', 'docs');
console.log('\n[실물 문서로 대조]');
if (!existsSync(관리부문서)) console.log(`  (건너뜀: 관리부 문서 자리가 없다 — ${관리부문서})`);
else for (const [파일, 종류] of [['work.md', '작업'], ['brainstorm.md', '구상'], ['verify.md', '검증'], ['errors.md', '오류']]) {
  const 원문 = readFileSync(join(관리부문서, 파일), 'utf8');
  const 목록 = 항목들(원문, { 종류 });
  const 번호들 = 목록.map((i) => i.번호);
  const 중복 = 번호들.filter((n, i) => 번호들.indexOf(n) !== i);
  확인(`${파일}에서 항목을 하나 이상 읽는다`, 목록.length > 0, `${목록.length}개`);
  확인(`${파일}에 번호 중복이 없다`, 중복.length === 0, `중복 ${중복}`);
  console.log(`     (${파일}: 읽은 항목 ${목록.length}개)`);
}

console.log(`\n결과: 통과 ${통과} · 실패 ${실패}`);
process.exit(실패 ? 1 : 0);
