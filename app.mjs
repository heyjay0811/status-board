// ★읽는 길은 bp-백엔드의 「상황판은 원본에서 그때그때 읽은 문서로 화면을 그린다」과 같다 — 기기에 둔 글(sb.문서)로 먼저 그리고, 지문으로 GitHub에 물어 바뀌었으면 바꿔 끼운다. //
