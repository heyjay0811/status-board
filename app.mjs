// [관리부 작업 443] bp-진행현황 「진행 현황 차트는 …의회·설계실을 처리 이력으로 긋고…」 조 ⑩ — 의회·설계실 현황 한 줄에 넘길 값. //
//   기다림 = 의회면 관리부 의회 파일에 올라 있는 법안 수, 설계실이면 부서·프로젝트마다의 설계실 파일에 올라 있는 설계안 수의 합 · //
//   답찍힘 = 그 가운데 결재 모듈이 내놓는 최종 답이 승인이나 취소인 안 수([관리부 작업 464] — 안들읽기()가 입힌 it.표시, //
