//   쌓은 = 이 화면이 쌓은 기록 자리 수. 줄기가 길어지면 history.pushState({ 깊이 })로 쌓고, 이전 버튼이 아닌 길로 짧아지면 //
//      history.go(-n)으로 걷는다. 걷어서 오는 popstate는 걷는중으로 가려 줄기를 다시 접지 않는다. //
//   곳 펼침·고정, 규칙안목록·설계실 목록 머리 줄(<details class="자리큰">), 설계 칩은 줄기에 넣지 않는다. //
//      다만 [관리부 작업 475] 모바일 앱에서 단추로 펼친 곳 하나는 줄기의 맨 앞 단계(상태.줄기.곳)다. //
//      이전 버튼은 곳 안에 열린 것을 줄기 끝부터 다 접은 뒤 곳을 접어 첫 화면으로 돌아오고, 첫 화면에서 누르면 앱이 닫힌다. PC 앱은 곳이 늘 null이다. //
상태.줄기 = 빈줄기;
const 카드머리 = '카드:';
const 박스열쇠 = (j) => (j.바깥 && !j.바깥.startsWith(카드머리) ? j.바깥 : null);
const 줄기글 = (j) => ([j.곳, j.바깥, j.안].filter(Boolean).join(' → ') || '(빈 줄기)');
// 카드 키(「저장소/경로」)나 조 키(「저장소/경로#차례」)가 줄기에 열려 있나 //
function 설계열림(k) {
  const i = k.lastIndexOf('#');
  return i < 0 ? 상태.줄기.바깥 === 카드머리 + k : 상태.줄기.바깥 === 카드머리 + k.slice(0, i) && 상태.줄기.안 === k;
}
function 설계펼침맞추기() {
  for (const d of 본문.querySelectorAll('details[data-설계펼침]')) {
    const 열림 = 설계열림(d.dataset.설계펼침);
    if (d.open !== 열림) d.open = 열림;
  }
}
let 쌓은 = 0, 걷는중 = 0, 걷은때 = 0;
// 줄기를 새 줄기로 바꾸고 기록 수를 맞춘다. 그림이 참이면 바뀐 만큼 다시 그린다 — 박스가 바뀌면 화면 전체, //
//   박스 안의 지시만 바뀌면 박스, 카드·조만 바뀌면 <details>의 open만 고친다. //
function 줄기바꾸기(새, 까닭, 그림 = true) {
  const 옛 = 상태.줄기;
  const 옛곳 = 옛.곳 || null, 새곳 = 새.곳 || null;
  if (새 === 옛 || (새곳 === 옛곳 && 새.바깥 === 옛.바깥 && 새.안 === 옛.안)) return;
  상태.줄기 = 새;
  const 옛박스 = 박스열쇠(옛), 새박스 = 박스열쇠(새);
  if (옛박스 !== 새박스) { 상태.열린 = 새박스 ? { 열쇠: 새박스 } : null; 상태.쓰는줄 = null; }
  기록(`줄기 — ${까닭}: ${줄기글(옛)} ⇒ ${줄기글(새)}`);
  기록맞추기();
  if (!그림) return;
  // 모바일 앱에서 곳이 바뀌면(펼침 · 「◀ 접기」 · 이전 버튼) 첫 화면과 곳 화면을 바꿔 그린다 //
  if (옛곳 !== 새곳 || 옛박스 !== 새박스) 그리기();
  else if (새박스) 박스그리기();
  else 설계펼침맞추기();
}
// 쌓은 기록 자리 수를 줄기 깊이에 맞춘다. 걷는 중이면 popstate가 온 뒤 다시 맞춘다. //
function 기록맞추기() {
  if (걷는중 && Date.now() - 걷은때 < 2000) return;
  if (걷는중) { 기록(`ERROR 기록을 걷었는데 2초 동안 popstate가 안 왔다 — 지금 기록 깊이로 다시 맞춘다`); 걷는중 = 0; 쌓은 = (history.state && history.state.깊이) || 0; }
  const 차이 = 기록차이(쌓은, 상태.줄기);
  try {
    if (차이 > 0) {
      for (let i = 1; i <= 차이; i++) history.pushState({ 깊이: 쌓은 + i }, '');
      쌓은 += 차이;
      기록(`기록 ${차이}자리 쌓음 — 깊이 ${쌓은}`);
    } else if (차이 < 0) {
      걷는중++; 걷은때 = Date.now(); 쌓은 += 차이;
      기록(`기록 ${-차이}자리 걷음 — 깊이 ${쌓은}`);
      history.go(차이);
    }
  } catch (e) { 기록(`ERROR 브라우저 기록을 못 맞췄다(차이 ${차이}) — 이전 버튼이 줄기와 어긋날 수 있다: ${e.message}`); }
}
// 이전 버튼 — 기록이 준 깊이까지 줄기 끝부터 접는다. 이 화면이 걷어서 온 popstate면 줄기는 그대로 두고 기록만 다시 맞춘다 //
addEventListener('popstate', (e) => {
  const 깊이 = (e.state && e.state.깊이) || 0;
  쌓은 = 깊이;
  if (걷는중) {
    걷는중--;
    기록(`기록을 걷었다 — 깊이 ${깊이}`);
    기록맞추기();
    return;
  }
  기록(`이전 버튼 — 기록 깊이 ${깊이}`);
  줄기바꾸기(깊이까지접기(상태.줄기, 깊이), '이전 버튼');
  기록맞추기();   // 앞으로 가기로 깊이가 줄기보다 깊어졌으면 걷는다 //
});
// 켤 때 줄기는 비어 있다 — 그 전에 쌓인 자리(브라우저 새로 고침 같은)가 남아 있으면 걷는다 //
function 남은기록걷기() {
  const 남은 = (history.state && history.state.깊이) || 0;
  try {
    if (남은 > 0) { 기록(`켤 때 남은 기록 ${남은}자리를 걷는다`); 걷는중++; 걷은때 = Date.now(); history.go(-남은); }
    else history.replaceState({ 깊이: 0 }, '');
  } catch (e) { 기록(`ERROR 켤 때 브라우저 기록을 못 맞췄다: ${e.message}`); }
}

