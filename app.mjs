// [관리부 작업 443] bp-프론트엔드 「상황판 PC 앱과 모바일 앱은 모양을 한 벌로 쓴다」 조 — 본문을 위 칸과 뷰어 칸 둘로 놓는다. //
//   위 칸: 알림 줄 · 「프로젝트」 단추 줄 · 펼친 곳의 차트(PC 앱). 뷰어 칸: 펼친 곳들의 뷰어(환경·작업·법안·설계안·설계 카드). //
//   창 전체는 굴리지 않고 뷰어 칸만 따로 굴린다(app.css) — 뷰어를 끝까지 내려도 단추 줄과 차트가 제자리에 남는다. //
// ★두 칸은 한 번 만들고 그 안만 갈아 그린다 — 칸을 통째로 새로 만들면 다시 그릴 때마다(박스를 열 때 같은) 뷰어의 굴린 자리가 //
//   맨 위로 튄다. 안을 갈아 그릴 때도 굴린 자리를 재어 두었다가 돌려놓는다. //
function 두칸() {
  let 위 = document.getElementById('위칸'), 뷰어 = document.getElementById('뷰어칸');
  if (!위 || !뷰어 || 위.parentNode !== 본문 || 뷰어.parentNode !== 본문) {
    본문.innerHTML = '<div class="위칸" id="위칸"></div><div class="뷰어칸" id="뷰어칸"></div>';
    위 = document.getElementById('위칸'); 뷰어 = document.getElementById('뷰어칸');
    // 뷰어 칸의 보이는 높이가 바뀌면(창 크기 · 위 칸의 차트 수) 넓은 화면 박스 칸의 높이도 맞춘다 //
    if (window.ResizeObserver) new ResizeObserver(뷰어높이맞추기).observe(뷰어);
    뷰어.addEventListener('scroll', 박스높이맞추기, { passive: true });
    기록('위 칸과 뷰어 칸을 만들었다');
  }
  return { 위, 뷰어 };
}
// bp-프론트엔드 — 넓은 화면의 박스 칸 높이는 화면에 보이는 뷰어 칸 높이를 넘지 않는다(app.css --뷰어높이) //
function 뷰어높이맞추기() {
  const 뷰어 = document.getElementById('뷰어칸');
  if (뷰어) document.documentElement.style.setProperty('--뷰어높이', 뷰어.clientHeight + 'px');
  박스높이맞추기();
}
// 넓은 화면의 박스 칸 높이를 뷰어 칸에서 지금 보이는 몫에 맞춘다 — 뷰어를 아직 덜 내려 박스 칸 위에 곳 이름 같은 줄이 보이는 동안은 //
//   그만큼 줄여, 박스 아래 끝(답 단추 칸)이 화면 밖으로 나가지 않게 한다. 다 내려 박스 칸이 뷰어 맨 위에 붙으면 보이는 뷰어 높이 전체다. //
function 박스높이맞추기() {
  const 뷰어 = document.getElementById('뷰어칸');
  if (!뷰어 || !덮개.classList.contains('옆칸') || !덮개.parentNode) { 덮개.style.maxHeight = ''; return; }
  const v = 뷰어.getBoundingClientRect(), 칸 = 덮개.parentNode.getBoundingClientRect();
  덮개.style.maxHeight = Math.max(160, v.bottom - Math.max(v.top, 칸.top) - 4) + 'px';
}

function 그리기() {
  document.getElementById('시각').textContent = 시각글();
  머리높이맞추기();
  if (!상태.통로) return 열쇠그리기();
  if (상태.맞추는중 && !상태.곳들.length) { 본문.innerHTML = `<p class="안내">${상태.통로 && 상태.통로.PC ? 'PC 폴더' : 'GitHub'}에서 처음 읽는 중…</p>`; return; }
  // 박스를 연 곳이 접혔으면 박스도 닫는다 — 박스는 그 곳 뷰어의 박스 칸에 선다. //
  //   그 곳 뷰어가 작업 목록이 아니라 환경·설계 카드를 보이고 있으면 작업 박스도 닫는다 //
  const 열린키 = 상태.열린 && 열린줄키(상태.열린.열쇠);
  if (상태.열린 && (!펼친가(열린키) || (열린키.startsWith('곳:') && 보기(열린키.slice(2)) !== '작업'))) { 상태.열린 = null; 상태.쓰는줄 = null; }
  const 알림 = [상태.알림, 코드알림].filter(Boolean).map((말) => `<p class="오류">${막기(말)}</p>`).join('');
  const 줄 = 줄들(), 펼친것 = 펼친줄들(줄);
  const { 위, 뷰어 } = 두칸();
  const 굴린자리 = 뷰어.scrollTop, 위굴린자리 = 위.scrollTop;
  위.innerHTML = 알림 + 단추줄글(줄) + (PC ? 펼친것.map(차트자리글).join('') : '');
  뷰어.innerHTML = 펼친것.map(뷰어글).join('') || '<p class="안내">위 단추에서 부서나 프로젝트를 고르면 여기 열린다.</p>';
  뷰어.scrollTop = 굴린자리; 위.scrollTop = 위굴린자리;
  곳칸채우기();
  설계칩채우기();
  박스그리기();
  뷰어높이맞추기();
}

