//      「GitHub에 못 적었다 — 까닭」 한 줄을 보인다. 코멘트를 못 적었으면 쓴 글을 코멘트 칸에 다시 채워 둔다. //
//   ⑨ 오류가 걷히는 때 — 그 박스에서 단추를 다시 누를 때와 「↻ 다시 읽기」로 화면이 다시 뜰 때(오류는 이 화면 기억에만 둔다). //
//   ⑩ 두지 않는 것 — 찍은 답을 기기에 쌓아 두기 · 뒤에서 차례로 적기 · 「못 적은 답」 목록 · 다시 적기 단추. //
// ★법안·설계안은 저장소·경로·제목 줄로 가린다 — 목록 차례 번호는 다시 읽으면 바뀔 수 있다. //
