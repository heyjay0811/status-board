const 답찍힘인가 = (it) => it.표시 === '승인' || it.표시 === '취소';
function 현황자료(종류) {
  const 경로 = 이력경로[종류];
  if (종류 === '의회') {
    const k = 의회자리.저장소 + '/' + 경로;
    const 관리부곳 = (곳목록 || []).find((x) => x.이름 === 의회자리.저장소);
    const 있음 = !!관리부곳 && 관리부곳.문서들.includes(경로);
    const 관리부 = 상태.곳들.find((x) => x.저장소 === 의회자리.저장소);
    const 안들 = 상태.의회;
    return {
      이력경로: '관리부 ' + 경로,
      이력글: 상태.원문[k] ?? null,
      이력오류: 상태.문서오류[k] || (!있음 ? `관리부 저장소 파일 목록에 ${경로}가 없다` : 상태.원문[k] === undefined ? `${경로}를 아직 받지 못했다` : ''),
      기다림: 안들 ? 안들.length : null,
      답찍힘: 안들 ? 안들.filter(답찍힘인가).length : null,
      마지막커밋: (관리부 && 관리부.시각[의회자리.경로]) || null,
    };
  }
  const 있는곳 = (곳목록 || []).filter((x) => x.문서들.includes(경로));
  const 글들 = [], 오류들 = [];
  for (const 곳 of 있는곳) {
    const k = 곳.이름 + '/' + 경로;
    if (상태.문서오류[k]) 오류들.push(`${보일이름(곳.이름)}: ${상태.문서오류[k]}`);
    if (상태.원문[k] !== undefined) 글들.push(상태.원문[k]);
    else if (!상태.문서오류[k]) 오류들.push(`${보일이름(곳.이름)}: 아직 받지 못했다`);
  }
  if (!있는곳.length) 오류들.push(`어느 곳의 파일 목록에도 ${경로}가 없다`);
  const 읽은 = 상태.설계실.filter((x) => x.안들);
  return {
    이력경로: '곳마다 ' + 경로,
    이력글: 글들.join('\n'),
    이력오류: 오류들.join(' · '),
    기다림: 설계안수(),
    답찍힘: 읽은.length || !상태.설계실.length ? 읽은.reduce((n, x) => n + x.안들.filter(답찍힘인가).length, 0) : null,
    마지막커밋: 설계실시각(),
  };
}

