//   오류는 파일이 있는데 못 읽은 까닭이다(bp-설계실 「상황판 설계실 화면은 부서·프로젝트마다의 설계실을 모아…」 조 ①). //
function 저장에서짓기() {
  상태.원문 = {}; 상태.의회 = null; 상태.설계실 = [];
  상태.곳들 = (곳목록 || []).map((곳) => {
    // 설계 — 파일 목록에 있는 bp 파일마다 읽은 결과나 못 읽은 까닭(bp-설계). 모듈 수는 파일 수, 조 수는 읽은 파일의 조 수 합이다 //
    const 결과 = { 저장소: 곳.이름, 이름: 보일이름(곳.이름), 작업: null, 오류: [], 시각: {}, 목록오류: 곳.목록오류 || '', 줄까닭: '', 설계: [] };
    // PC 폴더에는 있는데 GitHub에서 그 저장소를 못 읽은 곳 — 단추는 지우지 않고 까닭을 단다(bp-부서프로젝트목록 · bp-백엔드) //
    if (곳.목록오류) { const 말 = `${상태.통로 && 상태.통로.PC ? 'PC 폴더' : 'GitHub'}에서 못 읽었다 — ${곳.목록오류}`; 결과.오류.push(말); 결과.줄까닭 = 말; }
    for (const 경로 of 곳.문서들) {
      const k = 곳.이름 + '/' + 경로, d = 문서[k];
      const 설계 = 설계꼴.test(경로);
      if (상태.문서오류[k]) 결과.오류.push(`${경로}: ${상태.문서오류[k]}`);
      if (설계) 결과.설계.push({ 경로, 읽음: d ? 설계문서읽기(d.글) : null, 오류: 상태.문서오류[k] || (d ? '' : '아직 GitHub에서 받지 못했다') });
      if (경로 === 설계실경로) 상태.설계실.push({ 저장소: 곳.이름, 안들: d ? 법안읽기(d.글, '설계실.md') : null, 오류: 상태.문서오류[k] || (d ? '' : '아직 받지 못했다') });
      if (!d) continue;
      상태.원문[k] = d.글; 결과.시각[경로] = d.시각;
      if (경로 === 'docs/work.md') 결과.작업 = 항목분해(d.글, { 종류: '작업' });
      else if (경로 === 의회자리.경로 && 곳.이름 === 의회자리.저장소) 상태.의회 = 법안읽기(d.글, 'assembly.md');
    }
    return 결과;
  });
}

async function 모두읽기(훑기 = false, 받기안함 = false) {
  기록(`START 모두읽기${훑기 ? ' — 저장소도 다시 훑는다' : ''}`);
  if (곳목록 && !훑기) { 저장에서짓기(); 줄고르기(); }   // 지난번 받은 글로 먼저 그린다 //
  상태.맞추는중 = true; 그리기();
  try {
    // ★기기에 둔 곳 목록에 작업 파일 목록이 없으면(작업 파일을 찾기 전 판이 남긴 것) 저장소를 다시 훑는다 //
    const 작업파일모름 = 곳목록 && 곳목록.some((곳) => !Array.isArray(곳.작업파일들) || 곳.판 !== 곳목록판);
    // ★PC 앱이면 기기에 둔 곳 목록이 PC 폴더 곳과 다르거나, 지난번에 GitHub에서 못 읽은 곳이 있으면 다시 훑는다 //
    const PC곳다름 = 곳목록 && PC곳이름들 && (곳목록.map((x) => x.이름).sort().join() !== [...PC곳이름들].sort().join() || 곳목록.some((x) => x.목록오류));
    if (!곳목록 || 훑기 || 작업파일모름 || PC곳다름) {
      if (작업파일모름) 기록('기기에 둔 곳 목록에 작업 파일 목록이 없다 — 저장소를 다시 훑는다');
      if (PC곳다름) 기록('기기에 둔 곳 목록이 PC 폴더 곳과 다르거나 못 읽은 곳이 있다 — 다시 훑는다');
      const 곳들 = PC곳이름들 ? await PC곳들읽기() : await 상태.통로.부서저장소들();
      곳목록 = 곳들.map((곳) => ({ 이름: 곳.이름, 문서들: 곳.목록.filter((p) => 읽을문서인가(곳.이름, p)).sort(),
        작업파일들: 곳.목록.filter((p) => 작업파일꼴.test(p)), 판: 곳목록판, ...(곳.오류 ? { 목록오류: 곳.오류 } : {}) }));
      저장쓰기(곳목록자리, 곳목록);
      기록(`곳 목록을 정했다 — 작업 파일 ${곳목록.reduce((n, 곳) => n + 곳.작업파일들.length, 0)}개`);
    }
    let 받음 = 0, 안바뀜 = 0, 적은칸 = 0;
    const 오류 = {}, 남길것 = {};
    await Promise.all(곳목록.flatMap((곳) => 곳.문서들.map(async (경로) => {
      const k = 곳.이름 + '/' + 경로, 옛 = 문서[k];
      try {
        const f = await 상태.통로.파일읽기(곳.이름, 경로, 옛 && 옛.지문);
        if (!f) return;                                   // 파일이 정말 없어졌다 //
        if (f.안바뀜) { 남길것[k] = 옛; 안바뀜++; return; }   // 안 바뀐 문서는 기기에 다시 적지 않는다 //
        남길것[k] = { 글: f.글, 지문: f.지문, 시각: await 상태.통로.마지막커밋(곳.이름, 경로) }; 받음++;
        if (문서칸쓰기(k, 남길것[k])) 적은칸++;            // 새로 받은 문서만 그 칸 하나를 적는다 //
      } catch (e) { 오류[k] = e.message; if (옛) 남길것[k] = 옛; 기록(`ERROR ${k} 못 읽음 — ${e.message}`); }
    })));
    // 기기에 둔 작업 파일은 목록에 남아 있는 것만 그대로 둔다 — 작업 파일은 여는 순간 지문으로 묻는다(bp-작업) //
    for (const 곳 of 곳목록) for (const p of 곳.작업파일들 || []) { const k = 곳.이름 + '/' + p; if (문서[k]) 남길것[k] = 문서[k]; }
    // 박스를 열 때 받은 갈 곳 파일(의회·설계실 박스가 맞대는 파일)도 그대로 둔다 — 박스를 열 때마다 지문으로 묻는다(bp-의회) //
    for (const k of Object.keys(문서)) if (k.startsWith('갈곳:')) 남길것[k] = 문서[k];
    // 목록에서 빠진 문서는 기기에서 지운다 //
    const 지울것 = Object.keys(문서).filter((k) => !(k in 남길것));
    for (const k of 지울것) 문서칸지우기(k);
    문서 = 남길것;
    기록(`기기 저장 — 문서 칸 ${적은칸}개를 적고 ${지울것.length}개를 지웠다(안 바뀐 ${안바뀜}개는 그대로)`);
    상태.문서오류 = 오류;
    상태.맞춘때 = new Date().toISOString(); 저장쓰기(맞춘때자리, 상태.맞춘때);
    상태.알림 = '';
    저장에서짓기(); 줄고르기();
    기록(`SUCCESS 모두읽기 — ${상태.곳들.length}곳 · 새로 받음 ${받음} · 안 바뀜 ${안바뀜} · 못 읽음 ${Object.keys(오류).length} · 법안 ${상태.의회 ? 상태.의회.length : '못 읽음'}`);
  } catch (e) {
    상태.알림 = '원본과 못 맞췄다 — 지난번 내용을 보이는 중: ' + e.message;
    기록('ERROR 모두읽기 — ' + e.message);
  }
  상태.맞추는중 = false; 그리기();
  if (상태.통로 && 상태.통로.받아오기 && !받기안함) 받아오고다시읽기();
}

// [관리부 작업 443] bp-백엔드 「상황판은 원본에서 그때그때 읽은 문서로 화면을 그린다」 조 ②③ — PC 앱은 PC 폴더로 먼저 그린 뒤, //
//   관리부 저장소와 docs/설계실.md가 있는 부서·프로젝트 저장소를 GitHub에서 받아 온다(폰 상황판이 적는 것은 관리부 의회 파일과 //
//   곳마다의 설계실 파일뿐이다 — [관리부 작업 454]). 새 커밋이 들어왔으면 다시 읽어 바꿔 끼우고, 못 받으면 시각 줄에 까닭을 붙인다. //
async function 받아오고다시읽기() {
  상태.받는중 = true; 상태.받기실패글 = ''; 그리기();
  const 처음 = Date.now();
  const 받을곳 = [...new Set([의회자리.저장소, ...(곳목록 || []).filter((곳) => 곳.문서들.includes(설계실경로)).map((곳) => 곳.이름)])];
  try {
    기록(`받아 오기 — ${받을곳.join('·')}`);
    const r = await 상태.통로.받아오기(받을곳);
    if (r.못받음.length) { 상태.받기실패글 = `GitHub에서 못 받아 왔다 — ${r.못받음.map((x) => x.까닭).join(' · ')}`; 기록('ERROR ' + 상태.받기실패글); }
    기록(`받아 오기 끝 — ${Date.now() - 처음}ms · 새 커밋 든 곳 ${r.바뀜.length ? r.바뀜.join('·') : '없음'}`);
    상태.받는중 = false;
    if (r.바뀜.length) { await 모두읽기(false, true); return; }
  } catch (e) { 상태.받기실패글 = `GitHub에서 못 받아 왔다 — ${e.message}`; 기록('ERROR ' + 상태.받기실패글); }
  상태.받는중 = false; 그리기();
}

// 답을 적은 파일의 글로 그 자리를 갈아 끼운다 — 답을 찍은 뒤 「찍었다」와 「문서에 있다」가 갈라지지 않게. //
// ★글과 시각은 커밋 응답에서 온 것(GitHub이 받아 적은 그 글)이라 파일을 다시 읽지 않는다 — 찍기가 GitHub을 두 번만 오간다([작업 395]). //
function 적은글넣기(저장소, 경로, 글, 시각) {
  const 곳 = 상태.곳들.find((x) => x.저장소 === 저장소);
  if (저장소 === 의회자리.저장소 && 경로 === 의회자리.경로) 상태.의회 = 법안읽기(글, 'assembly.md');
  else if (경로 === 설계실경로) {
    // 그 설계안이 있는 곳의 설계실만 갈아 끼운다 //
    const 실 = 상태.설계실.find((x) => x.저장소 === 저장소);
    if (실) 실.안들 = 법안읽기(글, '설계실.md'); else 상태.설계실.push({ 저장소, 안들: 법안읽기(글, '설계실.md'), 오류: '' });
  }
  if (곳 && 시각) 곳.시각[경로] = 시각;
}

