// [관리부 작업 464] 안 파일(의회 파일 · 설계실 파일)을 읽어 안마다 최종 답과 코멘트를 입힌다 — bp-결재 「답과 코멘트 찍기와 최종 답 고르기」 조 ⑦ · //
//   「찍은 답을 답 파일로 원본에 전달하기와 「전달 안 됨」 딱지」 조 ⑩: 그 저장소의 원본 답 파일과 기기에 남은 답 파일을 더해 //
//   최종답() · 최종코멘트()로 고른다. 안 파일에 이미 적힌 답 줄 · 코멘트 줄은 그 자리에 답 파일이 없을 때만 쓴다. //
//   제목이 같은 안이 없는 답 파일은 어느 안에도 입히지 않는다(그려지지 않는다). //
// 한계: 안마다 안 파일 글을 다시 훑는다 — 66KB · 안 33개에 24ms(PC, 2026-10-14) · 바꿀 때: 폰에서 누를 때 끊김이 느껴지면 //
//   안 파일을 한 번만 훑어 안마다 옛 답 줄 · 코멘트 줄을 모아 두고 최종답() · 최종코멘트()에 넘긴다. //
function 안들읽기(저장소, 경로, 글) {
  const 안들 = 법안읽기(글, 경로.split('/').pop());
  const 파일들 = [...(상태.원본답[저장소] || []), ...전달줄.filter((a) => a.저장소 === 저장소).map((a) => ({ 이름: a.이름, 값: a.값 }))]
    .filter((f) => f.값.문서 === 경로);
  for (const it of 안들) {
    const 제목줄 = '## ' + it.제목, 안 = 안이름(제목줄);
    const 답 = 최종답(글, 경로, 안, 파일들, 제목줄);
    it.표시 = 답 === '없음' ? '' : 답;
    it.코멘트 = 최종코멘트(글, 경로, 안, 파일들, 제목줄);
  }
  return 안들;
}
