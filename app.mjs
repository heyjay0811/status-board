//   · 묶음 안에서는 곳시각이 늦은 곳이 앞이다 — 곳시각은 부서·프로젝트면 그 곳 docs/work.md와 docs/bp-*.md 가운데 가장 늦은 //
//     마지막 커밋 시각, 규칙안목록이면 관리부 docs/assembly.md, 설계실이면 부서·프로젝트마다의 docs/설계실.md 가운데 가장 늦은 마지막 커밋 시각이다. //
const 시각값 = (시각) => (시각 ? Date.parse(시각) : -Infinity);
const 가장늦은 = (시각들) => 시각들.filter(Boolean).sort((a, b) => 시각값(b) - 시각값(a))[0] || null;
const 곳시각 = (곳) => 가장늦은(Object.entries(곳.시각).filter(([경로]) => 경로 === 'docs/work.md' || 설계꼴.test(경로)).map(([, t]) => t));
// 설계실 — 곳마다의 설계안 수를 더한다. 못 읽은 설계실이 하나라도 있으면 수를 모른다(null — 「–」) — 읽은 것만 더한 모자란 수를 //
//   찍으면 못 읽은 설계안이 「없음」처럼 보인다(bp-백엔드 · [관리부 작업 443] 2026-10-21 사용자 「3」) //
const 설계실다읽음 = () => 상태.설계실.every((x) => x.안들);
const 설계안수 = () => (설계실다읽음() ? 상태.설계실.reduce((n, x) => n + x.안들.length, 0) : null);
const 설계실시각 = () => 가장늦은(상태.곳들.map((곳) => 곳.시각[설계실경로]));
function 줄들() {
  const 관리부곳 = 상태.곳들.find((x) => x.저장소 === 규칙안목록자리.저장소);
  const 관리부시각 = (경로) => (관리부곳 && 관리부곳.시각[경로]) || null;
  const 줄 = 상태.곳들.map((곳) => ({ 키: '곳:' + 곳.저장소, 종류: '곳', 곳, 이름: 곳.이름, 부서: 부서인가(곳.저장소),
    수: 곳.작업계획 ? 곳.작업계획.length : null, 수뜻: '작업계획 목록의 작업계획 수', 시각: 곳시각(곳) }));
  if (관리부곳) 줄.push({ 키: '규칙안목록', 종류: '규칙안목록', 이름: '규칙안 목록', 부서: true, 수: 상태.규칙안목록 ? 상태.규칙안목록.length : null, 수뜻: '규칙안 목록에 올라온 규칙안 수', 시각: 관리부시각(규칙안목록자리.경로) });
  if (상태.곳들.length) {
    const 못읽음 = 상태.설계실.filter((x) => !x.안들).map((x) => 보일이름(x.저장소));
    줄.push({ 키: '설계실', 종류: '설계실', 이름: '설계실', 부서: true, 수: 설계안수(), 시각: 설계실시각(),
      수뜻: `부서·프로젝트마다의 설계실에 올라온 설계안 수의 합(설계실 ${상태.설계실.length}곳${못읽음.length ? ` · 못 읽어 수를 모름: ${못읽음.join(', ')}` : ''})` });
  }
  if (관리부곳) {
    // 규칙 지도 — 부서 묶음에 서고, 단추 수는 아직 옮기지 않은 규칙 수다(bp-규칙지도) //
    const 지도글 = 상태.원문[`${규칙안목록자리.저장소}/${규칙지도경로}`];
    if (지도글 !== undefined) 줄.push({ 키: '규칙지도', 종류: '규칙지도', 이름: '규칙 지도', 부서: true, 수: 규칙지도셈(규칙지도읽기(지도글)).남음, 수뜻: '아직 옮기지 않은 규칙 수', 시각: 관리부시각(규칙지도경로) });
  }
  // 부서 묶음 먼저 → 곳시각이 늦은 곳부터 → 시각이 같거나 없으면 이름순 //
  return 줄.sort((a, b) => (b.부서 - a.부서) || (!!b.맨앞 - !!a.맨앞) || (시각값(b.시각) - 시각값(a.시각)) || a.이름.localeCompare(b.이름, 'ko'));
}
// 모바일 앱([관리부 작업 475]) — 펼친 곳 = 마지막에 누른 곳 하나 또는 없음(줄기의 곳). 고정은 없다 //
const 펼친가 = (키) => (폰 ? 키 === 상태.줄기.곳 : 키 === 상태.고른줄 || 상태.고정.has(키));
// bp-프론트엔드 — 펼친 곳은 고정한 차례(먼저 고정한 곳이 위) → 고른 곳 차례로 선다. 위 칸의 차트와 뷰어 칸의 뷰어가 같은 차례다. //
function 펼친줄들(줄) {
  if (폰) return 줄.filter((x) => x.키 === 상태.줄기.곳);
  const 키들 = [...상태.고정];
  if (상태.고른줄 && !상태.고정.has(상태.고른줄)) 키들.push(상태.고른줄);
  return 키들.map((k) => 줄.find((x) => x.키 === k)).filter(Boolean);
}
// 박스를 연 항목이 어느 곳에 딸렸나 — 박스는 그 곳 뷰어의 박스 칸에 선다 //
const 열린줄키 = (열쇠) => {
  const [종류, a] = String(열쇠).split(':');
  return 종류 === '작업계획' ? '곳:' + a : 종류 === '규칙글' ? '규칙지도' : 종류;
};

// bp-부서프로젝트목록 — 열 때와 「↻」 때(사용자가 아직 단추를 안 만졌으면) PC 앱은 고정을 모두 풀고 가장 최근에 바뀐 곳 하나만 펼친다. //
