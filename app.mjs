// [관리부 작업 487] 턴 절 — bp-작업 제3조 ⑦ · bp-결재 제2조 ③ ⑧. 턴을 적힌 차례대로 늘어놓되 앞 턴은 턴줄 한 줄, 마지막 턴만 펼친다. //
//   단추섬(턴) = (턴 = 마지막 턴) AND (턴 상태 = 답 기다림) — 그 턴에만 옵션 단추 · 옵션 밖 답 칸 · 코멘트 칸 · 「이대로 진행」이 선다. //
//   고르는 중의 고름은 기기에만 둔다(턴고름 칸) — 「이대로 진행」을 누를 때 턴답 하나로 남는다. //
const 턴고름자리 = (저장소, 안) => `sb.턴고름:${저장소}:${안}`;
const 턴고름읽기 = (저장소, 안) => { const v = 저장읽기(턴고름자리(저장소, 안), null); return v && typeof v === 'object' ? { 고름: v.고름 || {}, 밖: v.밖 || {}, 코멘트: v.코멘트 || '' } : { 고름: {}, 밖: {}, 코멘트: '' }; };
const 턴고름쓰기 = (저장소, 안, v) => { if (!저장쓰기(턴고름자리(저장소, 안), v)) 기록(`ERROR 턴 고름을 기기에 못 적었다 — ${안}`); };
const 턴고름지우기 = (저장소, 안) => { try { localStorage.removeItem(턴고름자리(저장소, 안)); } catch (e) { 기록(`ERROR 턴 고름을 못 지웠다 — ${e.message}`); } };
// 보낼 고른것 — 정할 것마다 옵션 밖 글 → 고른 옵션 → [추천] 차례. 아무것도 없는 정할 것은 빠진 이름표로 돌려준다 //
function 턴고른것(턴, 고름) {
  const 고른것 = [], 빠짐 = [];
  for (const p of 턴.정할것) {
    const 밖 = (고름.밖[p.이름표] || '').trim();
    const 옵션 = 고름.고름[p.이름표] || (p.꼭고름 ? '' : p.추천 || '');
    if (밖) 고른것.push({ 이름표: p.이름표, 옵션: '', 글: 밖 });
    else if (옵션) 고른것.push({ 이름표: p.이름표, 옵션, 글: '' });
    else 빠짐.push(p.이름표);
  }
  return { 고른것, 빠짐 };
}
