// [관리부 작업 461] bp-프론트엔드 — //
//   상태.줄기 = { 바깥, 안 }. 바깥은 박스 열쇠(「규칙안목록:i」·「설계실:저장소:i」·「작업:저장소:i」)나 「카드:저장소/경로」, //
