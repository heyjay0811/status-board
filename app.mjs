  const 조각들 = 글.replace(/^# .*\r?\n/, '').split(/^(## .*)$/m).map((x, i) => (x.startsWith('## ') ? `<h3 class="작업계획절">${꾸미기(x.slice(3))}</h3>` : 꾸미기((i ? x : x.replace(/^(?:> |---\s*$)/gm, '')).trim())));
