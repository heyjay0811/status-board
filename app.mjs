// [관리부 작업 457] bp-백엔드 — 열 때마다 모든 곳의 파일 목록을 확인해 //
//   곳목록을 확인한 목록으로 바꿔 끼운다. 확인하지 못한 곳은 기기에 둔 목록을 그대로 쓰고 { 곳, 까닭 }을 못맞춘에 넣는다. //
//   PC 앱 — 곳마다 받아 온 GitHub 커밋의 파일 목록(앱 본체 docs-ipc.cjs — [관리부 작업계획 554] bp-백엔드 제2조 ⑤)을 다시 읽는다. //
//   모바일 앱 — GitHub에 저장소 목록을 한 번, 곳마다 마지막 커밋을 묻고 //
//     목록다시받기(곳) = (기기에 저장한 그 곳의 파일 목록 없음) OR (지금 마지막 커밋 ≠ 목록을 받을 때 저장한 마지막 커밋)인 곳만 목록을 다시 받는다(github.mjs 곳목록확인()). //
//   훑기(「↻ 다시 읽기」) — 모바일 앱은 커밋이 같아도 모든 저장소의 파일 목록을 다시 받는다. //
const 곳짓기 = (이름, 목록, 커밋) => ({ 이름, 문서들: 목록.filter((p) => 읽을문서인가(이름, p)).sort(),
  작업계획파일들: 목록.filter((p) => 작업계획파일형식.test(p)), 판: 곳목록판, ...(커밋 ? { 커밋 } : {}) });
// 기기에 그 곳의 파일 목록이 있나 — 판이 다르거나 작업계획 파일 목록이 없는 옛 판의 목록은 없는 것으로 친다 //
const 목록있음 = (곳) => !!곳 && 곳.판 === 곳목록판 && Array.isArray(곳.문서들) && Array.isArray(곳.작업계획파일들);
// 확인하지 못한 곳 — 기기에 둔 목록으로 그리고 까닭을 단다(목록이 없으면 빈 곳으로 단추만 세운다) //
const 못읽은곳 = (이름, 옛, 까닭) => (목록있음(옛) ? { ...옛, 목록오류: 까닭 } : { 이름, 문서들: [], 작업계획파일들: [], 판: 곳목록판, 목록오류: 까닭 });
async function 곳목록맞추기(훑기, 못맞춘) {
  const 옛곳 = new Map((곳목록 || []).map((x) => [x.이름, x]));
  let 새곳목록;
  if (PC곳이름들) {
    새곳목록 = (await PC곳들읽기()).map((곳) => {
      if (!곳.오류) return 곳짓기(곳.이름, 곳.목록);
      못맞춘.push({ 곳: 곳.이름, 까닭: `파일 목록 — ${곳.오류}` });
      return 못읽은곳(곳.이름, 옛곳.get(곳.이름), 곳.오류);
    });
  } else {
    const 알던 = {};
    for (const [이름, 커밋] of Object.entries(곳아님 || {})) 알던[이름] = { 커밋, 곳: false };
    for (const 곳 of 곳목록 || []) if (목록있음(곳) && 곳.커밋) 알던[곳.이름] = { 커밋: 곳.커밋, 곳: true };
    const 결과 = await 상태.통로.곳목록확인(알던, { 모두다시: 훑기 });
    새곳목록 = []; const 새곳아님 = {};
    for (const x of 결과) {
      const 옛 = 옛곳.get(x.이름);
      if (x.오류) {
        // 부서·프로젝트인지 아직 모르는 새 저장소를 못 읽은 것도 확인하지 못한 곳이다 — 그 곳일 수 있어서다 //
        못맞춘.push({ 곳: x.이름, 까닭: `${옛 || x.곳 ? '파일 목록' : '부서·프로젝트인지 가리지 못했다'} — ${x.오류}` });
        if (옛 || x.곳) 새곳목록.push(못읽은곳(x.이름, 옛, x.오류));
      } else if (x.곳) {
        // 그대로인 곳은 기기에 둔 목록을 쓴다 — 지난번에 못 읽어 단 까닭은 이번에 확인했으니 걷는다 //
        if (x.그대로) { const { 목록오류, ...깨끗 } = 옛; 새곳목록.push(깨끗); }
        else 새곳목록.push(곳짓기(x.이름, x.목록, x.커밋));
      }
      else 새곳아님[x.이름] = x.커밋;
    }
    곳아님 = 새곳아님; 저장쓰기(곳아님자리, 곳아님);
  }
  곳목록 = 새곳목록;
  저장쓰기(곳목록자리, 곳목록);
  기록(`곳 목록을 확인했다 — ${곳목록.length}곳 · 작업계획 파일 ${곳목록.reduce((n, 곳) => n + 곳.작업계획파일들.length, 0)}개 · 못 읽은 곳 ${곳목록.filter((x) => x.목록오류).length}`);
}

