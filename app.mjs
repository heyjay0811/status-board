// [관리부 작업 443] bp-설계 「상황판은 부서·프로젝트의 확정된 설계를 모듈마다 카드로 펼쳐 보이고, 모듈마다 구현과 검증이 얼마나 됐는지 센다」 조. //
//   칩 — 「설계 N모듈 · M조」: N = 그 곳 docs/ 바로 아래 bp-*.md 파일 수 · M = 그 파일들의 「## 제K조」 줄 수의 합. N이 0이면 「설계 없음」. //
//     PC 앱은 차트 「할 것」 칸의 설계 칩(progress-chart.mjs가 자리만 그린다)에 이 글을 채우고, 폰은 뷰어의 작업 목록 위에 둔다. //
//   카드 — 파일 이름 그대로 · 조 수 · 「🔧 a/b · ☑ c」(a = 구현 완료 줄이 붙은 항 수, b = 항 수, c = 검증 완료 줄이 붙은 항 수). //
//     카드를 누르면 조 제목 목록이, 조 제목을 누르면 그 조의 항이 펼쳐지고, 다시 누르면 접힌다. 못 읽은 파일은 그 카드에 알린다. //
// ★설계 문서는 읽기만 한다 — 답이나 표시를 적지 않는다. //
function 설계칩글(곳) {
  const 파일 = 곳.설계 || [];
  if (!파일.length) return '설계 없음';
  const 조 = 파일.reduce((n, f) => n + (f.읽음 ? f.읽음.조수 : 0), 0);
  return `설계 ${파일.length}모듈 · ${조}조${파일.some((f) => f.오류) ? ' · ⚠' : ''}`;
}
function 설계칩채우기() {
  for (const 칩 of 본문.querySelectorAll('.chip[data-설계칩]')) {
    const 곳 = 상태.곳들.find((x) => x.저장소 === 칩.dataset.설계칩);
    칩.textContent = 곳 ? 설계칩글(곳) : '설계 —';
    칩.classList.toggle('켜짐', !!곳 && 보기(곳.저장소) === '설계');
  }
}
function 설계카드글(곳) {
  const 파일 = 곳.설계 || [];
  if (!파일.length) return '<p class="안내">이 곳에는 확정된 설계(docs/bp-*.md)가 없다.</p>';
  return '<div class="설계카드들">' + 파일.map((f) => {
    const 키 = `${곳.저장소}/${f.경로}`, 이름 = f.경로.split('/').pop(), r = f.읽음;
    const 열림 = (k) => (설계열림(k) ? ' open' : '');
    // 못 읽은 파일의 까닭은 카드 머리에 둔다 — 카드를 펼치지 않아도 보이게 //
    const 알림 = f.오류 ? `<span class="오류 설계오류">${r ? '새로 못 읽어 지난번 받은 글을 보이는 중 — ' : '못 읽었다 — '}${막기(f.경로)}: ${막기(f.오류)}</span>` : '';
    const 진척 = r ? `${r.조수}조 · 🔧 ${r.구현수}/${r.항수} · ☑ ${r.검증수}` : '못 읽음';
    const 조들 = r ? r.조.map((조, i) => `<details class="설계조" data-설계펼침="${막기(키 + '#' + i)}"${열림(키 + '#' + i)}>`
      + `<summary>${꾸미기(조.제목)}</summary><div class="설계항들">`
      + (조.항.length ? 조.항.map((h) => `<div class="설계항 본문글">${꾸미기(h.글)}</div>`).join('') : '<p class="안내">항이 없다.</p>')
      + '</div></details>').join('') : '';
    return `<details class="설계카드" data-설계펼침="${막기(키)}"${열림(키)}><summary><span class="설계카드이름">${막기(이름)}</span>`
      + `<span class="설계진척">${막기(진척)}</span>${알림}</summary>${조들}</details>`;
  }).join('') + '</div>';
}
