  //   맞대 바뀐 곳을 따로 셈하지 않는다(bp-의회 「상황판 의회 화면은 조문을 팝업 박스 하나로 열고, 갈 자리와 바뀔 내용을 함께 보여준다」 조 ⑤ · //
  //   「법안 종류와 고치는 글의 표시 읽기」 조 ②~⑤ · bp-설계실 「상황판 설계실 화면은 …의회 화면과 같은 박스로 연다」 조 ② — 설계실 박스도 이 코드다). //
