// [관리부 작업 443] bp-진행현황 — 규칙안목록·설계실 현황 한 줄에 넘길 값. //
//   기다림 = 규칙안목록이면 관리부 규칙안목록 파일에 올라 있는 규칙안 수, 설계실이면 부서·프로젝트마다의 설계실 파일에 올라 있는 설계안 수의 합 · //
//   답찍힘 = 그 가운데 답 찍기 모듈이 내놓는 최종 답이 확인인 안 수([관리부 작업 464 · 545] — 안들읽기()가 입힌 it.표시, //
//   곧 안 파일 · 원본 답 파일 · 기기에 남은 답 파일을 answer-file.mjs 최종답()으로 고른 것). //
//   막대는 규칙안목록이면 관리부 규칙안목록 이력, 설계실이면 곳마다의 설계실 이력을 모은 줄마다 끝 칸 날짜로 긋는다 — 그 글을 넘기고(설계실은 //
//   곳마다의 글을 줄바꿈으로 이어 붙인다 — [관리부 작업 454]), 못 읽은 곳이 있으면 까닭을 넘긴다. //
const 답찍힘인가 = (it) => it.표시 === '확인';
function 현황자료(종류) {
  const 경로 = 이력경로[종류];
  if (종류 === '규칙안목록') {
    const k = 규칙안목록자리.저장소 + '/' + 경로;
    const 관리부곳 = (곳목록 || []).find((x) => x.이름 === 규칙안목록자리.저장소);
    const 있음 = !!관리부곳 && 관리부곳.문서들.includes(경로);
    const 관리부 = 상태.곳들.find((x) => x.저장소 === 규칙안목록자리.저장소);
    const 안들 = 상태.규칙안목록;
    return {
      이력경로: '관리부 ' + 경로,
      이력글: 상태.원문[k] ?? null,
      이력오류: 상태.문서오류[k] || (!있음 ? `관리부 저장소 파일 목록에 ${경로}가 없다` : 상태.원문[k] === undefined ? `${경로}를 아직 받지 못했다` : ''),
      기다림: 안들 ? 안들.length : null,
      답찍힘: 안들 ? 안들.filter(답찍힘인가).length : null,
      마지막커밋: (관리부 && 관리부.시각[규칙안목록자리.경로]) || null,
    };
  }
  const 있는곳 = (곳목록 || []).filter((x) => x.문서들.includes(경로));
  const 글들 = [], 오류들 = [];
  for (const 곳 of 있는곳) {
    const k = 곳.이름 + '/' + 경로;
    if (상태.문서오류[k]) 오류들.push(`${보일이름(곳.이름)}: ${상태.문서오류[k]}`);
    if (상태.원문[k] !== undefined) 글들.push(상태.원문[k]);
    else if (!상태.문서오류[k]) 오류들.push(`${보일이름(곳.이름)}: 아직 받지 못했다`);
  }
  if (!있는곳.length) 오류들.push(`어느 곳의 파일 목록에도 ${경로}가 없다`);
  const 읽은 = 상태.설계실.filter((x) => x.안들);
  return {
    이력경로: '곳마다 ' + 경로,
    이력글: 글들.join('\n'),
    이력오류: 오류들.join(' · '),
    기다림: 설계안수(),
    답찍힘: 설계실다읽음() ? 읽은.reduce((n, x) => n + x.안들.filter(답찍힘인가).length, 0) : null,
    마지막커밋: 설계실시각(),
  };
}

// ── 설계 ─────────────────────────────────────────────────────────────── //
// [관리부 작업 443] 상황판은 부서·프로젝트의 확정된 설계를 모듈마다 카드로 펼쳐 보이고, 모듈마다 구현과 검증이 얼마나 됐는지 센다(bp-설계). //
//   칩 — 「설계 N모듈 · M조」: N = 그 곳 docs/ 바로 아래 bp-*.md 파일 수 · M = 그 파일들의 「## 제K조」 줄 수의 합. N이 0이면 「설계 없음」. //
//     PC 앱은 차트 「할 것」 칸의 설계 칩(progress-chart.mjs가 자리만 그린다)에 이 글을 채우고, 폰은 뷰어의 작업계획 목록 위에 둔다. //
//   카드 — 파일 이름 그대로 · 조 수 · 「🔧 a/b · ☑ c」(a = 구현 완료 줄이 붙은 항 수, b = 항 수, c = 검증 완료 줄이 붙은 항 수). //
//     카드를 누르면 조 제목 목록이, 조 제목을 누르면 그 조의 항이 펼쳐지고, 다시 누르면 접힌다. 못 읽은 파일은 그 카드에 알린다. //
// ★설계 문서는 읽기만 한다 — 답이나 표시를 적지 않는다. //
function 설계칩글(곳) {
  const 파일 = 곳.설계 || [];
  if (!파일.length) return '설계 없음';
  const 조 = 파일.reduce((n, f) => n + (f.읽음 ? f.읽음.조수 : 0), 0);
  return `설계 ${파일.length}모듈 · ${조}조${파일.some((f) => f.오류) ? ' · ⚠' : ''}`;
}
function 설계칩채우기() {
  for (const 칩 of 본문.querySelectorAll('.chip[data-설계칩]')) {
    const 곳 = 상태.곳들.find((x) => x.저장소 === 칩.dataset.설계칩);
    칩.textContent = 곳 ? 설계칩글(곳) : '설계 —';
    칩.classList.toggle('켜짐', !!곳 && 보기(곳.저장소) === '설계');
  }
}
function 설계카드글(곳) {
  const 파일 = 곳.설계 || [];
  if (!파일.length) return '<p class="안내">이 곳에는 확정된 설계(docs/bp-*.md)가 없다.</p>';
  return '<div class="설계카드들">' + 파일.map((f) => {
    const 키 = `${곳.저장소}/${f.경로}`, 이름 = f.경로.split('/').pop(), r = f.읽음;
    const 열림 = (k) => (설계열림(k) ? ' open' : '');
    // 못 읽은 파일의 까닭은 카드 머리에 둔다 — 카드를 펼치지 않아도 보이게 //
    const 알림 = f.오류 ? `<span class="오류 설계오류">${r ? '새로 못 읽어 지난번 받은 글을 보이는 중 — ' : '못 읽었다 — '}${막기(f.경로)}: ${막기(f.오류)}</span>` : '';
    const 진척 = r ? `${r.조수}조 · 🔧 ${r.구현수}/${r.항수} · ☑ ${r.검증수}` : '못 읽음';
    const 조들 = r ? r.조.map((조, i) => `<details class="설계조" data-설계펼침="${막기(키 + '#' + i)}"${열림(키 + '#' + i)}>`
      + `<summary>${꾸미기(조.제목)}</summary><div class="설계항들">`
      + (조.항.length ? 조.항.map((h) => `<div class="설계항 본문글">${꾸미기(h.글)}</div>`).join('') : '<p class="안내">항이 없다.</p>')
      + '</div></details>').join('') : '';
    return `<details class="설계카드" data-설계펼침="${막기(키)}"${열림(키)}><summary><span class="설계카드이름">${막기(이름)}</span>`
      + `<span class="설계진척">${막기(진척)}</span>${알림}</summary>${조들}</details>`;
  }).join('') + '</div>';
}
// 카드·조는 <details>라 누르면 브라우저가 먼저 펼치고 접는다 — 그 toggle로 줄기를 고친 뒤, 줄기에 없는 다른 카드·조의 open을 걷는다. //
//   다시 그릴 때 open을 달고 선 <details>도 toggle을 내는데, 이미 줄기에 있는 것이라 줄기가 그대로다(stem.mjs 바깥열기·안열기). //
document.addEventListener('toggle', (e) => {
  const d = e.target;
  if (!d || !d.dataset || !d.dataset.설계펼침) return;
  const k = d.dataset.설계펼침, i = k.lastIndexOf('#');
  const 바깥 = 카드머리 + (i < 0 ? k : k.slice(0, i));
  const 새 = d.open ? (i < 0 ? 바깥열기(상태.줄기, 바깥) : 안열기(상태.줄기, 바깥, k)) : 접기(상태.줄기, i < 0 ? 바깥 : k);
  줄기바꾸기(새, d.open ? `설계 펼침 ${k}` : `설계 접음 ${k}`);
}, true);

