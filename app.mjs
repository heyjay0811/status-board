// 규칙 글 — PC 앱은 규칙 지도를 열 때, 모바일 앱은 박스를 열 때 그 저장소에서 읽는다(bp-규칙지도) //
상태.규칙글 = {};
async function 규칙글받기(저장소, 경로) {
  const k = 저장소 + '/' + 경로;
  try {
    const f = await 상태.통로.파일읽기(저장소, 경로);
    상태.규칙글[k] = f ? { 글: f.글 } : { 오류: '파일이 없다' };
    기록(f ? `SUCCESS 규칙 글 읽음 — ${k}` : `ERROR 규칙 글 파일이 없다 — ${k}`);
  } catch (e) {
    상태.규칙글[k] = { 오류: e.message };
    기록(`ERROR 규칙 글을 못 읽었다 — ${k}: ${e.message}`);
  }
}
// 줄마다 여는 글을 한 번에 읽어 분량을 채운다 — 파일 하나를 여러 줄이 열어도 한 번만 읽는다(bp-규칙지도) //
let 분량읽는중 = false;
async function 규칙분량읽기(묶음들) {
  const 자리들 = new Map(묶음들.flatMap((x) => x.규칙들).map((r) => 규칙글자리(r.자리)).filter(Boolean).map((자리) => [`${자리.저장소}/${자리.경로}`, 자리]));
  const 읽을것 = [...자리들].filter(([k]) => !상태.규칙글[k]);
  if (분량읽는중 || !읽을것.length) return;
  분량읽는중 = true;
  await Promise.all(읽을것.map(([, 자리]) => 규칙글받기(자리.저장소, 자리.경로)));
  분량읽는중 = false;
  그리기();
}
async function 규칙글읽기(저장소, 경로) {
  const k = 저장소 + '/' + 경로;
  상태.규칙글[k] = { 읽는중: true };
  기록(`START 규칙 글 읽기 — ${k}`);
  박스그리기();
  await 규칙글받기(저장소, 경로);
  박스그리기();
}
// 규칙 글 박스 머리의 판정 단추 — 확인 · 제거는 누르는 순간 저장, 변경은 글 칸을 펴 「보내기」로 저장(bp-규칙지도) //
