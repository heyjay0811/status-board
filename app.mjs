// [관리부 작업 475] bp-부서프로젝트목록 — 모바일 앱의 첫 화면. 부서·프로젝트 단추만 큰 칸으로, 부서 묶음을 먼저 · 프로젝트 묶음을 뒤에 세우는 차례대로 늘어놓는다. //
//   칸마다 이름(한글 이름) · 폴더 이름(한글 이름과 같으면 비운다 — 같은 글을 두 번 보이지 않게) · 그 곳의 현재 작업 수(오른쪽 위). //
//   규칙안목록·설계실은 폴더가 없어 그 자리에 수가 무엇을 세는지(규칙안 · 설계안)를 적는다. 📌는 두지 않는다. //
//   묶음은 색이 아니라 묶음 이름표와 칸막이(자리)로 가르고, 칸 모양은 설계 모듈 카드와 같은 카드 모양을 쓴다(app.css .큰단추). //
function 큰단추글(줄) {
  const 단추 = (x) => {
    const 까닭 = x.곳 && (x.곳.줄까닭 || x.곳.오류.join(' / '));
    const 이름 = x.곳 ? 곳이름[x.곳.저장소] || x.곳.저장소 : x.이름;
    const 아래 = x.곳 ? (이름 === x.곳.저장소 ? '' : x.곳.저장소) : x.종류 === '규칙안목록' ? '규칙안' : x.종류 === '규칙지도' ? '안 옮긴 규칙' : '설계안';
    return `<button type="button" class="큰단추" data-펼침="${막기(x.키)}" title="누르면 이 곳만 화면 전체로 연다">`
      + `<span class="큰단추머리"><span class="큰단추이름">${막기(이름)}</span>`
      + (까닭 ? `<span class="못읽음표" title="${막기(까닭)}">⚠</span>` : '')
      + (x.수없음 ? '' : `<span class="수" title="${막기(x.수뜻)}">${x.수 == null ? '–' : x.수}</span>`) + '</span>'
      + `<span class="큰단추폴더">${막기(아래)}</span></button>`;
  };
  const 묶음 = (이름, 목록) => (목록.length ? `<section class="큰단추묶음" aria-label="${이름}"><h2 class="묶음이름">${이름}</h2>`
    + `<div class="큰단추칸">${목록.map(단추).join('')}</div></section>` : '');
  const 부서 = 줄.filter((x) => x.부서), 프로젝트 = 줄.filter((x) => !x.부서);
  if (!줄.length) return '<p class="안내">보일 부서·프로젝트가 없다 — 「↻」로 다시 읽는다.</p>';
  return `<div class="첫화면" role="navigation" aria-label="부서·프로젝트">${묶음('부서', 부서)}`
    + (부서.length && 프로젝트.length ? '<hr class="큰묶음칸막이">' : '') + `${묶음('프로젝트', 프로젝트)}</div>`;
}

// 위 칸의 차트 자리(PC 앱) — 부서·프로젝트는 그 곳의 진행 현황 차트, 규칙안목록·설계실은 현황 한 줄(bp-진행현황). //
