// 가짜 GitHub — { '저장소/경로': { 글, sha } }. PUT 수를 센다. 실패를 흉내 내려면 넘김.PUT에 상태 번호를 넣는다 //
function 가짜GitHub(파일들, 넘김 = {}) {
  let 번호 = 0; const 셈 = { PUT: 0 };
  const 응답 = (상태, 값) => ({ status: 상태, text: async () => JSON.stringify(값) });
  const fetch = async (주소, 옵션) => {
    if (넘김.끊김) throw new TypeError('Failed to fetch');
    const m = new URL(주소).pathname.match(/^\/repos\/heyjay0811\/([^/]+)\/contents\/(.+)$/);
    if (!m) return 응답(500, { message: '가짜가 모르는 요청' });
    const k = decodeURIComponent(m[1]) + '/' + decodeURIComponent(m[2]);
    if (옵션.method === 'GET') return 파일들[k] ? 응답(200, { type: 'file', content: b64(파일들[k].글), sha: 파일들[k].sha }) : 응답(404, { message: 'Not Found' });
    셈.PUT++;
    if (넘김.PUT) return 응답(넘김.PUT, { message: '흉내 낸 실패' });
    const 몸 = JSON.parse(옵션.body);
    if (파일들[k].sha !== 몸.sha) return 응답(409, { message: 'sha does not match' });
    파일들[k] = { 글: 글로(몸.content), sha: 's' + (++번호) };
    return 응답(200, { content: { sha: 파일들[k].sha }, commit: { sha: 'c0ffee' + 번호 + '000000', committer: { date: '2026-10-13T01:02:03Z' } } });
  };
  return { fetch, 셈 };
}

