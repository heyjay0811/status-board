// 가짜 GitHub — { '저장소/경로': 글 }. sha 없는 PUT은 새 파일 만들기(없으면 201, 있으면 422). 요청마다 { 방법, 경로, keepalive }를 남긴다 //
//   넘김.PUT에 상태 번호를 넣으면 PUT이 그 번호로 실패하고, 넘김.끊김이면 그물이 끊긴 것처럼 던진다 //
function 가짜GitHub(파일들, 저장소들, 넘김 = {}) {
  const 기록 = [];
  const 응답 = (상태, 값) => ({ status: 상태, text: async () => JSON.stringify(값) });
  const fetch = async (주소, 옵션) => {
    if (넘김.끊김) throw new TypeError('Failed to fetch');
    const m = new URL(주소).pathname.match(/^\/repos\/heyjay0811\/([^/]+)\/contents\/(.+)$/);
    if (!m) return 응답(500, { message: '가짜가 모르는 요청' });
    const 저장소 = decodeURIComponent(m[1]), k = 저장소 + '/' + decodeURIComponent(m[2]);
    기록.push({ 방법: 옵션.method, 경로: k, keepalive: !!옵션.keepalive });
    if (!저장소들.includes(저장소)) return 응답(404, { message: 'Not Found' });
    if (옵션.method === 'GET') return k in 파일들 ? 응답(200, { type: 'file', content: b64(파일들[k]), sha: 's' }) : 응답(404, { message: 'Not Found' });
    if (넘김.PUT) return 응답(넘김.PUT, { message: '흉내 낸 실패' });
    const 몸 = JSON.parse(옵션.body);
    if ('sha' in 몸) return 응답(500, { message: '이 시험에서 sha를 실은 PUT은 없어야 한다' });
    if (k in 파일들) return 응답(422, { message: 'Invalid request.\n\n"sha" wasn\'t supplied.' });
    파일들[k] = 글로(몸.content);
    return 응답(201, { content: { sha: 'n' }, commit: { sha: 'c0ffee0000000', committer: { date: '2026-10-14T03:15:23Z' } } });
  };
  return { fetch, 기록 };
}

