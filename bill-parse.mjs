// 소속 칸 맨 앞의 주인 → 저장소. 긴 이름부터 맞춘다(「일톡 자동 주문 수집기」가 「일톡」에 먼저 걸리지 않게). //
// 회장실·전역으로 갈 법안은 관리부에 센다 — 관리부가 공통 자리를 맡는 부서이기 때문이다(제2조 ⑨). //
const 주인표 = Object.entries(곳이름).map(([저장소, 이름]) => [이름, 저장소])
  .concat([['일톡 자동 주문', '1talk-app-auto-order'], ['회장실', 'management'], ['전역', 'management']])
  .sort((a, b) => b[0].length - a[0].length);
export function 주인저장소(갈곳) {
  const t = String(갈곳 || '').trim();
  const 맞음 = 주인표.find(([이름]) => t === 이름 || t.startsWith(이름 + ' '));
  return 맞음 ? 맞음[1] : null;
}

// [관리부 작업 448] 제11조 ① — 관리부 설계실 하나의 설계안을 갈 곳의 부서·프로젝트 머리 줄로 묶는다. //
//   머리줄(설계안) = 갈 곳 칸 맨 앞의 주인 이름이 가리키는 부서·프로젝트(법안읽기()가 단 `곳`). 주인 이름을 못 알아보는 갈 곳 //
//   (공통 자원 지도 같은 것)이나 화면에 없는 곳은 관리부 머리 줄에 놓는다. 설계안이 없는 곳도 머리 줄은 세운다. //
// 받는 것: 설계안 배열 · 머리 줄을 세울 저장소 이름들(화면의 곳 차례). 돌려주는 것: [{ 저장소, 안: [{ 항목, 번째 }] }] — 번째는 설계안 배열의 자리. //
export function 설계안묶기(설계안들, 저장소들) {
  const 묶음 = 저장소들.map((저장소) => ({ 저장소, 안: [] }));
  let 관리부묶음 = 묶음.find((x) => x.저장소 === 'management');
  if (!관리부묶음) { 관리부묶음 = { 저장소: 'management', 안: [] }; 묶음.unshift(관리부묶음); }
  (설계안들 || []).forEach((항목, 번째) => {
    (묶음.find((x) => x.저장소 === 항목.곳) || 관리부묶음).안.push({ 항목, 번째 });
  });
  return 묶음;
}

// 들어갈 문서 — 소속 앞부분에서 조·항 자리(「 · 제5조 …」 · 「 제1조 추가」 · 「 새 파일 …」)를 뗀 「주인 종류 이름」. //
export function 들어갈문서(제목) {
  return 소속앞부분(소속전문꺼내기(제목)).replace(/\s[·|]\s.*$/, '').replace(/\s+(제\d+조|새 파일|머리|\d+행|\d+절).*$/, '').trim();
}

// 항목 종류 — 의회 법안은 신설·변경·삭제, 설계실 설계안은 추가·변경·제거. 답 단추 둘을 고르는 데 쓴다(제4조 ③ · 제11조 ③). //
// [관리부 작업 443] 종류는 소속 칸의 낱말 무늬가 아니라 법안 몸으로 가린다(의회 스킬 제4조 ③ — 있는 조를 고치는 법안은 //
//   항을 지우든 바꾸든 더하든 그 조의 변경 법안 하나이고, 조가 통째로 없어질 때만 제목이 「삭제 — 」로 시작한다). //
//   · 제목이 「삭제 — 」로 시작하면 삭제(설계실은 제거). //
//   · 항이나 항 밖 줄에 (변경)·(삭제) 표시가 있으면 변경 — 두 표시는 「지금 글」이 있는 자리에만 단다. //
//   · (신설)·(추가) 표시만 있으면, 법안 몸에 표시 없는 글(그대로 둘 항이나 줄)이 하나라도 있거나 기존 조의 제정 줄(설계는 //
//     확정 줄)이 옮겨 적혀 있을 때 변경 · 그 밖은 새 조라 신설. 그대로 둘 글이 적혀 있다는 것은 이미 있는 것을 고친다는 뜻이다 //
//     (조가 아니라 머리 줄 `paths:`에 한 줄 더하는 법안은 제정 줄 없이 그대로 둘 줄 열 개와 (신설) 한 줄로 온다 — 2026-10-03). //
//     인용 줄(`>`)·가름 줄(`---`)·빈 줄과 기호에 글이 붙은 줄(「⑥의 …」)은 법안 설명이라 표시 없는 글로 치지 않는다. //
//   · 표시가 하나도 없으면 신설(설계실은 추가). //
// ★전에는 소속 칸에서 「변경」 없이 「삭제」가 보이면 조 삭제로, 「변경(」처럼 괄호가 붙은 「변경」은 못 알아봐 「항추가」로 //
//   읽었다 — `rule-개발` 제6조 변경(③ 삭제) 법안이 ①②③ 모두 지울 글로 그려지고 「신설·취소」 단추가 섰다(2026-10-03). //
//   소속 칸은 들어갈 문서와 머리 줄 이름을 정하는 데만 쓴다(들어갈문서()). //
// 받는 것: 법안읽기()가 읽은 항목({이름, 항, 앞줄}) · 문서 이름(「설계실.md」로 끝나면 설계안). //
const 있던조줄 = /^\[(제정|확정) \d+\]/;
const 조삭제인가 = (이름) => String(이름 || '').indexOf('삭제 —') === 0;
export function 항목종류(항목, 문서) {
  const 설계 = /설계실\.md$/.test(String(문서 || ''));
  if (조삭제인가(항목.이름)) return 설계 ? '제거' : '삭제';
  const 표들 = (항목.항 || []).map((x) => x.표)
    .concat(앞줄표시나누기(항목.앞줄 || []).filter((p) => p.종류 === '표시').map((p) => p.표))
    .filter(Boolean);
  const 있던조 = (항목.앞줄 || []).some((l) => 있던조줄.test(String(l).trim()));
  // ★표시 없는 항은 기호 뒤를 띄운 항만 센다 — 설계안의 「⑥의 글은 아래 …에서 가를 고른 때의 글이다」 같은 설명 줄도 //
  //   기호로 시작해 항으로 읽히는데, 이것을 그대로 둘 항으로 세면 새 조 추가 설계안이 변경으로 읽힌다(2026-10-03 관리부 설계실로 잼). //
  const 그대로둘글 = (항목.항 || []).some((x) => !x.표 && x.띄움 !== false)
    || 앞줄표시나누기(항목.앞줄 || []).some((p) => p.종류 === '글' && p.글.split('\n').some((l) => {
      const t = l.trim();
      return t && t !== '---' && t[0] !== '>' && !있던조줄.test(t);
    }));
  if (표들.some((표) => 표 === '변경' || 표 === '삭제') || (표들.length && (있던조 || 그대로둘글))) return '변경';
  return 설계 ? '추가' : '신설';
}
// 종류마다 세울 답 둘 //
export function 고를답(종류) {
  return { 삭제: ['제거', '취소'], 변경: ['변경', '취소'], 제거: ['제거', '취소'], 추가: ['추가', '취소'] }[종류] || ['신설', '취소'];
}

const 답낱말 = ['신설', '추가', '변경', '제거', '취소', '유지'];

// 의회 파일·설계실 파일을 읽어 항목 배열을 돌려준다. //
export function 법안읽기(원문, 문서 = 'assembly.md') {
  const 줄 = String(원문 || '').split('\n'), 목록 = [];
  let 지금 = null, 계획안 = false;
  for (let l of 줄) {
    if (l.endsWith('\r')) l = l.slice(0, -1);
    if (l.startsWith('## ')) {
      const 머리 = l.slice(3).trim();
      // 종류는 법안 몸을 다 읽은 뒤 정한다(항목종류()) //
      지금 = { 제목: 머리, 이름: 구분자로가르기(머리)[0], 소속: 소속앞부분(소속전문꺼내기(머리)), 문서: 들어갈문서(머리),
        종류: '', 표시: '', 코멘트: {}, 항: [], 앞줄: [], 계획: [] };
      지금.곳 = 주인저장소(지금.문서);
      목록.push(지금); 계획안 = false;
      continue;
    }
    if (!지금) continue;
    const t = l.trim();
    if (t.startsWith('> 📌')) { 지금.표시 = 답낱말.find((답) => t.includes(답)) || ''; continue; }
    // 코멘트 줄 모양: 「> 💬 **줄키** | 날짜 | 글」 — 옛 「 · 」도 읽는다 //
    if (t.startsWith('> 💬')) {
      const 조각 = t.slice(4).split(/ [·|] /);
      지금.코멘트[민글(조각[0] || '').trim()] = 조각.slice(2).join(' | ').trim();
      continue;
    }
    // 설계안의 구현 계획 묶음 — 항이 아니라 따로 글자 그대로 보인다(제11조 ②) //
    if (t.startsWith('**구현 계획')) { 계획안 = true; continue; }
    if (계획안) { if (t !== '---') 지금.계획.push(l); continue; }
    // 「왜 지우나」 칸에 「지우면 사라진다」가 적힌 항은 사라짐 표시를 단다 — 박스가 「지우면 사라짐」 딱지를 따로 붙인다(제6조 ⑭) //
    if (조삭제인가(지금.이름) && 지금.항.length && t.startsWith('왜 지우나:')) {
      const 항 = 지금.항[지금.항.length - 1];
      항.까닭 = t.slice(6).trim(); 항.사라짐 = 항.까닭.includes('지우면 사라진다');
      continue;
    }
    if (항줄인가(t)) {
      const 나눔 = 표시항나누기(t.slice(1));
      // 띄움: 기호 바로 뒤가 빈칸인가 — 조문 항은 「① 글」로 띄우고, 「⑥의 글은 …」처럼 붙은 줄은 항을 가리키는 설명이다(항목종류()) //
      지금.항.push({ 기호: t[0], 글: 나눔.글, 까닭: '', 표: 나눔.표, 지금글: 나눔.지금글, 받는: 나눔.지금글 !== null ? '지금' : '글', 띄움: t[1] === ' ' });
      continue;
    }
    const 끝항 = 지금.항[지금.항.length - 1];
    if (끝항 && 고칠글줄인가(t) && 끝항.지금글 !== null) { 끝항.글 = t.slice('→ 고칠 글:'.length).trim(); 끝항.받는 = '글'; continue; }
    if (끝항 && 딸린줄인가(t)) { if (끝항.받는 === '지금') 끝항.지금글 += '\n' + t; else 끝항.글 += '\n' + t; continue; }
    if (!지금.항.length) 지금.앞줄.push(l);
  }
  for (const it of 목록) {
    while (it.계획.length && !it.계획[it.계획.length - 1].trim()) it.계획.pop();
    it.종류 = 항목종류(it, 문서);
  }
  return 목록;
}
