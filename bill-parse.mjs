// ── 안의 종류 ──────────────────────────────────────────────────────────── //
// [관리부 작업 454] 관리부 설계 bp-의회 「의회 박스는 법안 종류를 소속 칸의 낱말로 가리고, 법안에 적힌 고친 뒤의 조를 갈 곳 파일의 //
//   지금 조와 항마다 맞대 바뀐 곳을 칠한다」 조 ②③ — 법안과 설계안의 종류는 신설·변경·제거 셋이고(설계안도 같은 이름이다), //
//   이 차례로 가린다(맞댄종류()): //
//   ① 제목이 제거머리로 시작함 → 제거. 제거머리 = 제목 맨 앞의 「(제거)」(지우는 항에 붙이는 표시와 같은 낱말), 옛 법안·설계안이면 「제거 — 」·「삭제 — 」. //
//   ② 종류낱말 있음 → 그 낱말대로(「신설」·「추가」는 신설, 「변경」은 변경, 「삭제」·「제거」는 제거). //
//   ③ 지금조 있음 OR 법안에 기록 줄 있음 → 변경. //
//   ④ 옛 모양 법안(몸에 **(변경)** 같은 표시가 있음) → 표시로 가린다(표시종류()). //
//   ⑤ 그 밖 → 못가림. 못 가린 안을 신설로 보이면 있는 글을 고치는 안이 새 글로 읽히기 때문이다. //
// ★전에는 법안 제목과 갈 곳 파일의 조 제목을 맞대 가리다 못 찾으면 신설로 떨어졌다 — 조 제목을 바꾸는 법안, 스킬 머리 줄을 고치는 //
//   법안, 여러 조의 바뀌는 항만 묶은 법안이 모두 「신설」로 보였다(관리부 커밋 295812e · b123d68 · 9d12ac8의 법안, 2026-10-05). //
export const 제거머리 = /^(?:\(제거\)|(?:제거|삭제) —)\s*/;
const 조삭제인가 = (이름) => 제거머리.test(String(이름 || ''));
// 종류낱말 = 법안 제목 줄의 소속 칸(설계안은 갈 곳 칸)에서 괄호 안 글 · 「함께 찍는다」 뒤 글 · 「」와 백틱으로 감싼 글을 뺀 //
//   나머지에 처음 나오는 「신설」·「추가」·「변경」·「삭제」·「제거」 낱말. 받는 것: 제목 줄 전체. 돌려주는 것: 신설·변경·제거 또는 null. //
const 낱말종류 = { 신설: '신설', 추가: '신설', 변경: '변경', 삭제: '제거', 제거: '제거' };
export function 종류낱말(제목) {
  const 칸 = 소속전문꺼내기(제목);
  let 밖 = '', 괄호 = 0, 낫표 = 0, 코드 = false;
  for (const c of 칸) {
    if (c === '`') { 코드 = !코드; 밖 += ' '; continue; }
    if (코드) continue;
    if (c === '「') { 낫표++; 밖 += ' '; continue; }
    if (c === '」') { if (낫표) 낫표--; 밖 += ' '; continue; }
    if (낫표) continue;
    if (c === '(') { 괄호++; 밖 += ' '; continue; }
    if (c === ')') { if (괄호) 괄호--; 밖 += ' '; continue; }
    if (괄호) continue;
    밖 += c;
  }
  // 「함께 찍는다」 뒤 글은 그 칸(다음 ` | ` 앞)까지만 뺀다 — 「소속: … · 함께 찍는다: … 3절 변경 | 신설 (추천 까닭: …)」처럼 //
  //   종류가 뒤 칸에 따로 적힌 법안이 있다(관리부 커밋 5a80a2e의 `safe-area` 법안). 괄호 안의 ` | `는 위에서 이미 걷혔다. //
  const 앞 = 밖.split('|').map((칸조각) => 칸조각.split('함께 찍는다')[0]).join('|');
  const m = /신설|추가|변경|삭제|제거/.exec(앞);
  return m ? 낱말종류[m[0]] : null;
}

// 옛 모양 법안의 종류 — 법안 몸의 표시로 가린다(맞댄종류()의 ④). 돌려주는 것: 변경·신설. //
//   · 항이나 항 밖 줄에 (변경)·(삭제) 표시가 있으면 변경 — 두 표시는 「지금 글」이 있는 자리에만 단다. //
//   · (신설)·(추가) 표시만 있으면, 법안 몸에 표시 없는 글(그대로 둘 항이나 줄)이 하나라도 있거나 기존 조의 제정 줄(설계는 //
//     확정 줄)이 옮겨 적혀 있을 때 변경 · 그 밖은 새 조라 신설. 그대로 둘 글이 적혀 있다는 것은 이미 있는 것을 고친다는 뜻이다 //
//     (조가 아니라 머리 줄 `paths:`에 한 줄 더하는 법안은 제정 줄 없이 그대로 둘 줄 열 개와 (신설) 한 줄로 온다 — 2026-10-03). //
//     인용 줄(`>`)·가름 줄(`---`)·빈 줄과 기호에 글이 붙은 줄(「⑥의 …」)은 법안 설명이라 표시 없는 글로 치지 않는다. //
// 받는 것: 법안읽기()가 읽은 항목({이름, 항, 앞줄}). //
const 있던조줄 = /^\[(제정|확정) \d+\]/;
export function 표시종류(항목) {
  const 표들 = (항목.항 || []).map((x) => x.표)
    .concat(앞줄표시나누기(항목.앞줄 || []).filter((p) => p.종류 === '표시').map((p) => p.표))
    .filter(Boolean);
  const 있던조 = (항목.앞줄 || []).some((l) => 있던조줄.test(String(l).trim()));
  // ★표시 없는 항은 기호 뒤를 띄운 항만 센다 — 설계안의 「⑥의 글은 아래 …에서 가를 고른 때의 글이다」 같은 설명 줄도 //
  //   기호로 시작해 항으로 읽히는데, 이것을 그대로 둘 항으로 세면 새 조 추가 설계안이 변경으로 읽힌다(2026-10-03 관리부 설계실로 잼). //
  const 그대로둘글 = (항목.항 || []).some((x) => !x.표 && x.띄움 !== false)
    || 앞줄표시나누기(항목.앞줄 || []).some((p) => p.종류 === '글' && p.글.split('\n').some((l) => {
      const t = l.trim();
      return t && t !== '---' && t[0] !== '>' && !있던조줄.test(t);
    }));
  if (표들.some((표) => 표 === '변경' || 표 === '삭제') || (표들.length && (있던조 || 그대로둘글))) return '변경';
  return '신설';
}
