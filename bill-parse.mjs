//
// 무엇을 하나: 문서 글을 받아 항목(법안·설계안)마다 제목·갈 곳·종류·찍힌 답·코멘트·항·항 밖 줄·구현 계획을 돌려준다. //
//   실물 파일에서 「지금 글」을 읽지 않는다 — 법안은 AI가 고칠 규칙의 그때 조를 가져와 바꿀 글과 함께 담아 상정한 안이라, //
//   법안 글만으로 박스를 그린다(관리부 설계 `bp-상황판` 제6조 ⑤). 대상 파일의 지금 상태는 환경 화면이 보여 준다. //
//
// 따르는 설계: 제4조 ②③(답과 법안 종류) · 제6조 ⑤⑬⑰(조 전체·삭제 법안·항 밖 줄) · 제11조 ①②⑤(설계실 · 구현 계획 · 들어갈 자리) · //
//   제2조 ⑨(법안은 소속 칸이 가리키는 곳으로 세고, 회장실·전역으로 갈 법안은 관리부에 센다). //
import { 구분자로가르기, 소속전문꺼내기, 소속앞부분, 민글, 항줄인가, 표시항나누기, 고칠글줄인가, 딸린줄인가, 항추가인가 } from './assembly-view.mjs';

// 부서·프로젝트 저장소 이름 ↔ 우리말 이름. 저장소 이름은 PC 폴더 이름·GitHub 저장소 이름과 같다(2026-09-29 원격 주소로 확인). //
// ponytail: 곳이 늘면 여기에 한 줄 더한다 — 소속 칸의 우리말 이름을 저장소로 잇는 표가 따로 없다. //
export const 곳이름 = {
  management: '관리부', knowledge: '자료실', yessoft: '전략기획실',
  '1talk-app': '일톡', '1talk-app-auto-order': '일톡 자동 주문 수집기', homepage: '홈페이지',
  'ilgongil-app': '일공일', 's36524-app': '모든예약',
};
// 소속 칸 맨 앞의 주인 → 저장소. 긴 이름부터 맞춘다(「일톡 자동 주문 수집기」가 「일톡」에 먼저 걸리지 않게). //
// 회장실·전역으로 갈 법안은 관리부에 센다 — 관리부가 공통 자리를 맡는 부서이기 때문이다(제2조 ⑨). //
const 주인표 = Object.entries(곳이름).map(([저장소, 이름]) => [이름, 저장소])
  .concat([['일톡 자동 주문', '1talk-app-auto-order'], ['회장실', 'management'], ['전역', 'management']])
  .sort((a, b) => b[0].length - a[0].length);
export function 주인저장소(갈곳) {
  const t = String(갈곳 || '').trim();
  const 맞음 = 주인표.find(([이름]) => t === 이름 || t.startsWith(이름 + ' '));
  return 맞음 ? 맞음[1] : null;
}

// 들어갈 문서 — 소속 앞부분에서 조·항 자리(「 · 제5조 …」 · 「 제1조 추가」 · 「 새 파일 …」)를 뗀 「주인 종류 이름」. //
export function 들어갈문서(제목) {
  return 소속앞부분(소속전문꺼내기(제목)).replace(/\s[·|]\s.*$/, '').replace(/\s+(제\d+조|새 파일|머리|\d+행|\d+절).*$/, '').trim();
}

// 항목 종류 — 의회 법안은 신설·항추가·변경·삭제, 설계실 설계안은 추가·변경·제거. 답 단추 둘을 고르는 데 쓴다(제4조 ③ · 제11조 ③). //
export function 항목종류(제목, 문서) {
  const 이름 = 구분자로가르기(String(제목 || ''))[0] || '';
  const 소속 = 소속앞부분(소속전문꺼내기(제목));
  if (/설계실\.md$/.test(String(문서 || ''))) {
    if (/(^|\s)(제거|삭제)(\s|$)/.test(소속) || 이름.indexOf('삭제 —') === 0) return '제거';
    if (/(^|\s)변경(\s|$)/.test(소속)) return '변경';
    return '추가';
  }
  if (이름.indexOf('삭제 —') === 0 || /(^|[\s·])삭제(\s|$|·)/.test(소속) && !/변경/.test(소속)) return '삭제';
  if (소속.indexOf('새 조') >= 0) return '신설';
  if (소속.indexOf('추가') >= 0 || 항추가인가(소속)) return '항추가';
  if (소속.indexOf('변경') >= 0) return '변경';
  return '신설';
}
// 종류마다 세울 답 둘 //
export function 고를답(종류) {
  return { 삭제: ['제거', '취소'], 변경: ['변경', '취소'], 제거: ['제거', '취소'], 추가: ['추가', '취소'] }[종류] || ['신설', '취소'];
}

const 답낱말 = ['신설', '추가', '변경', '제거', '취소', '유지'];

// 의회 파일·설계실 파일을 읽어 항목 배열을 돌려준다. //
export function 법안읽기(원문, 문서 = 'assembly.md') {
  const 줄 = String(원문 || '').split('\n'), 목록 = [];
  let 지금 = null, 계획안 = false;
  for (let l of 줄) {
    if (l.endsWith('\r')) l = l.slice(0, -1);
    if (l.startsWith('## ')) {
      const 머리 = l.slice(3).trim();
      지금 = { 제목: 머리, 이름: 구분자로가르기(머리)[0], 소속: 소속앞부분(소속전문꺼내기(머리)), 문서: 들어갈문서(머리),
        종류: 항목종류(머리, 문서), 표시: '', 코멘트: {}, 항: [], 앞줄: [], 계획: [] };
      지금.곳 = 주인저장소(지금.문서);
      목록.push(지금); 계획안 = false;
      continue;
    }
    if (!지금) continue;
    const t = l.trim();
    if (t.startsWith('> 📌')) { 지금.표시 = 답낱말.find((답) => t.includes(답)) || ''; continue; }
    // 코멘트 줄 모양: 「> 💬 **줄키** | 날짜 | 글」 — 옛 「 · 」도 읽는다 //
    if (t.startsWith('> 💬')) {
      const 조각 = t.slice(4).split(/ [·|] /);
      지금.코멘트[민글(조각[0] || '').trim()] = 조각.slice(2).join(' | ').trim();
      continue;
    }
    // 설계안의 구현 계획 묶음 — 항이 아니라 따로 글자 그대로 보인다(제11조 ②) //
    if (t.startsWith('**구현 계획')) { 계획안 = true; continue; }
    if (계획안) { if (t !== '---') 지금.계획.push(l); continue; }
    if (지금.종류 === '삭제' && 지금.항.length && t.startsWith('왜 지우나:')) { 지금.항[지금.항.length - 1].까닭 = t.slice(6).trim(); continue; }
    if (항줄인가(t)) {
      const 나눔 = 표시항나누기(t.slice(1));
      지금.항.push({ 기호: t[0], 글: 나눔.글, 까닭: '', 표: 나눔.표, 지금글: 나눔.지금글, 받는: 나눔.지금글 !== null ? '지금' : '글' });
      continue;
    }
    const 끝항 = 지금.항[지금.항.length - 1];
    if (끝항 && 고칠글줄인가(t) && 끝항.지금글 !== null) { 끝항.글 = t.slice('→ 고칠 글:'.length).trim(); 끝항.받는 = '글'; continue; }
    if (끝항 && 딸린줄인가(t)) { if (끝항.받는 === '지금') 끝항.지금글 += '\n' + t; else 끝항.글 += '\n' + t; continue; }
    if (!지금.항.length) 지금.앞줄.push(l);
  }
  for (const it of 목록) while (it.계획.length && !it.계획[it.계획.length - 1].trim()) it.계획.pop();
  return 목록;
}
