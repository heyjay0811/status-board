// ★옮겨 가는 동안: 옛모양 = 법안 몸(항과 항 밖 줄)에 **(변경)**·**(신설)**·**(삭제)**·**(추가)**·**(제거)** 표시가 하나라도 있음 — //
//   옛 모양 법안은 지금 길(표시대로 칠함)로 읽는다. 항이 없는 법안(스킬·담당·훅 — 생길 파일 모양으로 미리 본다)도 지금 길이다. //
export const 옛모양인가 = (it) => (it.항 || []).some((x) => x.표) || 앞줄표시나누기(it.앞줄 || []).some((p) => p.종류 === '표시');
export const 맞댈법안인가 = (it) => !옛모양인가(it) && (it.항 || []).length > 0;
const 기록줄 = /^\[(제정|확정) \d+\]/;
export const 첫기록줄 = (줄들) => (줄들 || []).map((l) => String(l).trim()).find((l) => 기록줄.test(l)) || null;

// 소속 칸 이름 → GitHub 저장소와 경로. 회장실은 회장실 저장소(yessoftbook)의 CLAUDE.md, 전역은 전역 환경 저장소(claude-config)의 그 파일, //
//   관리부·부서·프로젝트는 그 저장소의 CLAUDE.md·.claude/ 아래 파일·docs/bp-*.md다(assembly-view.mjs 소속자리()가 소속 모양을 읽는다). //
// ★소속 칸의 주인 이름이 곳이름 표와 글자가 다른 것(「일톡 자동주문」)도 받는다 — 긴 이름부터 맞춰 「일톡」에 먼저 걸리지 않는다. //
const 깃 = 'gh:';
const 깃자리표 = () => {
  const 부서 = {};
  for (const [저장소, 이름] of Object.entries(곳이름)) 부서[이름] = 깃 + 저장소;
  부서['일톡 자동주문'] = 깃 + '1talk-app-auto-order'; 부서['일톡 자동 주문'] = 깃 + '1talk-app-auto-order';
  return { 전역: 깃 + 'claude-config', 관리부: 깃 + 'management', 회장실: 깃 + 'yessoftbook/CLAUDE.md', 부서 };
};
export function 갈곳파일(소속) {
  const 자리 = 소속자리(소속, 깃자리표());
  if (!자리.주소) return { 까닭: 자리.까닭 || `소속 설명 「${소속앞부분(소속)}」에서 어느 파일인지 알아보지 못했다` };
  const 조각 = 자리.주소.slice(깃.length).split('/').filter(Boolean).map((x) => decodeURIComponent(x));
  return { 저장소: 조각[0], 경로: 조각.slice(1).join('/') };
}

// 갈 곳 파일의 조 — 「## 제N조 조 제목 | #태그」 줄마다 조 하나. 조 제목은 「제N조」와 ` | ` 뒤 태그를 뗀다. //
//   기록 = 조 제목 아래 첫 기록 줄(「[제정 N] 승인 날짜」·「[확정 N] 날짜」) · 항 = 원문자 줄과 그 아래 딸린 줄(🔧·☑ 표시 줄은 뺀다). //
const 원문자줄 = /^[①-⑳㉑-㉟㊱-㊿]/;
export function 조들읽기(원문) {
  const 조 = []; let 지금 = null, 코드 = false;
  for (let l of String(원문 ?? '').split('\n')) {
    if (l.endsWith('\r')) l = l.slice(0, -1);
    if (/^\s*```/.test(l)) 코드 = !코드;
    if (코드 || /^\s*```/.test(l)) { if (지금 && 지금.항.length) 지금.항[지금.항.length - 1].글 += '\n' + l.trim(); continue; }
    const m = /^##\s+제\d+조\s+(.*)$/.exec(l);
    if (m) { 지금 = { 제목: m[1].replace(/\s+[|·]\s+#.*$/, '').trim(), 기록: null, 항: [], 제목뒤: true }; 조.push(지금); continue; }
    if (/^#{1,2}\s/.test(l)) { 지금 = null; continue; }
    if (!지금) continue;
    const t = l.trim();
    if (지금.제목뒤 && t) { 지금.제목뒤 = false; if (기록줄.test(t)) { 지금.기록 = t; continue; } }
    if (기록줄.test(t) && !지금.항.length) continue;   // 조 제목 아래 기록 줄은 견주지 않는다 //
    if (원문자줄.test(t)) { const 기호 = [...t][0]; 지금.항.push({ 기호, 글: t.slice(기호.length).trim() }); continue; }
    if (지금.항.length && 딸린줄인가(t) && !표시줄인가(t)) 지금.항[지금.항.length - 1].글 += '\n' + t;
  }
  return 조.map(({ 제목, 기록, 항 }) => ({ 제목, 기록, 항 }));
}

// 지금조 = (조 제목 = 법안 제목)인 조, 없으면 (조 제목 아래 첫 기록 줄 = 법안에 적힌 첫 기록 줄)인 조, 그것도 없으면 없음. //
//   법안 제목은 앞의 「삭제 — 」를 떼고 견준다. //
export function 조고르기(파일글, it) {
  const 조들 = 조들읽기(파일글);
  const 법제목 = String(it.이름 || '').replace(/^삭제 —\s*/, '').trim();
  const 법기록 = 첫기록줄(it.앞줄);
  return 조들.find((x) => x.제목 === 법제목) || (법기록 && 조들.find((x) => x.기록 === 법기록)) || null;
}

// 법안 종류 — 제목이 「삭제 — 」로 시작함이면 삭제(설계안은 제거), 그다음 지금조 있음이면 변경, 그다음 지금조 없음 AND 법안에 기록 줄 없음이면 //
//   신설(설계안은 추가). 지금조 없음 AND 기록 줄 있음이면 맞댈 조를 못 찾은 것이다(못찾음). //
export function 맞댄종류(it, 지금조, 설계) {
  if (/^삭제 —/.test(String(it.이름 || ''))) return 설계 ? '제거' : '삭제';
  if (지금조) return '변경';
  if (!첫기록줄(it.앞줄)) return 설계 ? '추가' : '신설';
  return '못찾음';
}
// 갈 곳 파일을 아직 못 읽었거나 못 읽었을 때 목록과 답 단추에 쓸 종류 — 못 읽은 법안은 신설로 가리지 않는다: //
//   삭제 제목이면 삭제(제거), 기록 줄이 있으면 변경, 없으면 신설(추가). //
export function 못맞댄종류(it, 설계) {
  if (/^삭제 —/.test(String(it.이름 || ''))) return 설계 ? '제거' : '삭제';
  return 첫기록줄(it.앞줄) ? '변경' : (설계 ? '추가' : '신설');
}

// 항 맞대기 — 변경 법안의 항(고친 뒤의 조)과 지금조의 항을 이 차례로 짝짓는다. //
//   ① 글이 같은 항끼리 → 그대로(흐리게) · ② 남은 항 가운데 기호가 같은 항끼리 → 바뀜(지금 글 아래 고칠 글) · //
//   ③ 그래도 남은 법안의 항 → 새 · ④ 남은 지금조의 항 → 빠짐(원래 자리에 끼운다). 글은 굵게를 벗겨 견준다. //
// 돌려주는 것: [{ 갈래: '그대로'|'바뀜'|'새'|'빠짐', 기호, 지금글, 고칠글 }] — 법안 항 차례에 빠진 항을 끼운 차례. //
export function 항맞대기(법안항, 지금항) {
  const 같은글 = (a, b) => 민글(a).trim() === 민글(b).trim();
  const 짝 = new Map(), 쓴 = new Set();   // 법안 항 차례 → { 지금 항 차례, 갈래 } //
  (법안항 || []).forEach((b, i) => { const j = (지금항 || []).findIndex((g, k) => !쓴.has(k) && 같은글(g.글, b.글)); if (j >= 0) { 짝.set(i, { j, 갈래: '그대로' }); 쓴.add(j); } });
  (법안항 || []).forEach((b, i) => { if (짝.has(i)) return; const j = (지금항 || []).findIndex((g, k) => !쓴.has(k) && g.기호 === b.기호); if (j >= 0) { 짝.set(i, { j, 갈래: '바뀜' }); 쓴.add(j); } });
  const 줄 = (법안항 || []).map((b, i) => {
    const p = 짝.get(i);
    return p ? { 갈래: p.갈래, 기호: b.기호, 지금글: 지금항[p.j].글, 고칠글: b.글, 자리: p.j } : { 갈래: '새', 기호: b.기호, 지금글: null, 고칠글: b.글, 자리: null };
  });
  (지금항 || []).forEach((g, j) => {
    if (쓴.has(j)) return;
    const 뒤 = 줄.findIndex((r) => r.자리 !== null && r.자리 > j);
    const 빠짐 = { 갈래: '빠짐', 기호: g.기호, 지금글: g.글, 고칠글: null, 자리: j };
    if (뒤 < 0) 줄.push(빠짐); else 줄.splice(뒤, 0, 빠짐);
  });
  return 줄.map(({ 갈래, 기호, 지금글, 고칠글 }) => ({ 갈래, 기호, 지금글, 고칠글 }));
}

// 의회 파일·설계실 파일을 읽어 항목 배열을 돌려준다. //
export function 법안읽기(원문, 문서 = 'assembly.md') {
  const 줄 = String(원문 || '').split('\n'), 목록 = [];
  let 지금 = null, 계획안 = false;
  for (let l of 줄) {
    if (l.endsWith('\r')) l = l.slice(0, -1);
    if (l.startsWith('## ')) {
      const 머리 = l.slice(3).trim();
      // 종류는 법안 몸을 다 읽은 뒤 정한다(항목종류()) //
      지금 = { 제목: 머리, 이름: 구분자로가르기(머리)[0], 소속: 소속앞부분(소속전문꺼내기(머리)), 문서: 들어갈문서(머리),
        종류: '', 표시: '', 코멘트: {}, 항: [], 앞줄: [], 계획: [] };
      지금.곳 = 주인저장소(지금.문서);
      목록.push(지금); 계획안 = false;
      continue;
    }
    if (!지금) continue;
    const t = l.trim();
    if (t.startsWith('> 📌')) { 지금.표시 = 답낱말.find((답) => t.includes(답)) || ''; continue; }
    // 코멘트 줄 모양: 「> 💬 **줄키** | 날짜 | 글」 — 옛 「 · 」도 읽는다 //
    if (t.startsWith('> 💬')) {
      const 조각 = t.slice(4).split(/ [·|] /);
      지금.코멘트[민글(조각[0] || '').trim()] = 조각.slice(2).join(' | ').trim();
      continue;
    }
    // 설계안의 구현 계획 묶음 — 항이 아니라 따로 글자 그대로 보인다(제11조 ②) //
    if (t.startsWith('**구현 계획')) { 계획안 = true; continue; }
    if (계획안) { if (t !== '---') 지금.계획.push(l); continue; }
    // 「왜 지우나」 칸에 「지우면 사라진다」가 적힌 항은 사라짐 표시를 단다 — 박스가 「지우면 사라짐」 딱지를 따로 붙인다(제6조 ⑭) //
    if (조삭제인가(지금.이름) && 지금.항.length && t.startsWith('왜 지우나:')) {
      const 항 = 지금.항[지금.항.length - 1];
      항.까닭 = t.slice(6).trim(); 항.사라짐 = 항.까닭.includes('지우면 사라진다');
      continue;
    }
    if (항줄인가(t)) {
      const 나눔 = 표시항나누기(t.slice(1));
      // 띄움: 기호 바로 뒤가 빈칸인가 — 조문 항은 「① 글」로 띄우고, 「⑥의 글은 …」처럼 붙은 줄은 항을 가리키는 설명이다(항목종류()) //
      지금.항.push({ 기호: t[0], 글: 나눔.글, 까닭: '', 표: 나눔.표, 지금글: 나눔.지금글, 받는: 나눔.지금글 !== null ? '지금' : '글', 띄움: t[1] === ' ' });
      continue;
    }
    const 끝항 = 지금.항[지금.항.length - 1];
    if (끝항 && 고칠글줄인가(t) && 끝항.지금글 !== null) { 끝항.글 = t.slice('→ 고칠 글:'.length).trim(); 끝항.받는 = '글'; continue; }
    if (끝항 && 딸린줄인가(t)) { if (끝항.받는 === '지금') 끝항.지금글 += '\n' + t; else 끝항.글 += '\n' + t; continue; }
    if (!지금.항.length) 지금.앞줄.push(l);
  }
  for (const it of 목록) {
    while (it.계획.length && !it.계획[it.계획.length - 1].trim()) it.계획.pop();
    // 새 모양 법안(표시 없이 고친 뒤의 조만 적음)은 갈 곳 파일과 맞대기 전까지 못맞댄종류()로 둔다 — 박스를 열어 맞대면 화면이 바꿔 단다 //
    it.종류 = 맞댈법안인가(it) ? 못맞댄종류(it, /설계실\.md$/.test(String(문서 || ''))) : 항목종류(it, 문서);
  }
  return 목록;
}
