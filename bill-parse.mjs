// 답 줄(「> 📌 …」)의 답 — 같은 조 ④: 전에 찍혀 남아 있는 신설·변경·제거·추가 답 줄은 승인으로 읽는다. //
//   답 줄 머리(첫 ` | ` 앞)만 본다 — 뒤에 붙은 날짜·한마디에 든 낱말에 끌려가지 않게. 옛 「유지」는 그대로 읽는다. //
export function 답줄읽기(줄) {
  const 머리 = String(줄 || '').split(' | ')[0];
  if (머리.includes('취소')) return '취소';
  if (/승인|신설|추가|변경|제거/.test(머리)) return '승인';
  if (머리.includes('유지')) return '유지';
  return '';
}

