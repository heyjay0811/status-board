// 상황판 — 의회 파일의 법안과 설계실 파일의 설계안을 읽는 공통 부품(PC 앱 새 화면과 모바일 앱이 함께 쓴다). //
//
// 무엇을 하나: 문서 글을 받아 항목(법안·설계안)마다 제목·갈 곳·종류·찍힌 답·코멘트·몸의 줄 목록·구현 계획을 돌려준다. //
//   몸의 줄 목록은 법안에 적힌 줄을 적힌 차례대로 두고, 줄마다 머리의 「(신설)」·「(변경)」·「(제거)」 표시와 「(변경)」 줄의 짝을 단다. //
//   갈 곳 파일과 맞대지 않는다 — 화면(app.mjs 박스그리기())은 이 줄 목록만 보고 칠한다 //
//   (관리부 설계 bp-의회 「법안 종류와 고치는 글의 표시 읽기」 조 · 「상황판 의회 화면은 조문을 팝업 박스 하나로 열고, 갈 자리와 바뀔 내용을 함께 보여준다」 조 ⑤). //
//
// 따르는 설계: bp-결재 · bp-의회 · bp-설계실(답 승인·취소와 안의 종류 신설·변경·제거 · 고치는 글의 표시 · 설계실 · 구현 계획 · 들어갈 자리). //
import { 구분자로가르기, 소속전문꺼내기, 소속앞부분, 민글, 항줄인가, 표시줄인가 } from './assembly-view.mjs';

// 부서·프로젝트 저장소 이름 ↔ 우리말 이름. 저장소 이름은 PC 폴더 이름·GitHub 저장소 이름과 같다(2026-09-29 원격 주소로 확인). //
// ponytail: 곳이 늘면 여기에 한 줄 더한다 — 소속 칸의 우리말 이름을 저장소로 잇는 표가 따로 없다. //
export const 곳이름 = {
  management: '관리부', knowledge: '자료실', yessoft: '전략기획실',
  '1talk-app': '일톡', '1talk-app-auto-order': '일톡 자동 주문 수집기', homepage: '홈페이지',
  'ilgongil-app': '일공일', 's36524-app': '모든예약',
};
// 소속 칸 맨 앞의 주인 → 저장소. 긴 이름부터 맞춘다(「일톡 자동 주문 수집기」가 「일톡」에 먼저 걸리지 않게). //
// 회장실·전역으로 갈 법안은 관리부에 센다 — 관리부가 공통 자리를 맡는 부서이기 때문이다(제2조 ⑨). //
const 주인표 = Object.entries(곳이름).map(([저장소, 이름]) => [이름, 저장소])
  .concat([['일톡 자동 주문', '1talk-app-auto-order'], ['회장실', 'management'], ['전역', 'management']])
  .sort((a, b) => b[0].length - a[0].length);
export function 주인저장소(갈곳) {
  const t = String(갈곳 || '').trim();
  const 맞음 = 주인표.find(([이름]) => t === 이름 || t.startsWith(이름 + ' '));
  return 맞음 ? 맞음[1] : null;
}

// [관리부 작업 454] 관리부 설계 bp-설계실 「상황판 설계실 화면은 부서·프로젝트마다의 설계실을 모아 곳마다 묶어 의회 화면과 같은 박스로 연다」 조 ① — //
//   머리줄(설계안) = 그 설계안이 있는 설계실 파일의 저장소. 갈 곳 칸의 주인 이름으로 묶지 않는다 — 설계안은 그 곳 설계실에 올라 //
//   늘 그 곳 설계 문서로 간다. 설계실 파일이 없거나 설계안이 없는 곳도 머리 줄은 세운다. //
// 받는 것: 곳마다의 설계실 [{ 저장소, 안들(법안읽기() 결과, 못 읽었으면 null), 오류 }] · 머리 줄을 세울 저장소 이름들(화면의 곳 차례). //
// 돌려주는 것: [{ 저장소, 안: [{ 항목, 번째 }], 오류 }] — 번째는 그 곳 설계안 배열의 자리. 머리 줄 목록에 없는 곳의 설계실은 끝에 붙인다. //
export function 설계안묶기(설계실들, 저장소들) {
  const 묶음 = (저장소들 || []).map((저장소) => ({ 저장소, 안: [], 오류: '' }));
  for (const 실 of 설계실들 || []) {
    let 곳 = 묶음.find((x) => x.저장소 === 실.저장소);
    if (!곳) { 곳 = { 저장소: 실.저장소, 안: [], 오류: '' }; 묶음.push(곳); }
    곳.오류 = 실.오류 || '';
    (실.안들 || []).forEach((항목, 번째) => 곳.안.push({ 항목, 번째 }));
  }
  return 묶음;
}

// 들어갈 문서 — 소속 앞부분에서 조·항 자리(「 · 제5조 …」 · 「 제1조 추가」 · 「 새 파일 …」)를 뗀 「주인 종류 이름」. //
export function 들어갈문서(제목) {
  return 소속앞부분(소속전문꺼내기(제목)).replace(/\s[·|]\s.*$/, '').replace(/\s+(제\d+조|새 파일|머리|\d+행|\d+절).*$/, '').trim();
}

// ── 안의 종류 ──────────────────────────────────────────────────────────── //
// [관리부 작업 456] 관리부 설계 bp-의회 「법안 종류와 고치는 글의 표시 읽기」 조 ① — 법안과 설계안의 종류는 신설·변경·제거 셋이고 //
//   (설계안도 같은 이름이다), 이 차례로만 가린다(안종류()): //
//   ① 제목 맨 앞에 「(제거)」가 붙음 → 제거. //
//   ② 종류낱말 있음 → 그 낱말대로(「신설」·「추가」는 신설, 「변경」은 변경, 「삭제」·「제거」는 제거). //
//   ③ 그 밖 → 못가림. //
//   종류는 안을 쓴 쪽이 제목 줄에 적은 낱말로만 가리고 갈 곳 파일과 맞대 짐작하지 않는다. //
// ★전에는 갈 곳 파일의 조와 맞대고 기록 줄·옛 굵은 표시로도 짐작해, 적은 종류와 화면의 종류가 어긋날 길이 있었다 — 그 갈래를 걷었다. //
export const 제거머리 = /^\(제거\)\s*/;
const 조삭제인가 = (이름) => 제거머리.test(String(이름 || ''));
// 종류낱말 = 법안 제목 줄의 소속 칸(설계안은 갈 곳 칸)에서 괄호 안 글 · 「함께 찍는다」 뒤 글 · 「」와 백틱으로 감싼 글을 뺀 //
//   나머지에 처음 나오는 「신설」·「추가」·「변경」·「삭제」·「제거」 낱말. 받는 것: 제목 줄 전체. 돌려주는 것: 신설·변경·제거 또는 null. //
const 낱말종류 = { 신설: '신설', 추가: '신설', 변경: '변경', 삭제: '제거', 제거: '제거' };
export function 종류낱말(제목) {
  const 칸 = 소속전문꺼내기(제목);
  let 밖 = '', 괄호 = 0, 낫표 = 0, 코드 = false;
  for (const c of 칸) {
    if (c === '`') { 코드 = !코드; 밖 += ' '; continue; }
    if (코드) continue;
    if (c === '「') { 낫표++; 밖 += ' '; continue; }
    if (c === '」') { if (낫표) 낫표--; 밖 += ' '; continue; }
    if (낫표) continue;
    if (c === '(') { 괄호++; 밖 += ' '; continue; }
    if (c === ')') { if (괄호) 괄호--; 밖 += ' '; continue; }
    if (괄호) continue;
    밖 += c;
  }
  // 「함께 찍는다」 뒤 글은 그 칸(다음 ` | ` 앞)까지만 뺀다 — 「소속: … · 함께 찍는다: … 3절 변경 | 신설 (추천 까닭: …)」처럼 //
  //   종류가 뒤 칸에 따로 적힌 법안이 있다(관리부 커밋 5a80a2e의 `safe-area` 법안). 괄호 안의 ` | `는 위에서 이미 걷혔다. //
  const 앞 = 밖.split('|').map((칸조각) => 칸조각.split('함께 찍는다')[0]).join('|');
  const m = /신설|추가|변경|삭제|제거/.exec(앞);
  return m ? 낱말종류[m[0]] : null;
}

// [관리부 작업 454] 관리부 설계 bp-결재 「의회·설계실 화면은 법안과 설계안마다 `승인`·`취소` 두 답을 찍고, 제목 줄과 항마다 코멘트 칸을 둔다」 조 ②③ — //
//   답은 어느 종류의 안이든 승인·취소 둘이다. 종류를 못 가린 안의 승인 단추는 화면(app.mjs 박스그리기())이 막는다. //
export function 고를답() {
  return ['승인', '취소'];
}

// 답 줄(「> 📌 …」)의 답 — 같은 조 ④: 전에 찍혀 남아 있는 신설·변경·제거·추가 답 줄은 승인으로 읽는다. //
//   답 줄 머리(첫 ` | ` 앞)만 본다 — 뒤에 붙은 날짜·한마디에 든 낱말에 끌려가지 않게. 옛 「유지」는 그대로 읽는다. //
export function 답줄읽기(줄) {
  const 머리 = String(줄 || '').split(' | ')[0];
  if (머리.includes('취소')) return '취소';
  if (/승인|신설|추가|변경|제거/.test(머리)) return '승인';
  if (머리.includes('유지')) return '유지';
  return '';
}

// 안의 종류 — 위 「안의 종류」 머리 주석의 차례 ①~③. 돌려주는 것: '신설' · '변경' · '제거' · '못가림'. //
export function 안종류(it) {
  if (조삭제인가(it.이름)) return '제거';
  return 종류낱말(it.제목) || '못가림';
}

// ── 고치는 글의 표시 ─────────────────────────────────────────────────── //
// [관리부 작업 456] 관리부 설계 bp-의회 「법안 종류와 고치는 글의 표시 읽기」 조 ②③ — 법안 몸을 적힌 차례의 줄 목록으로 읽는다. //
//   줄 = { 표시: '신설'|'변경'|'제거'|'', 글(표시를 뗀 글), 원(표시를 뗀 날줄 — 들여쓰기 그대로), 기호(글이 원문자로 시작하면 그 기호), //
//          갈곳(「갈 곳:」으로 시작하는가), 기록(🔧·☑ 줄인가), 빈(빈 줄인가), 짝(「(변경)」 줄이면 짝 줄의 차례, 없으면 null), 짝임(다른 「(변경)」 줄의 짝인가) }. //
//   표시는 줄 머리에만 단다 — 「(신설) ⑤ …」·「(변경) ④ …」·「(제거) 🔧 …」·「(변경) 갈 곳: …」. //
// ★한 항 아래 빈 줄 없이 이어지는 표시 없는 줄(항 아래 목록 같은 것)은 그 항의 글에 붙인다 — 한 항이 한 줄 덩어리다. //
//   표시 단 줄 · 원문자 줄 · 「갈 곳:」 줄 · 「조 제목:」 줄 · 🔧·☑ 줄은 붙이지 않는다. //
// ★전에는 원문자로 시작하는 줄만 항으로 읽어 「(변경) ④ …」·「(신설) ⑤ …」·「(제거) 🔧 …」 줄이 바로 위 항의 이어지는 줄로 붙었다 //
//   (2026-10-10 관리부 설계실·의회 실물로 잼). //
const 표시머리 = /^\((신설|변경|제거)\)\s*/;
export function 줄읽기(l) {
  const 날 = String(l ?? '').replace(/\r$/, '');
  const t = 날.trim();
  const m = 표시머리.exec(t);
  const 표시 = m ? m[1] : '';
  const 글 = m ? t.slice(m[0].length).trim() : t;
  const 원 = m ? 날.slice(0, 날.indexOf('(')) + 글 : 날;
  return { 표시, 글, 원, 기호: 항줄인가(글) ? [...글][0] : '', 갈곳: 글.startsWith('갈 곳:'), 기록: 표시줄인가(글), 빈: !t, 짝: null, 짝임: false };
}
// 「(변경)」 줄의 짝 — 짝 = 그 줄에서 위로 올라가며 빈 줄 · 표시 단 줄 · 🔧 줄 · ☑ 줄을 건너뛰고 처음 만나는 줄, //
//   단 그 줄이 「갈 곳:」 줄이거나 이미 다른 「(변경)」 줄의 짝이면 짝 없음(같은 조 ②). 「(변경) 갈 곳:」 줄은 짝을 찾지 않는다. //
//   위에서부터 차례로 찾는다 — 원래 글 하나 아래 「(변경)」 줄이 둘이면 둘째는 짝 없음이다. //
export function 짝잇기(줄) {
  줄.forEach((x, i) => {
    if (x.표시 !== '변경' || x.갈곳) return;
    let j = i - 1;
    while (j >= 0 && (줄[j].빈 || 줄[j].표시 || 줄[j].기록)) j--;
    if (j < 0 || 줄[j].갈곳 || 줄[j].짝임) return;
    x.짝 = j; 줄[j].짝임 = true;
  });
  return 줄;
}
const 붙일줄인가 = (x) => !x.빈 && !x.표시 && !x.기호 && !x.갈곳 && !x.기록 && !x.글.startsWith('조 제목:');
const 항덩어리인가 = (x) => !!x && !x.빈 && !!x.기호;
// 표시 없는 변경 안 — 「(신설)」·「(변경)」·「(제거)」 줄이 하나도 없다(같은 조 ⑤) //
export const 표시있음 = (it) => (it.줄 || []).some((x) => x.표시);

// 의회 파일·설계실 파일을 읽어 항목 배열을 돌려준다. //
export function 법안읽기(원문, 문서 = 'assembly.md') {
  const 줄 = String(원문 || '').split('\n'), 목록 = [];
  let 지금 = null, 계획안 = false;
  for (let l of 줄) {
    if (l.endsWith('\r')) l = l.slice(0, -1);
    if (l.startsWith('## ')) {
      const 머리 = l.slice(3).trim();
      // 종류는 법안 몸을 다 읽은 뒤 정한다(안종류()) //
      지금 = { 제목: 머리, 이름: 구분자로가르기(머리)[0], 소속: 소속앞부분(소속전문꺼내기(머리)), 문서: 들어갈문서(머리),
        종류: '', 표시: '', 코멘트: {}, 줄: [], 계획: [] };
      지금.곳 = 주인저장소(지금.문서);
      목록.push(지금); 계획안 = false;
      continue;
    }
    if (!지금) continue;
    const t = l.trim();
    if (t.startsWith('> 📌')) { 지금.표시 = 답줄읽기(t.slice(4)); continue; }
    // 코멘트 줄 모양: 「> 💬 **줄키** | 날짜 | 글」 — 옛 「 · 」도 읽는다 //
    if (t.startsWith('> 💬')) {
      const 조각 = t.slice(4).split(/ [·|] /);
      지금.코멘트[민글(조각[0] || '').trim()] = 조각.slice(2).join(' | ').trim();
      continue;
    }
    // 설계안의 구현 계획 묶음 — 몸이 아니라 따로 글자 그대로 보인다(bp-설계실 「상황판 설계실 화면은 …의회 화면과 같은 박스로 연다」 조 ②) //
    if (t.startsWith('**구현 계획')) { 계획안 = true; continue; }
    if (계획안) { if (t !== '---') 지금.계획.push(l); continue; }
    if (t === '---') continue;   // 법안 사이 가름 줄 //
    const x = 줄읽기(l), 앞 = 지금.줄[지금.줄.length - 1];
    if (붙일줄인가(x) && 항덩어리인가(앞)) { 앞.글 += '\n' + x.글; 앞.원 += '\n' + x.원; continue; }
    지금.줄.push(x);
  }
  for (const it of 목록) {
    while (it.계획.length && !it.계획[it.계획.length - 1].trim()) it.계획.pop();
    while (it.줄.length && it.줄[0].빈) it.줄.shift();
    while (it.줄.length && it.줄[it.줄.length - 1].빈) it.줄.pop();
    짝잇기(it.줄);
    it.종류 = 안종류(it);
  }
  return 목록;
}
