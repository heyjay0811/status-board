// 원격 켜기 셈 `remote-on.mjs`의 시험 — 파일 이름 · 글 읽기 · 적어도 되는 자리 · 처리할 요청 · 버튼 글을 본다. //
// 따르는 설계: bp-원격켜기 제1조 · 제2조, bp-백엔드 제5조 ③. //
import { 원격자리, 결과이름, 결과이름인가, 요청글짓기, 결과글짓기, 요청읽기, 결과읽기, 원격켜기됨, 처리할요청, 원격상태 } from './remote-on.mjs';
import { 적어도됨 } from './github.mjs';

let 통과 = 0, 실패 = 0;
const 확인 = (이름, 조건, 실제) => {
  if (조건) { 통과++; console.log(`  ✅ ${이름}`); }
  else { 실패++; console.log(`  ❌ ${이름}\n     실제: ${JSON.stringify(실제)}`); }
};

const 지금 = Date.parse('2026-11-17T12:00:00.000Z');
const 요1 = '20261117T114000000Z-abcd1234-000001.json', 요2 = '20261117T115500000Z-abcd1234-000002.json';
const 글1 = 요청글짓기('2026-11-17T11:40:00.000Z'), 글2 = 요청글짓기('2026-11-17T11:55:00.000Z');
const 결2 = 결과글짓기({ 요청: 요2, 켠: ['moneybook / 고고'], 이미켜짐: ['management / 393 진행 상황'], 못켠: [{ 세션: 'yessoft / 강의 영상 다운로드', 까닭: '눌러도 안 켜짐' }] });

console.log('① 이름과 글');
확인('결과 이름은 요청 이름 뒤에 -결과', 결과이름(요1) === '20261117T114000000Z-abcd1234-000001-결과.json', 결과이름(요1));
확인('결과 이름을 알아본다', 결과이름인가(결과이름(요1)));
확인('요청 이름은 결과 이름이 아니다', !결과이름인가(요1));
확인('요청 글을 읽는다', 요청읽기(요1, 글1)?.무엇 === '요청');
확인('결과 글은 요청 글이 아니다', 요청읽기(요2, 결2) === null);
확인('결과 글을 읽는다', 결과읽기(결과이름(요2), 결2)?.켠.length === 1);
확인('다른 요청의 결과 이름이면 결과가 아니다', 결과읽기(결과이름(요1), 결2) === null);

console.log('② 적어도 되는 자리(bp-백엔드 제5조 ③)');
확인('관리부 원격 켜기 자리의 요청은 된다', 적어도됨('management', 원격자리 + 요1, 글1));
확인('관리부 원격 켜기 자리의 결과는 된다', 적어도됨('management', 원격자리 + 결과이름(요2), 결2));
확인('다른 저장소면 안 된다', !적어도됨('moneybook', 원격자리 + 요1, 글1, ['moneybook']));
확인('하위 폴더면 안 된다', !원격켜기됨('management', 원격자리 + 'a/' + 요1, 글1));
확인('요청 이름에 결과 글이면 안 된다', !적어도됨('management', 원격자리 + 요2, 결2));
확인('글이 요청도 결과도 아니면 안 된다', !적어도됨('management', 원격자리 + 요1, '{"무엇":"다른것"}'));
확인('원격 켜기 자리 밖(작업계획 목록)은 여전히 안 된다', !적어도됨('management', 'docs/work.md', 글1));

console.log('③ 처리할 요청(bp-원격켜기 제2조 ②)');
확인('결과 없는 가장 늦은 요청', 처리할요청([{ 이름: 요1, 글: 글1 }, { 이름: 요2, 글: 글2 }], 지금) === 요2);
확인('결과가 있으면 그 요청은 끝났고 이른 요청은 처리하지 않는다', 처리할요청([{ 이름: 요1, 글: 글1 }, { 이름: 요2, 글: 글2 }, { 이름: 결과이름(요2), 글: 결2 }], 지금) === 요1);
확인('30분이 지난 요청은 처리하지 않는다', 처리할요청([{ 이름: 요1, 글: 글1 }], 지금 + 31 * 60 * 1000) === null);
확인('파일이 없으면 null', 처리할요청([], 지금) === null);

console.log('④ 버튼 글(bp-원격켜기 제1조 ⑤)');
확인('요청이 없으면 원격 켜기', 원격상태([]).버튼 === '원격 켜기');
확인('결과가 없으면 원격 켜는 중', 원격상태([{ 이름: 요2, 글: 글2 }]).버튼 === '원격 켜는 중');
확인('결과가 있으면 켠 수', 원격상태([{ 이름: 요2, 글: 글2 }, { 이름: 결과이름(요2), 글: 결2 }]).버튼 === '원격 켬 1');
const 남음 = { 이름: '20261117T115900000Z-abcd1234-000003.json', 누른시각: '2026-11-17T11:59:00.000Z' };
확인('기기에 남은 요청이 더 늦으면 원격 켜는 중', 원격상태([{ 이름: 요2, 글: 글2 }, { 이름: 결과이름(요2), 글: 결2 }], 남음).버튼 === '원격 켜는 중');

console.log(`\n통과 ${통과} · 실패 ${실패}`);
if (실패) process.exit(1);
