// 「제4조」처럼 적힌 데서 «처음 나오는» 조 번호를 집는다 — 조 제목 줄(## 제N조 …)을 읽는 자다. //
// ★소속 설명에는 쓰지 않는다 — 추천 까닭 괄호 속의 다른 조 번호를 집는다. 소속에는 소속조번호()를 쓴다. //
export function 조번호찾기(t) {
  var 글 = String(t || ''), i = 글.indexOf('제');
  while (i >= 0) {
    var j = i + 1, n = '';
    while (j < 글.length && 글[j] >= '0' && 글[j] <= '9') { n += 글[j]; j++; }
    if (n && 글[j] === '조') return { 번호: parseInt(n, 10), 끝: j + 1 };
    i = 글.indexOf('제', i + 1);
  }
  return null;
}

// 낫표(「…」) 안의 이름을 집는다 — 「머리말 「조문 형식」 변경」에서 어느 대목인지를 뽑는 자다. //
export function 낫표안(t) {
  var 글 = String(t || ''), a = 글.indexOf('「'), b = 글.indexOf('」', a + 1);
  return a >= 0 && b > a ? 글.slice(a + 1, b) : '';
}

// 제목 줄의 칸 구분자(` · `·` | `)가 선 자리들 — 낫표 「…」 안의 구분자는 이름(「키 | 시크릿」 절 같은 것)의 일부라 //
//   구분자로 보지 않는다. 제목·소속을 가르는 곳(법안읽기·소속칩·소속전문꺼내기·갈문서)이 모두 이 잣대를 쓴다. //
// ★전에는 곳곳에서 정규식으로 갈라, 제목에 「키 | 시크릿」이 든 법안의 제목이 「…「키」에서 잘리고 소속 칩이 셋으로 갈라졌다. //
export function 구분자자리들(t) {
  var 글 = String(t || ''), 자리 = [], 깊이 = 0;
  for (var i = 0; i < 글.length; i++) {
    var c = 글[i];
    if (c === '「') 깊이++;
    else if (c === '」') { if (깊이 > 0) 깊이--; }
    else if (!깊이 && (글.slice(i, i + 3) === ' · ' || 글.slice(i, i + 3) === ' | ')) { 자리.push(i); i += 2; }
  }
  return 자리;
}
export function 구분자로가르기(t) {
  var 글 = String(t || ''), 조각 = [], 앞 = 0;
  구분자자리들(글).forEach(function (k) { 조각.push(글.slice(앞, k)); 앞 = k + 3; });
  조각.push(글.slice(앞));
  return 조각;
}

// 법안 제목 줄에서 소속 칸부터 끝까지를 떼 온다. //
// ★제목 줄을 ` · `로 쪼갠 조각 하나만 쓰면 조 제목 「번호 · 기호와 제목 · …」 같은 글이 중간에서 //
//   잘리고, 「항이 온 자리」도 뒤 조각으로 떨어져 나간다. 그래서 자리를 알아볼 때는 통째로 쓴다. //
// [[작업 395]] 설계실 설계안은 소속 칸을 「갈 곳:」으로 적는다(설계 쓰기 스킬 11절) — 같은 칸으로 읽는다. //
export function 소속전문꺼내기(머리) {
  var t = String(머리 || ''), k = 구분자자리들(t).filter(function (i) { return t.slice(i + 3, i + 5) === '소속' || t.slice(i + 3, i + 6) === '갈 곳'; })[0];
  return k != null ? t.slice(k + 3).trim() : '';
}
// 소속 칸 앞의 이름표(「소속:」·「갈 곳:」)를 뗀다 //
function 이름표떼기(t) { return String(t || '').replace(/^(소속|갈 곳):\s*/, ''); }

// [[작업 401]] 소속 설명에서 «자리를 가리키는 앞부분»만 떼 온다 — 추천 까닭 괄호(「 (추천 까닭: …」)와 //
// ` · `로 붙는 덧말 앞까지다. 낫표와 백틱 안은 조 제목·파일 이름이라 거기서는 끊지 않는다. //
// ★「의회 스킬(`~/.claude/skills/assembly`) 제2조」처럼 이름에 바로 붙은 괄호는 앞부분이다 — 띄어 쓴 //
//   괄호만 덧말로 본다. //
export function 소속앞부분(소속) {
  var t = 이름표떼기(String(소속 || '').trim()).trim();
  var 깊이 = 0, 코드 = false;
  for (var i = 0; i < t.length; i++) {
    var c = t[i];
    if (c === 의회백틱) { 코드 = !코드; continue; }
    if (코드) continue;
    if (c === '「') { 깊이++; continue; }
    if (c === '」') { if (깊이 > 0) 깊이--; continue; }
    if (!깊이) {
      if (t.slice(i, i + 2) === ' (') return t.slice(0, i).trim();
      // [[작업 404]] ` · `에서는 뒤가 답 칸·항이 온 자리·되올림 같은 덧말일 때만 자른다. //
      // ★전에는 모든 ` · `에서 잘라, 정해진 소속 모양 「주인 종류 `이름` · 제N조 ② 변경」(제정 279)의 조 번호와 //
      //   「변경」이 앞부분 밖으로 떨어져 지금 글을 못 읽고 모든 법안이 신설로 읽혔다(2026-09-20 실제 의회 파일로 확인). //
      if ((t.slice(i, i + 3) === ' · ' || t.slice(i, i + 3) === ' | ') && /^(답\s*:|항이 온 자리|되올림)/.test(t.slice(i + 3))) return t.slice(0, i).trim();
    }
  }
  return t;
}

// 낫표 안(조 제목)과 백틱 안(파일 이름)을 뺀 글 — 「새 조」·「머리말」·「제N조」 같은 판단 낱말은 여기서 찾는다. //
// ★조 제목에 「제5조」 같은 글이 들어 있어도 그것을 들어갈 자리로 집지 않게 한다. //
function 낫표밖(t) {
  var 글 = String(t || ''), 밖 = '', 깊이 = 0, 코드 = false;
  for (var i = 0; i < 글.length; i++) {
    var c = 글[i];
    if (c === 의회백틱) { 코드 = !코드; continue; }
    if (코드) continue;
    if (c === '「') { 깊이++; continue; }
    if (c === '」') { if (깊이 > 0) 깊이--; continue; }
    if (!깊이) 밖 += c;
  }
  return 밖;
}

// 백틱 안의 글(파일 이름·경로)을 차례대로 모은다. //
