function 절이름(s) { return String(s || '').replace(/^#+\s*/, '').replace(/ [·|] /g, ' · ').trim(); }
function 절같나(머리, 이름) { var a = 절이름(머리), b = 절이름(이름); return !!b && (a === b || a.indexOf(b) === 0); }

// 설계도 파일 이름 — 「`bp-상황판`」·「`bp-코덱스.md`」에서 bp-이름.md를 뽑는다. //
