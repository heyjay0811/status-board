  var 새자리 = 밖.indexOf('새 조') >= 0 || 밖.indexOf('새 제') >= 0 || 밖.indexOf('새 훅') >= 0 || (밖.indexOf('신설') >= 0 && !항추가인가(소속));

  var 종류 = '파일', 주소 = null;
  // [[작업 404]] 소속 칸의 정해진 모양 「주인 종류 `이름` · 제N조 ② 변경」(의회 스킬 제2조 ⑥ · 제정 279)을 읽는다. //
