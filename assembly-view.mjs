// bp-의회의 「상황판 의회 화면은 조문을 팝업 박스 하나로 열고, 갈 자리와 바뀔 내용을 함께 보여준다」 — 조 번호가 없는 자리(부서 규칙 파일의 절·줄)를 소속에서 읽는다: 「「작업장」 절 12행 변경」 → //
//   [{절: '작업장'}, {가: 12, 나: 12}]. 「절 제목」은 {제목: true}로, 적힌 차례 그대로 돌려준다. //
// ★낫표 안은 절 이름이라 그 안의 숫자·「 | 」로 자르지 않는다 — 「「키 | 시크릿」 절」 같은 소속이 여기서 갈리면 못 읽는다. //
export function 줄자리읽기(소속) {
  var 앞 = 소속앞부분(소속), 표 = [], 절있음 = false, m;
  var 자 = /「([^」]*)」\s*절|(\d+)(?:~(\d+))?행|제목/g;
  while ((m = 자.exec(앞))) {
    if (m[1] != null) { 표.push({ 절: m[1] }); 절있음 = true; }
    else if (m[2]) 표.push({ 가: parseInt(m[2], 10), 나: parseInt(m[3] || m[2], 10) });
    else if (절있음) 표.push({ 제목: true });
  }
  return 표;
}

// 절 이름을 견줄 모양으로 — 머리의 「## 」를 떼고, 가운뎃점과 「 | 」를 한 모양으로 둔다(소속에 「키 · 시크릿」이 //
