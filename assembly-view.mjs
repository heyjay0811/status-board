// 의회 박스 부품 — 법안 글을 그리는 부품(꾸밈 · 달라진 데 칠하기 · 항 밖 글 · 파일 미리보기)과 법안 목록을 묶는 부품. //
//
// ★왜 따로 빼나 — 시험이 이 파일을 바로 부를 수 있게 화면 코드(app.mjs) 밖에 둔다. //
// ★여기서는 파일을 읽지 않는다. //
// [관리부 작업 456] 법안이 가리키는 갈 곳 파일을 알아보고 그 지금 글을 읽어 항마다 짝짓던 부품(소속자리() · 지금글찾기() · //
//   조문나누기() · 짝찾기() · 조전체짝() · 줄자리짝() 들)을 걷었다 — 박스는 이제 법안에 적힌 줄만 보고 칠한다 //
//   (bp-의회 「법안 종류와 고치는 글의 표시 읽기」 조). //
//
// 승인 bp-의회의 「상황판 의회 화면은 조문을 팝업 박스 하나로 열고, 갈 자리와 바뀔 내용을 함께 보여준다」가 근거다. //

var 의회백틱 = String.fromCharCode(96);
var 의회기록 = function (말) { console.log('[의회 박스] ' + 말); };

export function 막기(s) {
  return String(s == null ? '' : s).split('&').join('&amp;')
    .split('<').join('&lt;').split('>').join('&gt;').split('"').join('&quot;');
}

// 제6조 ③ — 박스는 굵게(별표 둘)와 코드(백틱)만 그리고 다른 꾸밈은 더하지 않는다. //
// ★홀짝으로 씌운다 — 여는 것과 닫는 것이 같은 글자라 쪼갠 조각의 홀수 자리가 곧 «안쪽»이다. //
export function 꾸미기(s) {
  var 조각 = 막기(s).split('**');
  var t = 조각.map(function (x, i) { return i % 2 ? '<b>' + x + '</b>' : x; }).join('');
  return t.split(의회백틱).map(function (x, i) { return i % 2 ? '<code>' + x + '</code>' : x; }).join('');
}

// 제6조 ⑧ — 지금 글과 바뀔 글을 맞대 보일 때는 굵게 표시를 벗기고 «글자만» 견준다. //
export function 민글(s) { return String(s == null ? '' : s).split('**').join(''); }

// 굵게를 벗긴 글과 같은 순서로, 글자마다 굵게·코드 여부를 달아 둔다. //
// ★견주기는 굵게를 벗긴 글자로 하고(⑧) 그리기는 꾸밈을 살리려면(③) 두 글의 자리가 하나하나 맞아야 //
//   한다. 별표 둘은 빼고(민글과 같다), 백틱은 자리를 지키되 「표지」로만 둬 그리지 않는다. //
function 꾸밈풀기(s) {
  var 글 = String(s == null ? '' : s), 굵게 = false, 코드 = false, 낱 = [];
  for (var i = 0; i < 글.length; i++) {
    if (글[i] === '*' && 글[i + 1] === '*') { 굵게 = !굵게; i++; continue; }
    if (글[i] === 의회백틱) { 코드 = !코드; 낱.push({ 자: 글[i], 표지: true }); continue; }
    낱.push({ 자: 글[i], 굵게: 굵게, 코드: 코드 });
  }
  return 낱;
}

// 풀어 둔 글자를 다시 그린다 — 짚을 자리 [가, 나)에는 mark를 씌운다. //
// ★꾸밈이 같은 글자끼리 한 덩어리로 묶고 덩어리마다 태그를 열고 닫는다 — 짚는 자리가 코드 한가운데서 //
//   끝나도 태그가 엇갈리지 않는다. //
function 낱그리기(낱, 가, 나) {
  var 밖 = '', 앞열쇠 = '', 닫을 = '';
  for (var i = 0; i < 낱.length; i++) {
    var x = 낱[i];
    if (x.표지) continue;
    var 짚음 = i >= 가 && i < 나;
    var 열쇠 = (짚음 ? 'm' : '') + (x.굵게 ? 'b' : '') + (x.코드 ? 'c' : '');
    if (열쇠 !== 앞열쇠) {
      밖 += 닫을;
      닫을 = '';
      if (짚음) { 밖 += '<mark>'; 닫을 = '</mark>' + 닫을; }
      if (x.굵게) { 밖 += '<b>'; 닫을 = '</b>' + 닫을; }
      if (x.코드) { 밖 += '<code>'; 닫을 = '</code>' + 닫을; }
      앞열쇠 = 열쇠;
    }
    밖 += 막기(x.자);
  }
  return 밖 + 닫을;
}

// [[작업 426]] 제6조 ⑧(제정 508) — 견주기 전에 조문 글이 아닌 자리 표시를 벗긴다. 줄마다 머리의 목록 표시 `- `, //
//   첫 줄 머리의 「13행 — 」·「「## 문서」 절(28~35행 자리) — 」 같은 행 번호·절 이름, 그 뒤에 글 전체를 감싼 「」다. //
// ★자리 표시가 남으면 두 글이 첫 글자부터 달라 보여, 끝 몇 글자만 바뀐 항도 문장 전체가 칠해졌다. //
// ★머리는 행 번호나 「…」 절로 시작할 때만 벗긴다 — 조문 글 속의 「 — 」까지 머리로 잘라 먹지 않게. //
export function 자리벗기기(s) {
  var 줄 = String(s == null ? '' : s).split('\n').map(function (l) { return l.replace(/^(\s*)- /, '$1'); });
  줄[0] = 줄[0].replace(/^\s*(?:\d+(?:~\d+)?행|「[^」]*」\s*절)[^—\n]{0,40}\s—\s+/, '');
  var 글 = 줄.join('\n').trim();
  if (글[0] !== '「' || 글[글.length - 1] !== '」') return 글;
  // 첫 「가 맨 끝 」에서 닫힐 때만 감싼 것이다 — 「가」 … 「나」처럼 따로 닫히는 글은 그대로 둔다 //
  for (var i = 0, 깊이 = 0; i < 글.length; i++) {
    if (글[i] === '「') 깊이++;
    else if (글[i] === '」' && --깊이 === 0 && i < 글.length - 1) return 글;
  }
  return 글.slice(1, -1).trim();
}

// 제6조 ⑥ — 두 문장에서 같은 앞뒤를 빼고 «달라지는 가운데»만 짚는다. //
// [[작업 401]] 제6조 ③ — 전에는 굵게를 벗긴 글을 글자 그대로 내보내 백틱이 글자로 보였다. 이제 //
//   견주기는 굵게를 벗긴 글자로 하고(⑧), 그리기는 굵게·코드를 살린다. //
export function 달라진데(a0, b0) {
  var a = 민글(a0), b = 민글(b0), 낱 = 꾸밈풀기(b0);
  var s = 0; while (s < a.length && s < b.length && a[s] === b[s]) s++;
  var e = 0; while (e < a.length - s && e < b.length - s && a[a.length - 1 - e] === b[b.length - 1 - e]) e++;
  if (s >= b.length - e) return 낱그리기(낱, -1, -1);
  return 낱그리기(낱, s, b.length - e);
}

// 제6조 ⑥ — 지금 글 쪽에서 «없어지는 대목»을 짚는다. 달라진데()는 뒤 글만 칠해, 글을 끝에서 지우기만 한 변경은 //
//   「바뀜」 딱지만 서고 칠할 데가 없었다. 앞뒤를 맞바꿔 부르면 같은 잣대로 지금 글의 달라진 가운데를 칠한다. //
export function 지운데(지금0, 새0) { return 달라진데(새0, 지금0); }

