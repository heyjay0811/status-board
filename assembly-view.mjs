// ★자리를 알아보는 차례: 새 자리 → 정해진 모양(주인 종류 `이름`) → 전역 규칙 → 회장실 → 관리부 → //
//   다른 프로젝트 → 못 알아봄. //
// ★옛 소속 모양(백틱 속 ~/.claude 경로 · 「훅」으로 시작 · 이름표 · 맨 bp-)을 짐작하던 갈래는 //
