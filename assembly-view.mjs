// ★「소속:」 뒤부터 첫 「 · 」 앞까지를 글자 그대로 쓴다 — 파일 주소를 짐작하지 않는다. 짐작하던 때는 모양이 //
//   다른 소속 15건이 어디로 갈지 못 가렸고, 모든예약 설계 법안이 관리부 설계로 갔다(2026-09-16 실제 의회 파일로 확인). //
export function 갈문서(제목) {
  var t = 이름표떼기(소속전문꺼내기(제목)).trim();
  var k = 구분자자리들(t)[0];
  return (k != null ? t.slice(0, k) : t).trim();
}

// [[작업 404]] 제6조 ⑮⑯(제정 292) — 법안을 두 단계로 묶는다. 제목들은 의회 파일에 올라온 차례의 법안 제목 줄이다. //
// 큰 묶음은 갈 문서에서 끝의 이름(`safe-area` 같은 것)을 뗀 「주인 종류」(전역 스킬 · 관리부 설계 · 회장실)이고, //
// 작은 묶음은 주소들[i](법안마다 소속자리()가 알아낸 실물 파일 주소)로 가르고, 주소가 없는 법안만 갈 문서 글자로 가른다(제6조 ⑯). //
// 돌려주는 것: [{이름, 문서들: [{이름, 번호들(법안 차례, 0부터)}]}]. //
