// [[작업 404]] bp-의회의 「상황판 의회 화면은 조문을 팝업 박스 하나로 열고, 갈 자리와 바뀔 내용을 함께 보여준다」 · 의회 스킬 제6조 ⑦(제정 279) — 법안이 갈 문서. 소속 칸 맨 앞에 //
