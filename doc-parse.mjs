// 프로젝트 문서(구상 창고·작업 목록·검증 대기·오답노트와 그 이력)의 항목 첫 줄을 알아보는 공통 부품 — 경로 규칙 `rule-문서` 제1조(항목 첫 줄 모양)의 구현. //
//
// 무엇을 하나: 문서를 줄 단위로 훑으면서 "이 줄이 새 항목의 시작인가, 본문인가"를 판정한다. //
//   판정 규칙은 `rule-문서` 제1조에 있고 여기 원문을 복사하지 않는다 — 요지만: 항목 첫 줄은 //
//   #이 정확히 둘인 줄이고 `## [종류 N] · 제목 · 필드 · 날짜` 꼴이며(①②④), # 셋 이상은 항목 안 //
//   소제목이고(②), 코드블록(백틱 세 개로 감싼 상자) 안은 통째로 건너뛴다(③). //
//
// ★왜 도구마다 따로 두지 않고 여기 한 벌만 두나: 같은 판정을 두 곳에 두면 한 곳만 고쳐져 반드시 갈린다. //
//   그래서 상황판 진행 현황(progress-data.mjs·progress.mjs)과 환경 목록(env-collect.mjs)이 이것을 함께 쓴다. //
//
// ★코드블록 안의 예시를 항목으로 읽으면 없는 항목이 화면에 뜬다. 그 번호는 실물 번호와 //
//   겹치지 않아 아무 신호 없이 거짓 항목이 남는다. //
//   (예시에는 도달 불가한 번호를 쓴다 — 실제 번호를 쓰면 그 번호가 나중에 진짜로 생겨 //
//    검사가 예시를 실물로 읽는다. 여기 주석에서 실제 번호를 안 쓰는 이유도 같다.) //
//
// ★[작업 402] 2026-09-14 — 읽는 규칙을 `rule-문서` 제1조에 맞춰 좁혔다. 전에는 # 없는 평문 줄 //
//   (`[구상 N] · …`), 종류 없는 `[N]`, 번호 없는 `##` 줄(상태 낱말만 있으면)도 항목으로 읽었다. //
//   지금은 셋 다 항목이 아니다. 그런 줄을 따로 세던 갈래(건너뛴줄·옛형식수)는 읽는 곳이 없어 //
//   2026-09-27에 걷었다. //

// 항목 첫 줄 — # 정확히 둘 + 빈칸 + `[종류 N]`(`rule-문서` 제1조). //
//   # 뒤에 빈칸을 요구하므로 `###`(항목 안 소제목)과 `#`(파일 제목)은 걸리지 않는다 — 안 그러면 //
//   `### ([작업 3]의 원래 계획 …)` 같은 소제목이 새 항목으로 읽힌다. //
//   번호 뒤 가운뎃점은 없어도 받는다 — # 둘 자체가 "여기가 항목이다"라는 표시라서, 아직 안 고친 //
//   옛 작업 제목 `## [작업 1] 제목 — 진행중 · 날짜`까지 항목에서 빠지면 그 작업이 통째로 사라진다. //
//   종류는 `rule-문서` 제1조의 넷(구상·작업·검증·오류)뿐이다 — 옛 `[설계 N]` 항목을 읽던 갈래는 옛 설계 파일 //
//   (`blueprint.md`)이 다 없어져 2026-09-27에 걷었다. 설계는 이제 `bp-*.md` 파일과 조로 부른다. //
const 항목첫줄 = /^##[ \t]+\[(구상|작업|검증|오류)[ \t]+(\d+)\][ \t]*[·|]?[ \t]*(.*)$/;

/** 코드블록 여닫이 — 앞에 공백이 있어도(목록 안 코드블록) 인정한다. */
const 코드울타리 = /^\s*```/;

/** 줄 끝의 CR(`\r`)을 뗀다.
 *  안 떼면 CRLF(윈도우 줄바꿈) 파일에서 한 줄도 못 읽는다 — 자바스크립트 정규식의 `.`는 줄바꿈 문자를
 *  안 먹어서 끝의 `(.*)$`가 `\r` 앞에서 멈추는데, `$`는 문자열 끝에만 맞아 매칭 전체가 실패한다.
 *  프로젝트마다 줄바꿈이 달라(LF·CRLF) 한쪽에서만 항목이 0개가 되는데, 조용히 0이라 "문제 없음"과
 *  구별되지 않는다. `줄훑기`로 읽으면 split이 CR을 떼주지만, `항목머리`를 직접 부르는 쪽은 그 보호가 없다. */
const CR떼기 = (줄) => String(줄).replace(/\r+$/, '');

/**
 * 문서를 줄 단위로 훑는다. 각 줄마다 이런 모양을 돌려준다:
 *   { 줄, 줄번호, 코드블록안, 머리 }
 * `머리`는 그 줄이 항목 첫 줄일 때만 채워지고, 아니면 null이다:
 *   { 종류, 번호, 나머지 }
 * 코드블록 안의 줄은 `머리`가 언제나 null이다 — 본문으로는 흘러가되 항목으로는 안 읽힌다.
 */
// `rule-문서` 제1조 — 코드블록 상태를 이어 붙인다. 한 줄 판정 자체는 항목머리가 한다. //
export function* 줄훑기(원문) {
  let 코드블록 = false;
  let 줄번호 = 0;
  for (const 줄 of String(원문).split(/\r?\n/)) {
    줄번호++;
    if (코드울타리.test(줄)) {
      코드블록 = !코드블록;
      yield { 줄, 줄번호, 코드블록안: true, 머리: null };
      continue;
    }
    const 머리 = 코드블록 ? null : 항목머리(줄);
    yield { 줄, 줄번호, 코드블록안: 코드블록, 머리 };
  }
}

/** 한 줄만 보고 항목 첫 줄인지 판정한다. 코드블록 안인지는 이 함수가 알 수 없으므로
 *  파일을 훑을 때는 반드시 `줄훑기`를 쓴다(이 함수를 직접 쓰면 코드블록 예시에 걸린다). */
// `rule-문서` 제1조 — 이 프로젝트의 모든 문서 도구가 "무엇이 항목인가"를 여기 하나에 묻는다. //
export function 항목머리(줄) {
  const 맞음 = CR떼기(줄).match(항목첫줄);
  if (맞음) return { 종류: 맞음[1], 번호: Number(맞음[2]), 나머지: 맞음[3] };
  return null;
}

/**
 * 그 문서의 항목 첫 줄만 모아 준다. 번호만 필요한 도구가 쓴다
 * (전역 훅 `before-tool-doc-number-guard.mjs`가 이것의 번호·나머지를 쓴다).
 */
// `rule-문서` 제1조 — 항목 첫 줄만 모은다. //
export function 항목들(원문, { 종류 = null } = {}) {
  const 결과 = [];
  for (const { 머리, 줄번호, 줄 } of 줄훑기(원문)) {
    if (!머리) continue;
    if (종류 && 머리.종류 !== 종류) continue;
    결과.push({ ...머리, 줄번호, 줄 });
  }
  return 결과;
}

// ─────────────────────────────────────────────────────────────────────────────── //
// 필드 분해 — 항목 첫 줄의 `제목 · 필드 · 날짜`를 갈라 읽는다(`rule-문서` 제1조). //
//
// ★필드는 자리 순서가 아니라 생김새로 찾는다 — 날짜는 `2026-07-19` 꼴, 태그는 `#`로 시작, //
//   상태는 정해진 낱말, 참조는 `[작업 N]`·`[설계 N]` 꼴. 그래서 필드가 빠지거나 순서가 달라도 안 깨진다. //
// ★구분자는 앞뒤에 빈칸이 있는 ` · ` 하나다. 제목 안에 빈칸 없이 붙은 `·`와 ` — `(줄표)는 //
//   구분자가 아니라 제목의 글자다 — 전에는 ` — `에서도 잘라, 제목 속 줄표가 ` · `로 바뀌어 //
//   화면의 제목이 문서의 제목과 달랐다. //
// ★어느 조각이 제목인지는 '필드로 안 읽히는 조각'이라는 소거법으로 정한다. 제목을 먼저 잡으려 하면 //
//   제목 안에 든 `[작업 9]를 …` 같은 말이 참조 필드로 먹혀 제목이 빈칸이 된다. //
// ─────────────────────────────────────────────────────────────────────────────── //
const 날짜눈 = /(\d{4}-\d{2}(?:-\d{2}|월))/;                 // 2026-07-19 · 2026-06월 둘 다 //
// 상태 낱말 — 작업은 `작업`(`rule-문서` 제2조), 검증은 `가능`·`환경대기`(`rule-문서` 제5조). //
// ★상태 뒤의 괄호 단서를 허용한다 — `작업(보류)`(제6조 ⑦)·`완료(실기기 검증)`처럼 실제로 //
//   쓰이고 있고, 그것은 상태가 아니라 **상태 + 단서**다("어떤 조건에서 끝냈나"·"왜 멈췄나"). //
//   괄호를 금지하면 그 정보가 사라지므로 상태는 앞부분으로 판정하고 단서는 그대로 둔다. //
// ★`구상`은 작업 상태가 아니다([작업 143]) — 할지 말지 모르는 것은 구상 창고에 살고, //
//   하기로 정해지는 순간 `작업`으로 작업 목록에 온다. //
// ★옛 낱말 `계획`·`진행중`도 계속 읽는다([작업 363]에서 `작업` 하나로 합쳤다) — 이력 파일에 //
//   이미 수백 건이 그 낱말로 적혀 있고, 못 읽으면 지난 기록의 상태가 통째로 빈칸이 된다. //
//   손댔다는 표시는 상태 낱말이 아니라 제목 맨 앞의 ▶가 맡는다(제6조 ③). //
const 상태눈 = /^(작업|계획|진행중|완료|취소|가능|환경대기)(\([^)]*\))?$/;
// 태그 — `#`로 시작하는 낱말이 빈칸으로 여럿 이어진 조각(`#규칙 #작업`). //
const 태그눈 = /^#[^\s#]+(?:\s+#[^\s#]+)*$/;
// 작업 참조 — 검증 항목의 `[작업 M]` 필드(`rule-문서` 제1조). 조각 전체가 참조일 때만 필드다. //
const 작업눈 = /^(?:\[작업\s+\d+\]\s*)+$/;
// 옛 설계 참조 — 옛 이력 항목의 `[설계 N]`·`[설계 N]을 낳음` 필드. 지금 설계에는 없지만 옛 기록을 읽으려고 남긴다. //
const 설계눈 = /^(?:\[설계\s+[\d~,\s]+\]\s*)+(을 낳음|를 낳음|관련|구현|배포|실증)?$/;

// 항목 첫 줄의 나머지 부분에서 어느 조각이 무슨 필드인지 판정하는 유일한 자리(`rule-문서` 제1조). //
//   돌려주는 값: { 제목, 상태, 날짜, 설계, 태그, 작업 } — 태그·작업은 [작업 402]에서 더했다. //
export function 필드분해(나머지) {
  const 조각들 = String(나머지 ?? '').split(/[ \t]+[·|][ \t]+/).map((s) => s.trim()).filter(Boolean);
  let 상태 = null, 날짜 = null;
  const 제목조각 = [], 설계 = [], 태그 = [], 작업 = [];
  for (const 조각 of 조각들) {
    if (!상태 && 상태눈.test(조각)) { 상태 = 조각; continue; }
    if (태그눈.test(조각)) { 태그.push(...조각.split(/\s+/)); continue; }
    if (작업눈.test(조각)) { 작업.push(조각); continue; }
    if (설계눈.test(조각)) { 설계.push(조각); continue; }
    const d = 조각.match(날짜눈);
    if (d && 조각.length <= 24) { 날짜 ||= d[1]; continue; }  // 날짜만 든 조각(꼬리말 붙은 짧은 것 포함) //
    제목조각.push(조각);
  }
  if (!날짜) 날짜 = (String(나머지 ?? '').match(날짜눈) || [])[1] || null;  // 제목에 섞여 있으면 거기서라도 //
  return { 제목: 제목조각.join(' | '), 상태, 날짜, 설계, 태그, 작업 };
}

// [작업 370] 「보류」인가 — 상태 낱말 뒤 괄호에 그 글자가 들었나로 판정한다(`작업(보류)` — `rule-문서` 제2조). //
//
// ★왜 새 상태 낱말을 안 만들었나. 보류도 **살아 있는 작업**이라 «살아있는 상태 낱말은 `작업` 하나»를 //
//   깨지 않는다. 괄호 단서는 `상태눈`이 이미 받고 있었으므로(위 정규식) 읽는 쪽을 한 줄 더하는 것으로 끝난다. //
// ★판정을 여기 한 곳에 두는 이유는 늘 같다 — 흩어지면 갈라진다. //
// ⚠️단 전역 훅 `~/.claude/hooks/before-tool-work-title-guard.mjs`는 이것을 못 쓰고 같은 판정을 자기 정규식으로 갖는다. //
//   전역 훅은 이 폴더가 없는 기계에서도 돌아야 해서 이 도구에 기댈 수 없기 때문이다. //
export const 보류인가 = (항목) => /\(\s*보류\s*\)/.test(항목?.상태 ?? '');

// [작업 395] `rule-문서` 제10조 ⑨ · 상황판 설계 제2조 ⑩ — 작업 본문 첫 줄의 상태 줄 //
//   「> 상태 | 결정할 사항: … | 남은 작업: … | 진행 상황: … | 날짜」를 칸으로 가른다. 상태 줄이 없으면 null이다. //
// ★칸 안의 글에도 「 | 」가 들어갈 수 있어(인용한 제목 같은 것), 이름표(결정할 사항:·남은 작업:·진행 상황:)로 시작하지 //
//   않는 조각은 앞 칸에 도로 붙인다. 날짜는 맨 끝 조각이 날짜 모양일 때만 뗀다. //
//   결정할 사항 칸이 「없음」으로 시작하지 않으면 결정이 필요하다. //
const 이름표 = { '결정할 사항': '결정할사항', '남은 작업': '남은작업', '진행 상황': '진행상황' };
export function 상태줄읽기(본문) {
  const 첫 = String(본문 ?? '').split('\n').map((l) => l.trim()).find((l) => l) || '';
  if (!/^>\s*상태\s*\|/.test(첫)) return null;
  const 조각 = 첫.replace(/^>\s*상태\s*\|\s*/, '').split(/\s+\|\s+/);
  let 날짜 = null;
  if (/^\d{4}-\d{2}-\d{2}$/.test(조각[조각.length - 1] || '')) 날짜 = 조각.pop();
  const 칸 = { 결정할사항: '', 남은작업: '', 진행상황: '' };
  let 이번 = null;
  for (const c of 조각) {
    const m = c.match(/^(결정할 사항|남은 작업|진행 상황):\s*(.*)$/);
    if (m) { 이번 = 이름표[m[1]]; 칸[이번] = m[2]; } else if (이번) 칸[이번] += ' | ' + c;
  }
  return { ...칸, 날짜, 결정필요: !!칸.결정할사항 && !/^없음/.test(칸.결정할사항) };
}

// [관리부 작업 443] 관리부 설계 `bp-상황판` 제13조 ③④⑤ · `rule-문서` 제10조 ⑪ · 제11조 — 작업 파일(`docs/작업/작업-N.md`)을 읽는다. //
//   소제목(`### `로 시작하는 줄)마다 절 하나로 파일에 적힌 차례대로 가르고, 첫 소제목 앞 글(파일 제목 줄 같은 것)은 앞글로 둔다. //
// ★코드블록 안의 `### `·`지시 N (` 줄은 소제목·지시로 읽지 않는다 — 예시를 실물로 읽으면 없는 절·지시가 선다. //
export function 작업파일나누기(원문) {
  const 앞글 = [], 절 = [];
  let 지금 = null;
  for (const { 줄, 코드블록안 } of 줄훑기(원문)) {
    const 소제목 = !코드블록안 && /^###\s+(.+?)\s*$/.exec(줄);
    if (소제목) { 지금 = { 제목: 소제목[1], 줄들: [] }; 절.push(지금); continue; }
    (지금 ? 지금.줄들 : 앞글).push(줄);
  }
  const 다듬기 = (줄들) => 줄들.join('\n').replace(/^\s*\n+/, '').replace(/\n+\s*$/, '');
  return { 앞글: 다듬기(앞글), 절: 절.map((x) => ({ 제목: x.제목, 글: 다듬기(x.줄들) })) };
}

// 진행 현황 절의 글을 지시 목록으로 읽는다(제13조 ④⑤ · `rule-문서` 제11조). //
//   지시줄 = 줄이 「지시 N (」로 시작한다 · 보고줄 = 줄이 「> 보고 N (」로 시작한다 · 보고(지시 N) = 같은 번호 N을 단 보고줄 모두. //
//   보고줄 뒤에 이어지는 `>` 줄은 다음 지시줄이나 보고줄 앞까지 그 보고에 붙는다(제11조 ③) — 「> 보고 3 이어서 (」처럼 //
//   보고줄 꼴이 아닌 `>` 줄도 앞 보고의 이음이다. 지시줄 바로 뒤의 `>` 아닌 글은 그 지시의 이음 줄이다. //
//   어느 짝에도 안 드는 줄(보고보다 앞선 `>` 줄, 보고 뒤의 맨글)은 버리지 않고 밖글로 돌려준다. //
// ★짝은 놓인 자리가 아니라 번호로 짓는다 — 담당 여럿이 동시에 보고하면 보고가 도착한 차례대로 섞이기 때문이다. //
//   보고기다림(지시 N) = 보고(지시 N)이 없다(제13조 ⑤). 같은 번호의 지시가 없는 보고는 짝없는보고로 돌려준다. //
export function 진행현황읽기(글) {
  const 지시 = [], 보고 = [], 밖글 = [];
  let 이번 = null;   // 지금 이어 붙일 지시나 보고 //
  for (const { 줄, 코드블록안 } of 줄훑기(글)) {
    const 지시줄 = !코드블록안 && /^지시\s+(\d+)\s*\(/.exec(줄);
    const 보고줄 = !코드블록안 && /^>\s*보고\s+(\d+)\s*\(/.exec(줄);
    if (지시줄) { 이번 = { 번호: Number(지시줄[1]), 줄: 줄, 이음: [] }; 지시.push(이번); continue; }
    if (보고줄) { 이번 = { 번호: Number(보고줄[1]), 줄들: [줄] }; 보고.push(이번); continue; }
    if (!줄.trim()) continue;
    const 인용 = /^\s*>/.test(줄);
    if (인용 && 이번 && 이번.줄들) { 이번.줄들.push(줄); continue; }
    if (!인용 && 이번 && 이번.이음) { 이번.이음.push(줄); continue; }
    밖글.push(줄);
  }
  const 지시번호 = new Set(지시.map((x) => x.번호));
  const 보고글 = (r) => ({ 번호: r.번호, 글: r.줄들.map((l) => l.replace(/^\s*>\s?/, '')).join('\n') });
  return {
    지시: 지시.map((x) => {
      const 짝 = 보고.filter((r) => r.번호 === x.번호).map(보고글);
      return { 번호: x.번호, 글: [x.줄, ...x.이음].join('\n'), 보고: 짝, 보고기다림: 짝.length === 0 };
    }),
    짝없는보고: 보고.filter((r) => !지시번호.has(r.번호)).map(보고글),
    밖글,
  };
}

// `rule-문서` 제1조 — 항목을 첫 줄(번호·필드)과 본문까지 통째로 갈라 배열로 만든다. //
//   본문은 원문 그대로 옮긴다(요약을 새로 쓰지 않는다 — 값 복사 금지). 앞뒤 빈 줄만 턴다. //
//
// ★[작업 402] 전에는 번호가 없어도 상태 필드가 있는 `##` 줄을 항목으로 봤다. 지금은 안 본다 — //
//   `rule-문서` 제1조가 항목 첫 줄을 `## [종류 N] · …` 하나로 정했기 때문이다. 그런 줄과 //
//   옛 모양 줄(평문·종류없음)은 앞 항목의 본문으로 흘러간다. //
export function 항목분해(원문, { 종류 = null } = {}) {
  const 결과 = [];
  let 현재 = null;
  for (const { 머리, 줄 } of 줄훑기(원문)) {
    const 새항목 = 머리 && (!종류 || 머리.종류 === 종류);
    if (!새항목) {
      현재?.본문줄.push(줄);
      continue;
    }
    현재 = { 번호: 머리.번호, 종류: 머리.종류, ...필드분해(머리.나머지), 본문줄: [] };
    결과.push(현재);
  }
  for (const it of 결과) {
    it.본문 = it.본문줄.join('\n').replace(/^\s*\n+/, '').replace(/\n+\s*$/, '');
    delete it.본문줄;
  }
  return 결과;
}
