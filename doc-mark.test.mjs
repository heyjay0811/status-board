// 답·코멘트를 문서에 적는 공통 부품 `doc-mark.mjs`의 시험 — 실제 글을 넣어 결과 글로 확인한다. //
// 따르는 설계: 관리부 설계 `bp-상황판` 제4조 ②③⑥ · 제11조 ③ (2026-09-29 확정) //
import { 표시붙인글, 코멘트붙인글, 찍힌표시, 코멘트달린줄들, 표시글, 답들 } from './doc-mark.mjs';

const 법안 = [
  '# 의회', '', '## 어떤 법안 | #규칙 | 소속: 전역 규칙 · 제1조 ③ 신설', '',
  '조 제목: 어떤 조', '① 있는 항이다.', '- 목록 하나', '- 목록 둘', '③ **(신설)** 새 항이다.', '', '---', '',
  '## 삭제 — 옛 절 | #규칙 | 소속: 일톡 규칙 | 절 삭제', '', '① 원문: 「옛 글」', '왜 지우나: 공통에 있다.', '② 원문: 「옛 글 둘」', '왜 지우나: 없다.', '', '---', '',
].join('\n');
const 설계안 = [
  '# 설계실', '', '## 어떤 설계 | #설계 | 갈 곳: 모든예약 설계 `bp-업장` 제1조 추가', '',
  '조 제목 **(추가)**: 어떤 설계', '① **(추가)** 첫 항이다.', '', '**구현 계획 초안**', '- 바꿀 파일: 없음', '', '---', '',
].join('\n');
const 오늘 = '2026-09-29';
let 통과 = 0; const 실패 = [];
const 확인 = (이름, 조건, 덧 = '') => { if (조건) { 통과++; console.log(`  ✓ ${이름}`); } else { 실패.push(이름); console.log(`  ✗ ${이름}${덧 ? ' — ' + 덧 : ''}`); } };
const 던지나 = (fn) => { try { fn(); return ''; } catch (e) { console.log(`    (막힘: ${e.message})`); return e.message; } };
const 줄들 = (t) => t.split('\n');

console.log('[doc-mark 시험] START');
// 제4조 ② — 의회 답 넷 //
for (const 답 of ['신설', '변경', '제거', '취소']) {
  const 새글 = 표시붙인글(법안, '어떤 법안', 답, 오늘);
  확인(`의회에 ${답}을 찍으면 제목 아래에 그 글자가 붙는다`, 줄들(새글)[4] === `> 📌 ${표시글[답]} | ${오늘}`, 줄들(새글)[4]);
}
확인('의회 파일에는 설계실 답 「추가」를 못 찍는다', 던지나(() => 표시붙인글(법안, '어떤 법안', '추가', 오늘)).includes('찍을 수 없는 답'));
확인('옛 답 「유지」는 새로 못 찍는다', 던지나(() => 표시붙인글(법안, '어떤 법안', '유지', 오늘)).includes('찍을 수 없는 답'));
// 거두기 — 찍힌 단추를 다시 누르면 빈 답이 온다 //
확인('빈 답이면 찍힌 답을 걷는다', !표시붙인글(표시붙인글(법안, '어떤 법안', '제거', 오늘), '어떤 법안', '', 오늘).includes('📌'));
확인('다시 찍으면 답은 하나로 남는다', 표시붙인글(표시붙인글(법안, '어떤 법안', '신설', 오늘), '어떤 법안', '취소', 오늘).split('📌').length === 2);
// 제4조 ③ — 삭제 법안도 항마다가 아니라 법안에 답 하나 //
const 삭제찍힘 = 표시붙인글(법안, '삭제 — 옛 절', '제거', 오늘);
확인('삭제 법안에도 제목 아래에 답 하나를 찍는다', 찍힌표시(삭제찍힘, '삭제 — 옛 절') === '제거');
확인('삭제 법안에 찍어도 앞 법안의 답은 그대로 비어 있다', 찍힌표시(삭제찍힘, '어떤 법안') === '');
// 제4조 ⑥ — 코멘트는 어느 답에나 딸리고, 코멘트를 달아도 답은 그대로 //
for (const 답 of ['신설', '제거', '취소']) {
  const 달림 = 코멘트붙인글(표시붙인글(법안, '어떤 법안', 답, 오늘), '어떤 법안', '①', '이 말은 빼자', 오늘);
  확인(`${답}이 찍힌 법안에 코멘트를 달아도 ${답}은 그대로다`, 찍힌표시(달림, '어떤 법안') === 답);
}
const 코멘트먼저 = 코멘트붙인글(법안, '어떤 법안', '③', '물어볼 게 있다', 오늘);
확인('코멘트가 달린 법안에도 신설을 찍을 수 있다', 찍힌표시(표시붙인글(코멘트먼저, '어떤 법안', '신설', 오늘), '어떤 법안') === '신설');
확인('답 없이 단 코멘트도 남는다(물음)', 코멘트달린줄들(코멘트먼저, '어떤 법안').length === 1 && 찍힌표시(코멘트먼저, '어떤 법안') === '');
const 목록코멘트 = 줄들(코멘트붙인글(법안, '어떤 법안', '①', '목록 뒤에', 오늘));
확인('항 아래 목록이 있으면 코멘트는 목록 끝에 달린다', 목록코멘트[목록코멘트.indexOf('- 목록 둘') + 2] === `> 💬 **①** | ${오늘} | 목록 뒤에`, 목록코멘트.slice(5, 11).join(' / '));
확인('삭제 법안의 항에도 코멘트를 단다', 코멘트달린줄들(코멘트붙인글(법안, '삭제 — 옛 절', '②', '이건 남기자', 오늘), '삭제 — 옛 절').length === 1);
확인('빈 코멘트는 그 줄 코멘트를 걷는다', 코멘트달린줄들(코멘트붙인글(코멘트먼저, '어떤 법안', '③', '', 오늘), '어떤 법안').length === 0);
// 제11조 ③ — 설계실 답 //
확인('설계실 파일의 답은 추가·변경·제거·취소다', 답들('docs/설계실.md').join() === '추가,변경,제거,취소' && 답들('assembly.md').join() === '신설,변경,제거,취소');
확인('설계실 설계안에 추가를 찍는다', 찍힌표시(표시붙인글(설계안, '어떤 설계', '추가', 오늘, '설계실.md'), '어떤 설계') === '추가');
확인('설계실 파일에는 의회 답 「신설」을 못 찍는다', 던지나(() => 표시붙인글(설계안, '어떤 설계', '신설', 오늘, '설계실.md')).includes('찍을 수 없는 답'));
const 설계코멘트 = 줄들(코멘트붙인글(설계안, '어떤 설계', '①', '반경을 넓히자', 오늘));
확인('설계안 항 코멘트는 구현 계획 묶음 앞에 달린다', 설계코멘트.indexOf(`> 💬 **①** | ${오늘} | 반경을 넓히자`) < 설계코멘트.indexOf('**구현 계획 초안**'));
// 작업 목록의 표시(✅❓❌)도 같은 부품으로 찍는다 — PC 앱 문서 목록이 쓴다 //
const 작업 = ['# 작업', '', '## [작업 1] | 어떤 일 | 작업 | 2026-09-29', '', '본문', ''].join('\n');
확인('작업 목록에는 체크를 찍고, 함께 적은 한마디가 줄 끝에 붙는다',
  표시붙인글(작업, '[작업 1]', '체크', 오늘, 'work.md', '이어서\n하자').includes(`> 📌 ${표시글.체크} | ${오늘} | 이어서 하자`));
확인('작업 목록에는 의회 답 「신설」을 못 찍는다', 던지나(() => 표시붙인글(작업, '[작업 1]', '신설', 오늘, 'work.md')).includes('찍을 수 없는 답'));
// 못 찾으면 던진다 //
확인('없는 항목이면 던진다', 던지나(() => 표시붙인글(법안, '없는 법안', '신설', 오늘)).includes('못 찾았다'));
확인('없는 항이면 던진다', 던지나(() => 코멘트붙인글(법안, '어떤 법안', '⑨', '말', 오늘)).includes('못 찾았다'));
// 줄끝이 섞인 문서에서 찍은 줄 말고는 글자 하나 안 바뀐다 //
const 섞인 = 법안.replace('① 있는 항이다.\n', '① 있는 항이다.\r\n');
const 찍힌섞인 = 표시붙인글(섞인, '어떤 법안', '신설', 오늘);
확인('줄끝이 섞인 문서도 찍은 두 줄 말고는 그대로다', 찍힌섞인.replace(`\n> 📌 ${표시글.신설} | ${오늘}\n`, '') === 섞인);

console.log(실패.length ? `[doc-mark 시험] ERROR 통과 ${통과} · 실패 ${실패.length} — ${실패.join(' · ')}` : `[doc-mark 시험] SUCCESS ${통과}건 통과`);
process.exit(실패.length ? 1 : 0);
