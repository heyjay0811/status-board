// 답·코멘트를 문서에 적는 공통 부품 `doc-mark.mjs`의 시험 — 실제 글을 넣어 결과 글로 확인한다. //
// 따르는 설계: bp-결재의 「의회·설계실 화면은 법안과 설계안마다 `승인`·`취소` 두 답을 찍고, 제목 줄과 항마다 코멘트 칸을 둔다」 조 — //
//   답은 승인·취소 둘이고 의회 파일과 설계실 파일이 같다 · 답 줄은 「> 📌 **승인** | 날짜」 · 옛 신설·변경·제거·추가 답 줄은 승인으로 읽는다. //
import { 표시붙인글, 코멘트붙인글, 찍힌표시, 코멘트달린줄들, 표시글, 답들, 안답들 } from './doc-mark.mjs';

const 법안 = [
  '# 의회', '', '## 어떤 법안 | #규칙 | 소속: 전역 규칙 · 제1조 변경', '',
  '조 제목: 어떤 조', '① 있는 항이다.', '- 목록 하나', '- 목록 둘', '③ 새 항이다.', '', '---', '',
  '## 제거 — 옛 절 | #규칙 | 소속: 일톡 규칙', '', '① 원문: 「옛 글」', '왜 지우나: 공통에 있다.', '② 원문: 「옛 글 둘」', '왜 지우나: 없다.', '', '---', '',
].join('\n');
const 설계안 = [
  '# 설계실', '', '## 어떤 설계 | #설계 | 갈 곳: `bp-업장` | 제1조 신설', '',
  '① 첫 항이다.', '', '**구현 계획 초안**', '- 바꿀 파일: 없음', '', '---', '',
].join('\n');
const 오늘 = '2026-10-06';
let 통과 = 0; const 실패 = [];
const 확인 = (이름, 조건, 덧 = '') => { if (조건) { 통과++; console.log(`  ✓ ${이름}`); } else { 실패.push(이름); console.log(`  ✗ ${이름}${덧 ? ' — ' + 덧 : ''}`); } };
const 던지나 = (fn) => { try { fn(); return ''; } catch (e) { console.log(`    (막힘: ${e.message})`); return e.message; } };
const 줄들 = (t) => t.split('\n');

console.log('[doc-mark 시험] START');
// ②④ — 답 둘, 답 줄 모양 //
확인('의회·설계실 답은 승인·취소 둘이고 두 파일이 같다', 안답들.join() === '승인,취소' && 답들('docs/assembly.md').join() === '승인,취소' && 답들('docs/설계실.md').join() === '승인,취소', `${답들('assembly.md')} / ${답들('설계실.md')}`);
for (const 답 of ['승인', '취소']) {
  const 새글 = 표시붙인글(법안, '어떤 법안', 답, 오늘);
  확인(`의회 법안에 ${답}을 찍으면 제목 아래에 「> 📌 **${답}** | 날짜」가 붙는다`, 줄들(새글)[4] === `> 📌 **${답}** | ${오늘}`, 줄들(새글)[4]);
  const 설계글 = 표시붙인글(설계안, '어떤 설계', 답, 오늘, 'docs/설계실.md');
  확인(`설계실 설계안에도 같은 모양으로 ${답}이 붙는다`, 줄들(설계글)[4] === `> 📌 **${답}** | ${오늘}`, 줄들(설계글)[4]);
}
for (const 옛답 of ['신설', '변경', '제거', '추가', '유지']) {
  확인(`옛 답 「${옛답}」은 의회 파일에 새로 못 찍는다`, 던지나(() => 표시붙인글(법안, '어떤 법안', 옛답, 오늘)).includes('찍을 수 없는 답'));
}
확인('옛 답 「추가」는 설계실 파일에도 새로 못 찍는다', 던지나(() => 표시붙인글(설계안, '어떤 설계', '추가', 오늘, '설계실.md')).includes('찍을 수 없는 답'));
// 옛 답 줄 읽기 — 신설·변경·제거·추가는 승인, 옛 🚫 취소는 취소 //
const 옛줄 = (글자) => 법안.replace('## 어떤 법안 | #규칙 | 소속: 전역 규칙 · 제1조 변경\n', `## 어떤 법안 | #규칙 | 소속: 전역 규칙 · 제1조 변경\n\n> 📌 ${글자} | 2026-10-05\n`);
for (const [글자, 읽음] of [['🆕 **신설**', '승인'], ['✏️ **변경**', '승인'], ['🗑️ **제거**', '승인'], ['🆕 **추가**', '승인'], ['🚫 **취소**', '취소'], ['🔒 **유지**', '유지']]) {
  확인(`옛 답 줄 「${글자}」은 ${읽음}으로 읽는다`, 찍힌표시(옛줄(글자), '어떤 법안') === 읽음, 찍힌표시(옛줄(글자), '어떤 법안'));
}
확인('옛 답 줄 위에 승인을 찍으면 옛 줄을 걷고 새 줄 하나만 남는다', (() => { const g = 표시붙인글(옛줄('✏️ **변경**'), '어떤 법안', '승인', 오늘); return g.split('📌').length === 2 && g.includes(`> 📌 **승인** | ${오늘}`) && !g.includes('✏️'); })());
// 거두기 — 찍힌 단추를 다시 누르면 빈 답이 온다 //
확인('빈 답이면 찍힌 답을 걷는다', !표시붙인글(표시붙인글(법안, '어떤 법안', '승인', 오늘), '어떤 법안', '', 오늘).includes('📌'));
확인('다시 찍으면 답은 하나로 남는다', 표시붙인글(표시붙인글(법안, '어떤 법안', '승인', 오늘), '어떤 법안', '취소', 오늘).split('📌').length === 2);
// ③ — 제거 안도 항마다가 아니라 안에 답 하나 //
const 제거찍힘 = 표시붙인글(법안, '제거 — 옛 절', '승인', 오늘);
확인('제거 안에도 제목 아래에 답 하나를 찍는다', 찍힌표시(제거찍힘, '제거 — 옛 절') === '승인');
확인('제거 안에 찍어도 앞 법안의 답은 그대로 비어 있다', 찍힌표시(제거찍힘, '어떤 법안') === '');
// ⑥ — 코멘트는 어느 답에나 딸리고, 코멘트를 달아도 답은 그대로 //
for (const 답 of ['승인', '취소']) {
  const 달림 = 코멘트붙인글(표시붙인글(법안, '어떤 법안', 답, 오늘), '어떤 법안', '①', '이 말은 빼자', 오늘);
  확인(`${답}이 찍힌 법안에 코멘트를 달아도 ${답}은 그대로다`, 찍힌표시(달림, '어떤 법안') === 답);
}
const 코멘트먼저 = 코멘트붙인글(법안, '어떤 법안', '③', '물어볼 게 있다', 오늘);
확인('코멘트가 달린 법안에도 승인을 찍을 수 있다', 찍힌표시(표시붙인글(코멘트먼저, '어떤 법안', '승인', 오늘), '어떤 법안') === '승인');
확인('답 없이 단 코멘트도 남는다(물음)', 코멘트달린줄들(코멘트먼저, '어떤 법안').length === 1 && 찍힌표시(코멘트먼저, '어떤 법안') === '');
const 목록코멘트 = 줄들(코멘트붙인글(법안, '어떤 법안', '①', '목록 뒤에', 오늘));
확인('항 아래 목록이 있으면 코멘트는 목록 끝에 달린다', 목록코멘트[목록코멘트.indexOf('- 목록 둘') + 2] === `> 💬 **①** | ${오늘} | 목록 뒤에`, 목록코멘트.slice(5, 11).join(' / '));
확인('제거 안의 항에도 코멘트를 단다', 코멘트달린줄들(코멘트붙인글(법안, '제거 — 옛 절', '②', '이건 남기자', 오늘), '제거 — 옛 절').length === 1);
확인('빈 코멘트는 그 줄 코멘트를 걷는다', 코멘트달린줄들(코멘트붙인글(코멘트먼저, '어떤 법안', '③', '', 오늘), '어떤 법안').length === 0);
const 설계코멘트 = 줄들(코멘트붙인글(설계안, '어떤 설계', '①', '반경을 넓히자', 오늘));
확인('설계안 항 코멘트는 구현 계획 묶음 앞에 달린다', 설계코멘트.indexOf(`> 💬 **①** | ${오늘} | 반경을 넓히자`) < 설계코멘트.indexOf('**구현 계획 초안**'));
// 작업 목록의 표시(✅❓❌)도 같은 부품으로 찍는다 — PC 앱 문서 목록이 쓴다 //
const 작업 = ['# 작업', '', '## [작업 1] | 어떤 일 | 작업 | 2026-09-29', '', '본문', ''].join('\n');
확인('작업 목록에는 체크를 찍고, 함께 적은 한마디가 줄 끝에 붙는다',
  표시붙인글(작업, '[작업 1]', '체크', 오늘, 'work.md', '이어서\n하자').includes(`> 📌 ${표시글.체크} | ${오늘} | 이어서 하자`));
확인('작업 목록에는 답 「승인」을 못 찍는다', 던지나(() => 표시붙인글(작업, '[작업 1]', '승인', 오늘, 'work.md')).includes('찍을 수 없는 답'));
// 못 찾으면 던진다 //
확인('없는 항목이면 던진다', 던지나(() => 표시붙인글(법안, '없는 법안', '승인', 오늘)).includes('못 찾았다'));
확인('없는 항이면 던진다', 던지나(() => 코멘트붙인글(법안, '어떤 법안', '⑨', '말', 오늘)).includes('못 찾았다'));
// 줄끝이 섞인 문서에서 찍은 줄 말고는 글자 하나 안 바뀐다 //
const 섞인 = 법안.replace('① 있는 항이다.\n', '① 있는 항이다.\r\n');
const 찍힌섞인 = 표시붙인글(섞인, '어떤 법안', '승인', 오늘);
확인('줄끝이 섞인 문서도 찍은 두 줄 말고는 그대로다', 찍힌섞인.replace(`\n> 📌 ${표시글.승인} | ${오늘}\n`, '') === 섞인);

console.log(실패.length ? `[doc-mark 시험] ERROR 통과 ${통과} · 실패 ${실패.length} — ${실패.join(' · ')}` : `[doc-mark 시험] SUCCESS ${통과}건 통과`);
process.exit(실패.length ? 1 : 0);
